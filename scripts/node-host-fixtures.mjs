// Reuse the existing owned fixture closure; do not duplicate semantic oracles.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {packageImports} from './portable-core.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = readFileSync(join(root,'src/workers_conformance/fixture.generated.mbt'),'utf8');
const aliases = new Set([...source.matchAll(/@(\w+)/g)].map(x => x[1]));
const imports = packageImports(readFileSync(join(root,'src/query_integration/moon.pkg'),'utf8'))
  .filter(x => aliases.has(x.alias)).map(x => [x.path,x.alias]);
imports.push(['actql/actql/connectors_builtin','builtin'],['actql/actql/connector_conformance','conformance']);
imports.push(
  ['actql/actql/physical_host', 'host_driver'],
  ['actql/actql/local_tea_provider', 'tea_provider'],
  ['actql/actql/managed_record_storage', 'record_storage'],
);
let manifest = '// Generated by scripts/node-host-fixtures.mjs.\n' +
  'supported_targets = "js"\n\npkgtype(kind: "foreign_library")\n\nimport {\n' +
  imports.map(([path,alias]) => `  "${path}" @${alias},\n`).join('') + '}\n';
manifest = execFileSync(join(process.env.MOON_HOME,'bin/moonfmt'),['-','-file-type','pkg'],{input:manifest,encoding:'utf8'});
const directory = join(root,'src/node_host_conformance');
for (const [file, text] of [['fixture.generated.mbt',source],['moon.pkg',manifest]]) {
  const path = join(directory,file);
  if (process.argv.includes('--write')) { mkdirSync(directory,{recursive:true}); writeFileSync(path,text); }
  else if (readFileSync(path,'utf8') !== text) throw new Error(`Stale Node Host fixture: ${file}`);
}
