import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalText} from './check-canonical-json.mjs';
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const corpus=read('portability/corpus/carrier-schemas.json');
assert.equal(corpus.version,'actql-carrier-schema-vectors/0.1');
const lines=['// Generated by scripts/check-carrier-schemas.mjs; do not edit.'];
const seen=new Set();
for(const c of corpus.cases){
  assert.ok(!seen.has(c.id));seen.add(c.id);
  assert.ok(['relation','graph','events','vectors'].includes(c.carrier));
  assert.equal(typeof c.accepted,'boolean');
  const wire=canonicalText(c.body);
  // Independent canonical-byte oracle plus Node SHA-256, never product output.
  const cid='sha256:'+createHash('sha256').update(wire,'utf8').digest('hex');
  lines.push('', '///|',`test ${JSON.stringify('Carrier schema corpus: '+c.id)} {`,
    `  let modes = carrier_modes(@json.parse(${JSON.stringify(wire)}), ${JSON.stringify(c.carrier)})`,
    '  let result = check_carrier_schemas(modes, carrier_limits())',
    `  assert_eq(result is Ok(_), ${c.accepted})`);
  if(c.accepted)lines.push(`  assert_eq(carrier_schema_body_cid(carrier_schema_at(result.unwrap(), 0).unwrap()), ${JSON.stringify(cid)})`);
  lines.push('}');
}
const path='src/check_environment/carrier_vectors.generated_test.mbt',text=lines.join('\n')+'\n';
if(process.argv.includes('--write'))writeFileSync(path,text);
assert.equal(readFileSync(path,'utf8'),text);
console.log(`${seen.size} fixed Carrier schema outcomes and independent body preimages verified.`);
