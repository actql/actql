import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const quote = s => '"' + [...s].map(c => {
  const n = c.codePointAt(0);
  return n < 32 || n > 126 ? '\\u{' + n.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const issues = new Set(['Decode','InvalidBody','DuplicateField','UnknownField','UnknownSource','InvalidOrder','NotAuthorOrderable','InvalidMetadata']);
export function generate(c) {
  assert.equal(c.version, 'actql-relation-results-corpus/0.1');
  assert.ok(Array.isArray(c.cases) && c.cases.length);
  const names = new Set(), out = ['// Generated by scripts/check-relation-results.mjs --write. Do not edit.'];
  for (const v of c.cases) {
    assert.ok(typeof v.id === 'string' && v.id && !names.has(v.id)); names.add(v.id);
    assert.ok(v.body && typeof v.body === 'object');
    const args = [quote(JSON.stringify(v.body))];
    if (v.issue !== undefined) {
      assert.ok(issues.has(v.issue)); assert.equal(v.target, undefined); args.push(quote(v.issue));
    } else {
      assert.match(v.target,/^(input|step):[0-9]+$/);
      assert.ok(Array.isArray(v.fields) && v.fields.length && v.fields.every(x => typeof x === 'string'));
      if (v.order !== undefined) {
        assert.ok(Array.isArray(v.order) && v.order.length);
        for (const o of v.order) assert.ok(o.length === 4 && typeof o[0] === 'string' && ['asc','desc'].includes(o[1]) && ['first','last'].includes(o[2]) && typeof o[3] === 'boolean');
      }
      args.push(quote(v.target), '['+v.fields.map(quote).join(',')+']', v.order === undefined ? 'None' : 'Some('+quote(JSON.stringify(v.order))+')');
    }
    out.push('', '///|', `test ${quote('Result corpus: '+v.id)} {`, `  corpus_${v.issue === undefined ? 'accepted' : 'rejected'}(${args.join(', ')})`, '}');
  }
  return out.join('\n')+'\n';
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = JSON.parse(readFileSync('portability/corpus/actql-relation-results-v0.1.json','utf8'));
  const text = generate(c), path = 'src/relation_results/corpus.generated_test.mbt';
  if (process.argv.includes('--write')) writeFileSync(path,text);
  else assert.equal(readFileSync(path,'utf8'),text,'stale Result corpus tests');
  console.log(`${c.cases.length} fixed Result type/projection cases; publication order remains pending.`);
}
