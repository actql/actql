import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export function generate(corpus) {
  assert.equal(corpus.version, 'actql-relation-nest-corpus/0.1');
  assert.ok(corpus.cases.length);
  const fields = names => Object.fromEntries(Object.entries(names).map(([name, type]) => {
    assert.ok(Object.hasOwn(corpus.types, type), 'unknown type');
    return [name, corpus.types[type]];
  }));
  const literal = value => JSON.stringify(JSON.stringify(value));
  const lines = ['// Generated by scripts/check-relation-nest.mjs --write. Do not edit.'];
  const seen = new Set();
  for (const [i, c] of corpus.cases.entries()) {
    assert.ok(c.body && c.parent && c.child);
    const key = JSON.stringify([c.body,c.parent,c.child]);
    assert.ok(!seen.has(key), 'duplicate case'); seen.add(key);
    assert.notEqual(Object.hasOwn(c, 'output'), Object.hasOwn(c, 'issue'), 'exactly one expectation required');
    const args = [literal(c.body), literal(fields(c.parent)), literal(fields(c.child))];
    if (Object.hasOwn(c, 'output')) args.push(`Some(${literal(fields(c.output))})`, 'None');
    else {
      assert.ok(['InvalidBody','EmptyBody','InvalidName','UnknownField','IncomparableKeys','DuplicateOutput','InputCollision','NotConstructible','InvalidOrder','NotAuthorOrderable','InvalidGuard','UnknownParameter'].includes(c.issue));
      args.push('None', `Some(${JSON.stringify(c.issue)})`);
    }
    lines.push('', '///|', `test "nest type corpus ${i + 1}" {`, `  corpus_case(${args.join(', ')})`, '}');
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const corpus = JSON.parse(readFileSync('portability/corpus/actql-relation-nest-v0.1.json', 'utf8'));
  const generated = generate(corpus);
  const path = 'src/relation_nest/corpus.generated_test.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, generated);
  else assert.equal(readFileSync(path, 'utf8'), generated, 'stale nest tests');
  console.log(`${corpus.cases.length} fixed nest type cases; not execution or proof conformance.`);
}
