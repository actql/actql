import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {machineCid} from './actql-spec-family.mjs';

const corpus=JSON.parse(readFileSync('portability/corpus/ordered-derive.json','utf8'));
assert.equal(corpus.version,'actql-ordered-derive-vectors/0.1');
const lines=['// Generated by scripts/check-ordered-derive-preimages.mjs --write. Do not edit.'];
for (const c of corpus.preimages) {
  assert.deepEqual(JSON.parse(c.canonical), c.body);
  assert.equal('sha256:'+createHash('sha256').update(c.canonical).digest('hex'), c.cid);
  assert.equal(machineCid(c.body), c.cid);
  lines.push('', '///|', `test ${JSON.stringify('ordered derive '+c.id)} {`,
    `  let value = @canonical_json.from_json(@json.parse(${JSON.stringify(c.canonical)}), 1000, 100, 100000)`,
    `  assert_eq(@canonical_json.stringify_value(value, 100000, 1000, 100), ${JSON.stringify(c.canonical)})`,
    `  assert_eq(@canonical_json.cid_value(value, 100000, 1000, 100), ${JSON.stringify(c.cid)})`, '}');
}
const path='src/canonical_json/ordered_derive_preimages.generated_test.mbt';
const text=lines.join('\n')+'\n';
if (process.argv.includes('--write')) writeFileSync(path,text);
else assert.equal(readFileSync(path,'utf8'),text);
console.log(`${corpus.preimages.length} ordered derive preimages verified; not execution evidence.`);
