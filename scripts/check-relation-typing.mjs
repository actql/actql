import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const operations = { top_k: 'TopK', top_k_by: 'TopKBy', analytic: 'Analytic', pivot: 'Pivot', group: 'Group', derive: 'Derive', filter: 'Filter', select: 'Select', rename: 'Rename', drop: 'Drop', sort: 'Sort', take: 'Take', distinct: 'Distinct', dedupe_rows: 'DedupeRows', json_pick: 'JsonPick', unnest: 'Unnest', assert_rows: 'AssertRows', unpivot: 'Unpivot' };
const issues = ['InvalidFrame', 'InvalidFill', 'FillValue', 'InvalidAggregate', 'InvalidAggregateArgument', 'InvalidAggregateOption', 'ForbiddenAggregateValue', 'ExpectedBoolean', 'UnknownField', 'NullTypeUnresolved', 'EmptyBody', 'InvalidBody', 'InputCollision', 'DuplicateOutput', 'InvalidName', 'InvalidOrder', 'NotAuthorOrderable', 'NotKeyComparable', 'InvalidCount', 'UnknownParameter', 'ExpectedObject', 'ExpectedArray', 'ShapeEvidenceRequired', 'IncompatibleColumn'];

export function generate(corpus) {
  assert.equal(corpus.version, 'actql-relation-typing-corpus/0.1');
  assert.ok(corpus.accepted.length && corpus.rejected.length);
  const fields = names => Object.fromEntries(Object.entries(names).map(([name, type]) => {
    assert.ok(Object.hasOwn(corpus.types, type), 'missing expected type');
    return [name, corpus.types[type]];
  }));
  const lines = ['// Generated by scripts/check-relation-typing.mjs --write. Do not edit.'];
  const seen = new Set();
  for (const group of ['accepted', 'rejected']) for (const [index, entry] of corpus[group].entries()) {
    assert.ok(Object.hasOwn(operations, entry.operation), 'unknown operation');
    assert.ok(Object.hasOwn(entry, 'body'), 'missing body');
    const key = JSON.stringify([entry.operation, entry.body, entry.input ?? corpus.input]);
    assert.ok(!seen.has(key), 'duplicate case'); seen.add(key);
    const args = [operations[entry.operation], literal(JSON.stringify(entry.body)), literal(JSON.stringify(fields(entry.input ?? corpus.input)))];
    if (group === 'accepted') {
      assert.ok(entry.output && typeof entry.output === 'object', 'missing output');
      args.push(literal(JSON.stringify(fields(entry.output))));
      assert.ok(entry.order === undefined || (Array.isArray(entry.order) && entry.order.every(n => typeof n === 'string')));
      args.push(entry.order ? 'Some([' + entry.order.map(literal).join(',') + '])' : 'None');
    } else {
      assert.ok(issues.includes(entry.issue), 'unknown issue'); args.push(literal(entry.issue));
    }
    lines.push('', '///|', `test "relation type corpus ${group}: ${index + 1}" {`,
      `  corpus_${group}(${args.join(', ')})`, '}');
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const corpus = JSON.parse(readFileSync('portability/corpus/actql-relation-typing-v0.1.json', 'utf8'));
  const text = generate(corpus);
  const path = 'src/relation_typing/corpus.generated_test.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, text);
  else assert.equal(readFileSync(path, 'utf8'), text, 'stale relation type tests');
  console.log(`${corpus.accepted.length} accepted and ${corpus.rejected.length} rejected relation type vectors; not runtime conformance.`);
}
