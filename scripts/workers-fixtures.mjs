// Reuse owned, filesystem-free fixture builders, not a second checker/planner.
// Only helper declarations reachable from these roots are projected. Expected
// outputs live separately in Node/workerd tests and are never generated here.
import {readFileSync, readdirSync, mkdirSync, writeFileSync, existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {packageImports} from './portable-core.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const bridgeBinding = (manifest, path) => {
  const escaped = path.replaceAll(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`"${escaped}"\\s+@(\\w+)`).exec(manifest)?.[1];
};
const directory = join(root, 'src/query_integration');
const functions = new Map();
for (const file of readdirSync(directory).filter(x => x.endsWith('.mbt')).sort()) {
  for (const block of readFileSync(join(directory, file), 'utf8').split('///|')) {
    const match = /^\s*(?:(?:\/\/[^\n]*\n)*)\s*fn (\w+)\b/.exec(block);
    if (match) {
      if (functions.has(match[1])) throw new Error(`Duplicate fixture helper: ${match[1]}`);
      functions.set(match[1], {file, block});
    }
  }
}
const pending = ['captured_graph_fixture', 'dispatch_test_generated'];
const selected = new Set();
while (pending.length) {
  const name = pending.pop();
  if (selected.has(name)) continue;
  const item = functions.get(name);
  if (!item) throw new Error(`Missing fixture helper: ${name}`);
  selected.add(name);
  for (const candidate of functions.keys()) {
    if (new RegExp('(?<![@.\\w])' + candidate + '\\s*\\(').test(item.block)) pending.push(candidate);
  }
}
let source = '// Generated by scripts/workers-fixtures.mjs; test data/preparation only.\n';
for (const name of [...selected].sort()) {
  const item = functions.get(name);
  source += '\n///|\n/// Fixture owner: query_integration/' + item.file + '\n' + item.block.trim() + '\n';
}
const aliases = new Set([...source.matchAll(/@(\w+)/g)].map(x => x[1]));
const imports = packageImports(readFileSync(join(directory, 'moon.pkg'), 'utf8'))
  .filter(x => aliases.has(x.alias));
for (const entry of imports) {
  if (/duckdb|_node|connectors_builtin/.test(entry.path)) throw new Error(`Nonportable fixture dependency: ${entry.path}`);
}
if (imports.length !== aliases.size) throw new Error('Unresolved fixture import');
const extra = [
  ['actql/actql/connectors_workers','builtin'],
  ['actql/actql/physical_host','host_driver'],
  ['actql/actql/connector_sdk','connector'],
  ['actql/actql/run_publication','publication'],
  ['actql/actql/execution_site','site'],
  ['actql/actql/remote_site_protocol','remote'],
  ['actql/actql/physical_manifest','manifest'],
  ['actql/actql/remote_transfer','transfer'],
  ['actql/actql/remote_credential','credential'],
  ['actql/actql/remote_bundle','bundle'],
  ['actql/actql/connectors_workers_async','probe'],
  ['actql/actql/connectors/reference_compute/driver','numeric_driver'],
  ['actql/actql/connectors/local/driver','local_driver'],
];
let manifest = '// Generated by scripts/workers-fixtures.mjs.\n' +
  'supported_targets = "js"\n\npkgtype(kind: "foreign_library")\n\nimport {\n' +
  [...imports.map(x => [x.path,x.alias]), ...extra].map(([path,alias]) => `  "${path}" @${alias},\n`).join('') + '}\n';
// Link preparation and both ordinary generated Host bridges into the same
// compilation unit. MoonBit extensible Error tags are link-unit local: passing
// them between separately linked runtimes is not a portable ABI.
const localBridgeDirectory = join(root, 'src/connectors_workers_bridge');
const localBinding = bridgeBinding(
  readFileSync(join(localBridgeDirectory, 'moon.pkg'), 'utf8'),
  'actql/actql/connectors/local/driver',
);
if (localBinding === undefined) throw new Error('Missing Local bridge binding');
const localBridge = readFileSync(
  join(localBridgeDirectory, 'bridge.generated.mbt'), 'utf8',
).replaceAll(`@${localBinding}`, '@local_driver');
const asyncBridgeDirectory = join(root, 'src/connectors_workers_async_bridge');
const asyncBinding = bridgeBinding(
  readFileSync(join(asyncBridgeDirectory, 'moon.pkg'), 'utf8'),
  'actql/actql/connectors/reference_compute/driver',
);
if (asyncBinding === undefined) {
  throw new Error('Missing numeric bridge binding');
}
const asyncBridge = readFileSync(
  join(asyncBridgeDirectory, 'bridge.generated.mbt'), 'utf8',
);
const asyncProjection = asyncBridge
  .replaceAll('@builtin','@probe')
  .replaceAll(`@${asyncBinding}`, '@numeric_driver')
  .replaceAll('NodeHostFailure','AsyncHostFailure')
  .replaceAll('StrategyHost','AsyncStrategyHost')
  .replaceAll('physical_manifest_', 'async_physical_manifest_')
  .replaceAll(
    'physical_representation_contracts',
    'async_physical_representation_contracts',
  )
  .replaceAll(
    '#export_name("physical',
    '#export_name("asyncPhysical',
  )
  .replaceAll('@strategy.strategy_','@strategy.__owned_strategy_')
  .replaceAll('strategy_','async_strategy_')
  .replaceAll('@strategy.__owned_async_strategy_','@strategy.strategy_')
  .replaceAll(
    '#export_name("strategy',
    '#export_name("asyncStrategy',
  );
const bridges = localBridge + '\n' + asyncProjection;
const formatter = join(process.env.MOON_HOME, 'bin/moonfmt');
source = execFileSync(formatter, ['-'], {input:source, encoding:'utf8'});
manifest = execFileSync(formatter, ['-', '-file-type', 'pkg'], {input:manifest, encoding:'utf8'});
const output = join(root,'src/workers_conformance');
for (const [file,text] of [['fixture.generated.mbt',source],['moon.pkg',manifest],
  ['host.generated.mbt',execFileSync(formatter,['-'],{input:bridges,encoding:'utf8'})]]) {
  const path = join(output,file);
  if (process.argv.includes('--write')) { mkdirSync(output,{recursive:true}); writeFileSync(path,text); }
  else if (!existsSync(path) || readFileSync(path,'utf8') !== text) throw new Error(`Stale Workers fixture: ${file}`);
}
console.log(`${selected.size} existing fixture helpers projected without concrete Node dependencies.`);
