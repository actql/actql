import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalText,verifyIdentity} from './check-canonical-json.mjs';

const path = 'portability/corpus/rel-values-execution.json';
const corpus = JSON.parse(readFileSync(path,'utf8'));
assert.equal(corpus.version,'actql-rel-values-execution-vectors/0.1');
// Explicit maintenance command uses the independent Node canonical oracle,
// never product lowering or product identity output. Normal CI only checks.
if (process.argv.includes('--write-identities')) {
  for (const c of corpus.cases.filter(c => c.schema_valid && c.rows_valid.every(Boolean))) {
    c.expected_canonical_json = canonicalText(c.params);
    c.expected_cid = 'sha256:' + createHash('sha256').update(c.expected_canonical_json).digest('hex');
  }
  writeFileSync(path,JSON.stringify(corpus,null,2)+'\n');
}
const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const lines = ['// Generated by scripts/check-values-execution.mjs --write. Do not edit.'];
const identities = ['// Generated by scripts/check-values-execution.mjs --write. Do not edit.'];
const ids = new Set();
for (const c of corpus.cases) {
  assert.ok(c.id && !ids.has(c.id)); ids.add(c.id);
  assert.equal(typeof c.schema_valid,'boolean');
  if (!c.schema_valid) continue;
  assert.equal(c.rows_valid.length,c.params.rows.length);
  const contract = {type:'object',nullable:false,additional_properties:false,fields:c.params.schema};
  lines.push('', '///|', `test ${literal('REL.values wire admission: '+c.id)} {`,
    `  let c = @contract.read_checked(owned(parsed(${literal(JSON.stringify(contract))})), { max_nodes: 10000, max_depth: 100, max_text_bytes: 100000 }).unwrap()`);
  for (const [i,row] of c.params.rows.entries()) {
    assert.equal(typeof c.rows_valid[i],'boolean');
    lines.push(`  assert_eq(@value_admission.admit(c, owned(parsed(${literal(JSON.stringify(row))})), limits()) is Ok(_), ${c.rows_valid[i]})`);
  }
  if (!c.params.rows.length) lines.push('  assert_true(@contract.type_equal(c, c, 10000))');
  lines.push('}');
  if (c.rows_valid.every(Boolean)) {
    verifyIdentity(c.params,c.expected_cid,c.expected_canonical_json);
    identities.push('', '///|', `test ${literal('REL.values params identity: '+c.id)} {`,
      `  let json = @json.parse(${literal(JSON.stringify(c.params))})`,
      '  let value = @canonical_json.from_json(json, 10000, 100, 100000)',
      `  assert_eq(@canonical_json.stringify_value(value, 100000, 10000, 100), ${literal(c.expected_canonical_json)})`,
      `  assert_eq(@canonical_json.cid_value(value, 100000, 10000, 100), ${literal(c.expected_cid)})`, '}');
  }
}
for (const [file,body] of [
  ['src/value_admission/values_execution.generated_test.mbt',lines],
  ['src/canonical_json/values_execution.generated_test.mbt',identities],
]) {
  const text = body.join('\n')+'\n';
  if (process.argv.includes('--write')) writeFileSync(file,text);
  else assert.equal(readFileSync(file,'utf8'),text,'stale execution fixture tests: '+file);
}
console.log(`${ids.size} REL.values fixed vectors; schema/value/identity evidence, not executor conformance.`);
