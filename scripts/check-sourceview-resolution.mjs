import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalText} from './check-canonical-json.mjs';

const corpus=JSON.parse(readFileSync('portability/corpus/sourceview-resolution.json','utf8'));
const keyed=JSON.parse(readFileSync('portability/corpus/sourceview-keyed-requests.json','utf8'));
const carrierCases=JSON.parse(readFileSync('portability/corpus/carrier-schemas.json','utf8')).cases;
assert.equal(corpus.version,'actql-sourceview-resolution-vectors/0.1');
const cid=v=>'sha256:'+createHash('sha256').update(canonicalText(v),'utf8').digest('hex');
const seal=(v,key)=>({...v,[key]:cid(v)});
const compare=(a,b)=>a<b?-1:a>b?1:0;
const bySelf=key=>(a,b)=>compare(a[key],b[key]);
const byBody=(a,b)=>compare(cid(a),cid(b));
const lines=['// Generated by scripts/check-sourceview-resolution.mjs; do not edit.'];
const seen=new Set();
let integrationFixture;
for(const c of [...corpus.cases,...keyed.cases.map(c=>({...keyed.defaults,...c}))]){
  assert.ok(!seen.has(c.id));seen.add(c.id);
  assert.ok(!c.error||['Ambiguous','DuplicateSelector','InvalidSourceReference','Unresolved'].includes(c.error));
  if(c.request_outcome)assert.ok(!c.error&&['accepted','UnknownField','MissingField','Literal','IncompatibleParameter','IncompatibleBinding'].includes(c.request_outcome));
  if(c.direct_mode){
    assert.ok(!c.error);
    assert.ok(['snapshot','changes','watch','undeclared_snapshot','undeclared_changes'].includes(c.direct_mode));
  }
  const contracts=[],views=[],refs=new Map();
  const factsBody=c.lookup_capacity?{lookup_capacity:c.lookup_capacity}:{};
  function contract(kind,body){
    const key=kind+canonicalText(body);
    if(refs.has(key))return refs.get(key);
    const v=seal({schema:'actql.contract/0.1',id:`fixture-${contracts.length}`,version:'fixture',kind,body},'cid');
    contracts.push(v);
    const ref={id:v.id,version:v.version,cid:v.cid};refs.set(key,ref);return ref;
  }
  for(const v of c.views){
    const fields=c.request_fields??(v.required_field?{id:{type:'number',nullable:false}}:{});
    const request=contract('request_schema',{type:'object',nullable:false,additional_properties:false,fields});
    const output=c.output_fixture?carrierCases.find(x=>x.id===c.output_fixture):null;
    if(c.output_fixture)assert.ok(output?.accepted);
    const row=contract('carrier_schema',output?.body??{type:'object',nullable:false,additional_properties:false,fields:c.output_fields??{}});
    const policy=contract('data_policy',{version:'actql-source-data-policy/0.1',source_ref:v.source_ref??`connector://crm/main/${v.resource}#${v.name}`,classification:'unknown'});
    const modes=(v.modes??[v.watch?{mode:'watch',bounded:false}:{mode:'snapshot',bounded:true}]).map(({checkpoint_type,expiration_type,...mode})=>{
      if(mode.mode==='snapshot'&&!checkpoint_type)return mode;
      return {...mode,checkpoint:{kind:'opaque',expires:Boolean(expiration_type),value_schema:contract('checkpoint',{type:checkpoint_type??'string',nullable:false}),...(expiration_type?{expiration_schema:contract('checkpoint',{type:expiration_type,nullable:false})}:{})}};
    });
    views.push(seal({schema:'actql.source_view/0.1',connector_id:'crm/main',connector_version:'fixture',resource_kind:v.kind??'record',view_id:v.name,view_version:'fixture',acquisition:{kind:c.correlation?'fetch':'scan',authority:'read_metadata',request_schema:request,modes,default_mode:v.default_mode??modes[0].mode,...(c.correlation?{correlation:c.correlation}:{})},request_processing:{mutates_business_state:false},output:{carrier:output?.carrier??'relation',schema:row,facts:contract('carrier_facts',factsBody),data_policy:policy},pushdown:{contract:contract('pushdown',{}),operations:[]}},'contract_cid'));
  }
  const catalog=seal({schema:'actql.connector_catalog/0.1',connector_id:'crm/main',connector_version:'fixture',contracts:[...contracts].sort(bySelf('cid')),source_views:[...views].sort(bySelf('contract_cid')),commands:[]},'catalog_cid');
  const env=seal({version:'actql-check-environment/0.1',schema_snapshots:[],connector_capabilities:[],mapping_contracts:[],source_views:[...views].sort(byBody),command_contracts:[],model_task_contracts:[],contract_registry:[...contracts].sort(byBody),connector_catalogs:[catalog],host_policy_profile:{}},'evidence_bundle_cid');
  if(c.id==='sole-address-not-kind'){
    const {evidence_bundle_cid,...body}=env;
    integrationFixture=seal({...body,schema_snapshots:[{
      output_carrier:'relation',schema:{type:'object',nullable:false,additional_properties:false,fields:{id:{type:'number',nullable:false}}},
      source_ref:'source:local/first/a',version:'actql-local-input-schema/0.1',
    }]},'evidence_bundle_cid');
  }
  const selectedIndex=c.views.findIndex(v=>v.name===c.selected&&v.resource===c.input.resource.normalize('NFC'));
  let error='None';
  if(c.error==='Ambiguous')error=`Some(Ambiguous(${JSON.stringify(c.candidates)}))`;
  else if(c.error==='DuplicateSelector')error=`Some(DuplicateSelector(${JSON.stringify(c.name)}))`;
  else if(c.error)error=`Some(${c.error})`;
  assert.ok(c.error||selectedIndex>=0);
  lines.push('', '///|',`test ${JSON.stringify('SourceView resolution corpus: '+c.id)} {`,
    `  check_fixture(${JSON.stringify(canonicalText(env))}, ${JSON.stringify(env.evidence_bundle_cid)}, ${JSON.stringify(JSON.stringify(c.input))}, ${error}, ${JSON.stringify(c.selected??'')}, ${JSON.stringify(selectedIndex<0?'':views[selectedIndex].contract_cid)}, ${Boolean(c.input.view)})`, '}');
  if(c.direct_mode){
    const acquisition=views[selectedIndex].acquisition;
    const mode=acquisition.modes.find(m=>m.mode===(c.input.scan?.mode??acquisition.default_mode));
    const checkpoint=mode?.checkpoint?.value_schema?.cid??'';
    lines.push('', '///|',`test ${JSON.stringify('SourceView direct mode corpus: '+c.id)} {`,
      `  check_mode_fixture(${JSON.stringify(canonicalText(env))}, ${JSON.stringify(env.evidence_bundle_cid)}, ${JSON.stringify(JSON.stringify(c.input))}, ${JSON.stringify(c.direct_mode)}, ${c.bounded??false}, ${JSON.stringify(checkpoint)})`, '}');
  }
  if(c.pipeline_uses){
    assert.ok(!c.error);
    lines.push('', '///|',`test ${JSON.stringify('SourceView consumer corpus: '+c.id)} {`,
      `  check_pipeline_uses_fixture(${JSON.stringify(canonicalText(env))}, ${JSON.stringify(env.evidence_bundle_cid)}, ${JSON.stringify(JSON.stringify(c.input))})`, '}');
  }
  if(c.keyed_outcome){
    assert.ok(!c.error&&['accepted','MissingCorrelation','CorrelationField','UnknownField','MissingField','Literal','IncompatibleParameter','IncompatibleBinding'].includes(c.keyed_outcome));
    const declarations=Object.entries({params:c.params,bindings:c.bindings}).filter(([,v])=>v!==undefined).map(([k,v])=>JSON.stringify(k)+':'+JSON.stringify(v)+',').join('');
    lines.push('', '///|',`test ${JSON.stringify('SourceView keyed request corpus: '+c.id)} {`,
      `  check_keyed_request_fixture(${JSON.stringify(canonicalText(env))}, ${JSON.stringify(env.evidence_bundle_cid)}, ${JSON.stringify(JSON.stringify(c.input))}, ${JSON.stringify(declarations)}, ${JSON.stringify(c.keyed_outcome)})`, '}');
  }
  if(c.acquisition_fixture){
    assert.ok(c.correlation);
    lines.push('', '///|',`test ${JSON.stringify('SourceView acquisition corpus: '+c.id)} {`,
      `  check_acquisition_fixture(${JSON.stringify(canonicalText(env))}, ${JSON.stringify(env.evidence_bundle_cid)}, ${c.correlation.request_fields.length}, ${c.lookup_capacity?(c.lookup_capacity.completeness==='complete_per_requested_key'?1:0):-1})`, '}');
  }
  if(c.request_outcome){
    const declarations=Object.entries({params:c.params,bindings:c.bindings}).filter(([,v])=>v!==undefined).map(([k,v])=>JSON.stringify(k)+':'+JSON.stringify(v)+',').join('');
    lines.push('', '///|',`test ${JSON.stringify('SourceView direct request corpus: '+c.id)} {`,
      `  check_request_fixture(${JSON.stringify(canonicalText(env))}, ${JSON.stringify(env.evidence_bundle_cid)}, ${JSON.stringify(JSON.stringify(c.input))}, ${JSON.stringify(declarations)}, ${JSON.stringify(c.request_outcome)})`, '}');
    if(c.request_outcome==='accepted'){
      // Fixed supplied values, not lowerer-derived expectations. Existing numeric
      // fixtures use 7; nonnumeric Parameter cases specify values explicitly.
      const supplied=c.parameter_values??Object.fromEntries(Object.entries(c.params??{}).map(([name,p])=>{assert.equal(p.type,'number');return [name,7];}));
      lines.push('', '///|',`test ${JSON.stringify('SourceView request parameter corpus: '+c.id)} {`,
        `  check_request_parameters_fixture(${JSON.stringify(canonicalText(env))}, ${JSON.stringify(env.evidence_bundle_cid)}, ${JSON.stringify(JSON.stringify(c.input))}, ${JSON.stringify(declarations)}, ${JSON.stringify(JSON.stringify(supplied))})`, '}');
    }
  }
}
const path='src/sourceview_resolution/vectors.generated_test.mbt',text=lines.join('\n')+'\n';
if(process.argv.includes('--write'))writeFileSync(path,text);
assert.equal(readFileSync(path,'utf8'),text);
assert.ok(integrationFixture);
const integrationPath='src/pipeline_check_context/sourceview_fixture.generated_test.mbt';
const integrationText=[
  '// Generated by scripts/check-sourceview-resolution.mjs; do not edit.',
  '///|',
  'fn sourceview_snapshot_fixture() -> (@environment.WireEnvironment, @snapshot.EnvironmentSnapshot) {',
  `  let environment = @environment.read(@utf8.encode(${JSON.stringify(canonicalText(integrationFixture))}), ${JSON.stringify(integrationFixture.evidence_bundle_cid)}, {max_bytes:1000000,max_nodes:100000,max_depth:100,max_members:1000}).unwrap()`,
  '  let snapshot = @snapshot.read_member(@environment.member_at(environment, @environment.SchemaSnapshots, 0).unwrap(), {max_bytes:100000,max_nodes:10000,max_depth:100}).unwrap()',
  '  (environment, snapshot)',
  '}', '',
].join('\n');
if(process.argv.includes('--write'))writeFileSync(integrationPath,integrationText);
assert.equal(readFileSync(integrationPath,'utf8'),integrationText);
console.log(`${seen.size} fixed SourceView resolution/request cases with independently sealed Catalogs verified.`);
