import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const corpus=JSON.parse(readFileSync('portability/corpus/text-extent-preimages.json','utf8'));
assert.equal(corpus.version,'actql-text-extent-preimages/0.1');
const canonical=v=>Array.isArray(v)?`[${v.map(canonical)}]`:v!==null&&typeof v==='object'
  ?`{${Object.keys(v).sort().map(k=>`${JSON.stringify(k)}:${canonical(v[k])}`)}}`:JSON.stringify(v);
const lines=['// Generated by scripts/check-text-extent-preimages.mjs --write. Do not edit.'];
for(const c of corpus.cases){
  assert.equal(canonical(JSON.parse(c.canonical)),c.canonical);
  assert.equal('sha256:'+createHash('sha256').update(c.canonical).digest('hex'),c.cid);
  lines.push('', '///|',`test ${JSON.stringify(c.id)} {`,
    `  let value = @canonical_json.from_json(@json.parse(${JSON.stringify(c.canonical)}), 1000, 100, 100000)`,
    `  assert_eq(@canonical_json.stringify_value(value, 100000, 1000, 100), ${JSON.stringify(c.canonical)})`,
    `  assert_eq(@canonical_json.cid_value(value, 100000, 1000, 100), ${JSON.stringify(c.cid)})`, '}');
}
const path='src/canonical_json/text_extent_preimages.generated_test.mbt', text=lines.join('\n')+'\n';
if(process.argv.includes('--write'))writeFileSync(path,text);
else assert.equal(readFileSync(path,'utf8'),text);
console.log(`${corpus.cases.length} fixed text extent preimages verified; not applicability evidence.`);
