import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

// This is a mechanical projection of the actual Core record declarations,
// not a second field schema. Unknown syntax/types fail generation closed.
export function projectCoreLedger(source) {
  const records = new Map();
  const declarations = source.replace(/\/\/[^\n]*/gu, '');
  const pattern = /pub\(all\)\s+struct\s+(LedgerLimits|LedgerUsage)\s*\{([^}]*)\}/gu;
  for (const match of declarations.matchAll(pattern)) {
    const [, name, body] = match;
    if (records.has(name)) throw Error(`Duplicate Core ledger declaration: ${name}`);
    const names = new Set();
    const fields = body.split('\n').map(line => line.trim()).filter(Boolean).map(line => {
      const field = /^([a-z][a-z0-9_]*)\s*:\s*(Int|Int64)$/u.exec(line);
      if (!field || names.has(field[1])) throw Error(`Unsupported Core ledger field: ${line}`);
      names.add(field[1]);
      // MoonBit Int is the signed 32-bit primitive; Int64 names its width.
      // The generated width drives both wire range and host representation.
      return Object.freeze({name: field[1], bits: field[2] === 'Int' ? 32 : Number(field[2].slice(3))});
    });
    if (fields.length === 0) throw Error(`Empty Core ledger declaration: ${name}`);
    records.set(name, Object.freeze(fields));
  }
  for (const name of ['LedgerLimits', 'LedgerUsage']) {
    if (!records.has(name)) throw Error(`Missing Core ledger declaration: ${name}`);
  }
  return Object.freeze({limits: records.get('LedgerLimits'), usage: records.get('LedgerUsage')});
}

// The diagnostic's spent/current distinction is also Core-owned. Project the
// exact closed record-update predicate, refusing a different expression/shape;
// consumers never maintain another list of all usage fields or exemptions.
export function projectLedgerUsageSpentFields(source) {
  const contract = projectCoreLedger(source);
  const declarations = source.replace(/\/\/[^\n]*/gu, '');
  const matches = [...declarations.matchAll(/pub fn ledger_usage_has_pending_resources\(usage\s*:\s*LedgerUsage\)\s*->\s*Bool\s*\{\s*let pending = \{\s*\.\.usage,([^}]+)\}\s*pending != initial_ledger_usage\s*\}/gu)];
  if (matches.length !== 1) throw Error('Unsupported Core ledger pending projection');
  const cleared = matches[0][1].split('\n').map(line => line.trim()).filter(Boolean).map(line => {
    const match = /^([a-z][a-z0-9_]*)\s*:\s*(0L?),$/u.exec(line);
    const field = match && contract.usage.find(field => field.name === match[1]);
    if (!field || match[2] !== (field.bits === 64 ? '0L' : '0')) {
      throw Error(`Unsupported Core ledger spent projection: ${line}`);
    }
    return field.name;
  });
  if (cleared.length === 0 || new Set(cleared).size !== cleared.length) {
    throw Error('Invalid Core ledger spent projection');
  }
  return Object.freeze(cleared);
}

export function renderLedgerUsageDiagnostic(source) {
  const {usage} = projectCoreLedger(source);
  // Exact numeric lexemes preserve the existing Native diagnostic wire. This
  // is deliberately not ToJson(Int64), which emits strings in the pinned Core.
  const terms = usage.flatMap((field, index) => [
    JSON.stringify(`${index === 0 ? '{' : ','}${JSON.stringify(field.name)}:`),
    `usage.${field.name}.to_string()`,
  ]);
  terms.push(JSON.stringify('}'));
  return '// Generated by scripts/generate-ledger-transport-contract.mjs; do not edit.\n' +
    '// Numeric diagnostic JSON only; not a validation, physical ACK or IPC codec.\n' +
    '// Exact Int64 decimal text must not be treated as a lossless JavaScript Number.\n\n' +
    '///|\npub fn ledger_usage_diagnostic_json(usage : LedgerUsage) -> String {\n' +
    terms.map((term, index) => `  ${term}${index < terms.length - 1 ? ' +' : ''}`).join('\n') +
    '\n}\n';
}

export function renderLedgerAccountingValues(source) {
  const contract = projectCoreLedger(source);
  const values = (owner, fields) => fields.map(({name, bits}) =>
    `    ${owner}.${name}${bits === 32 ? '.to_int64()' : ''},`);
  return '// Generated by scripts/generate-ledger-transport-contract.mjs; do not edit.\n' +
    '// Complete Core declaration-order DATA; not admission, report or physical ACK.\n\n' +
    '///|\npub fn ledger_limits_usage_values(ledger : Ledger) -> Array[Int64] {\n' +
    '  let limits = ledger_limits(ledger)\n  let usage = ledger_usage(ledger)\n  [\n' +
    [...values('limits', contract.limits), ...values('usage', contract.usage)].join('\n') +
    '\n  ]\n}\n';
}

export function renderLedgerTransportContract(source) {
  const contract = projectCoreLedger(source);
  const digest = createHash('sha256').update(JSON.stringify(contract)).digest('hex');
  const fields = entries => '[\n' + entries.map(field =>
    `  Object.freeze(${JSON.stringify(field)}),`).join('\n') + '\n]';
  return '// Generated by scripts/generate-ledger-transport-contract.mjs; do not edit.\n' +
    '// Definition owner: src/physical_resources/ledger.mbt LedgerLimits/LedgerUsage.\n' +
    `// Projected definition SHA-256: ${digest}\n` +
    `export const ledgerLimitsFields = Object.freeze(${fields(contract.limits)});\n` +
    `export const ledgerUsageFields = Object.freeze(${fields(contract.usage)});\n` +
    '// The cleared fields of the actual Core pending-resource predicate.\n' +
    `export const ledgerUsageSpentFields = Object.freeze(${JSON.stringify(projectLedgerUsageSpentFields(source))});\n`;
}

function main(args) {
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw Error('Usage: node scripts/generate-ledger-transport-contract.mjs [--check]');
  }
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const source = readFileSync(resolve(root, 'src/physical_resources/ledger.mbt'), 'utf8');
  const pending = readFileSync(resolve(root, 'src/physical_resources/ledger_usage_pending.mbt'), 'utf8');
  const targets = [
    [resolve(root, 'adapters/host-node/ledger-contract.generated.mjs'), renderLedgerTransportContract(source + '\n' + pending)],
    [resolve(root, 'src/physical_resources/ledger_usage_diagnostic.generated.mbt'), renderLedgerUsageDiagnostic(source)],
    [resolve(root, 'src/physical_resources/ledger_accounting.generated.mbt'), renderLedgerAccountingValues(source)],
  ];
  for (const [target, generated] of targets) {
    if (args[0] === '--check') {
      if (readFileSync(target, 'utf8') !== generated) throw Error(`Stale Core ledger projection: ${target}`);
    } else {
      writeFileSync(target, generated);
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main(process.argv.slice(2));
}
