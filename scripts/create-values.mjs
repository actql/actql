// Canonical per-row create projection; original Mapping and capture ownership
// remains with Common. This does not interpret SQL or grant write authority.
import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {parameterPrograms} from './parameter-schema.mjs';
import {machineCid} from './actql-spec-family.mjs';

const createBody = program => program.properties.effects.additionalProperties.oneOf
  .find(member => member.properties?.create).properties.create;
const originalBody = () => JSON.parse(readFileSync(new URL(
  '../portability/fixtures/create-body-before-values.json', import.meta.url), 'utf8'));

export function createValuesSchema() {
  return {type: 'object', additionalProperties: {oneOf: [
    {type: 'object', additionalProperties: false, required: ['literal'], properties: {literal: {}}},
    {type: 'object', additionalProperties: false, required: ['field'],
      properties: {field: {type: 'string', minLength: 1}}},
  ]}};
}

// Historical schema comparisons retain their original preimages. Removing the
// new alternative from this validated copy never rewrites a saved Program.
export function withoutCreateValuesSchema(program) {
  const copy = structuredClone(program), create = createBody(copy);
  assert.deepEqual(create.properties.values, createValuesSchema());
  assert.deepEqual(create.dependentRequired, {values: ['from']});
  delete create.properties.values;
  delete create.dependentRequired;
  assert.deepEqual(create, originalBody());
  return copy;
}

export function createValuesSchemas(protocol, write = false) {
  const before = originalBody();
  for (const program of parameterPrograms(protocol)) {
    const create = createBody(program);
    if (write) {
      if (Object.hasOwn(create.properties, 'values')) {
        assert.deepEqual(create.properties.values, createValuesSchema());
        assert.deepEqual(create.dependentRequired, {values: ['from']});
      } else assert.deepEqual(create, before, 'Original create alternatives must remain exact');
      create.properties.values = createValuesSchema();
      create.dependentRequired = {values: ['from']};
    }
    // The legacy from/payload XOR remains intact, so requiring from also
    // excludes payload. Empty values objects are left to Mapping admission.
    assert.deepEqual(createBody(withoutCreateValuesSchema(program)), before);
  }
  if (write) {
    for (const [name, body] of Object.entries(protocol.artifact_schemas)) {
      protocol.artifact_schema_cids[name] = machineCid(body);
    }
    protocol.artifact_registry_cid = machineCid(protocol.artifact_schemas);
  }
  for (const [name, body] of Object.entries(protocol.artifact_schemas)) {
    assert.equal(protocol.artifact_schema_cids[name], machineCid(body));
  }
  assert.equal(protocol.artifact_registry_cid, machineCid(protocol.artifact_schemas));
}

export function createValuesHeaderVectors(vectors) {
  return ['// Generated by scripts/create-values.mjs from independent create-values corpus.',
    '// Header/type structure only; original Mapping and execution are checked separately.', '',
    ...vectors.programs.flatMap(value => ['///|',
      `test ${JSON.stringify('independent create values header: ' + value.name)} {`,
      `  let program = parse(${JSON.stringify(JSON.stringify(value.program))}, limits(), format=Json).unwrap()`,
      '  let result = collect_effect_headers(program, 1, 100)',
      value.header_valid ? [
        '  let out = @encode.hashing_writer(10000, 1000, 40)',
        '  emit_effect_header_semantics(effect_header_at(result.unwrap(), 0).unwrap(), out)',
        `  assert_eq("sha256:" + @encode.finish_hash(out), ${JSON.stringify(value.header_cid)})`,
      ].join('\n')
        : `  assert_eq(effect_header_issue_kind(result.unwrap_err()), ${value.header_issue})`,
      '}', '']),
  ].join('\n');
}

export function checkCreateValuesVectors(vectors) {
  assert.equal(vectors.qualification,
    'Independent Python canonical JSON SHA-256; no product output or runtime acceptance');
  assert.equal(machineCid(vectors.previous_create_body), vectors.previous_create_body_cid);
  assert.deepEqual(vectors.previous_create_body, originalBody());
  for (const value of vectors.programs) {
    assert.equal(machineCid(value.program), value.input_wire_cid);
    if (value.header_valid) assert.equal(machineCid(value.header_preimage), value.header_cid);
  }
  return createValuesHeaderVectors(vectors);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const path = 'spec/contracts/actql-protocol-schemas.json';
  const protocol = JSON.parse(readFileSync(path, 'utf8'));
  createValuesSchemas(protocol, process.argv.includes('--write'));
  if (process.argv.includes('--write')) writeFileSync(path, JSON.stringify(protocol, null, 2) + '\n');
  const output = 'src/stage_syntax/create_values.generated_test.mbt';
  const generated = checkCreateValuesVectors(JSON.parse(readFileSync('portability/corpus/create-values.json', 'utf8')));
  if (process.argv.includes('--write')) writeFileSync(output, generated);
  assert.equal(readFileSync(output, 'utf8'), generated);
  console.log('Create values preserve original from/raw payload alternatives and require original Result.');
}
