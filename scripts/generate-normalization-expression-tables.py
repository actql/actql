#!/usr/bin/env python3
"""Generate bounded scalar normalization mappings from pinned Unicode 16 UCD."""
import hashlib,json,pathlib,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
UCD=ROOT/'vendor/unicode/16.0.0'
pins=json.loads((UCD/'manifest.json').read_text())['sha256']
for name,digest in pins.items():
    if hashlib.sha256((UCD/name).read_bytes()).hexdigest()!=digest: raise ValueError(name)
canonical={};compat={}
for line in (UCD/'UnicodeData.txt').read_text().splitlines():
    fields=line.split(';'); cp=int(fields[0],16); parts=fields[5].split()
    if not parts:continue
    tagged=parts[0].startswith('<')
    if tagged:parts=parts[1:]
    compat[cp]=[int(x,16) for x in parts]
    if not tagged:canonical[cp]=compat[cp]
def decompose(cp,mapping):
    if 0xac00<=cp<0xd7a4:
        s=cp-0xac00;t=s%28
        return [0x1100+s//588,0x1161+s%588//28]+([0x11a7+t] if t else [])
    return sum((decompose(x,mapping) for x in mapping[cp]),[]) if cp in mapping else [cp]
fold={}
for line in (UCD/'CaseFolding.txt').read_text().splitlines():
    line=line.split('#')[0].strip()
    if not line:continue
    cp,status,seq,*_=map(str.strip,line.split(';'))
    if status in ('C','F'):fold[int(cp,16)]=[int(x,16) for x in seq.split()]
nfkd={cp:decompose(cp,compat) for cp in compat}
foldnfd={cp:sum((decompose(x,canonical) for x in fold.get(cp,[cp])),[]) for cp in set(fold)|set(canonical)}
# The execution workspace owner reserves 18 slots per input UTF-16 unit.
# Reject a Unicode data update that invalidates that allocation law.
assert max(map(len, nfkd.values())) <= 18
assert max(map(len, foldnfd.values())) <= 18
out=['// Generated by scripts/generate-normalization-expression-tables.py.', '// Unicode 16.0.0; vendor/unicode/16.0.0/LICENSE.txt.']
for name,mapping in [('compatibility',nfkd),('folding',foldnfd)]:
    keys=sorted(mapping);offsets=[0];data=[]
    for cp in keys:data+=mapping[cp];offsets.append(len(data))
    for suffix,values in [('keys',keys),('offsets',offsets),('data',data)]:
        out+=['','///|',f'let {name}_{suffix} : FixedArray[Int] = [']
        for i in range(0,len(values),16):out.append('  '+', '.join(hex(x) for x in values[i:i+16])+',')
        out+= [']']
path=ROOT/'src/canonical_value/normalization_expression_tables.generated.mbt'
content='\n'.join(out)+'\n'
if '--check' in sys.argv:
    if not path.exists() or path.read_text()!=content: raise SystemExit('normalization tables stale')
else:
    path.write_text(content)
print(path, len(nfkd),len(foldnfd))
