import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {machineCid} from './actql-spec-family.mjs';
import {readCheckReasonCatalog, checkReasonSchemaFromCatalog} from './check-reason-catalog.mjs';
const root = new URL('../', import.meta.url);
export function buildCheckReasonCatalog(catalog, registry) {
  const schema = checkReasonSchemaFromCatalog(catalog, machineCid(registry.schemas.canonical_value_contract));
  assert.deepEqual(schema, registry.artifact_schemas.check_reason);
  const cid = machineCid(schema);
  assert.equal(cid, registry.artifact_schema_cids.check_reason);
  const info = {version: catalog.version, revision: catalog.revision, reasonSchemaCid: cid};
  const entries = Object.fromEntries(catalog.entries.map(entry => [entry.code, entry]));
  const module = '// Generated by scripts/generate-check-reason-catalog.mjs --write.\n' +
    '// Selection changes advice only; the existing checker/projection decides verdicts.\n' +
    'const freeze = value => { if (value && typeof value === "object") {Object.values(value).forEach(freeze); Object.freeze(value);} return value; };\n' +
    `const info = freeze(${JSON.stringify(info, null, 2)});\n` +
    `const entries = freeze(${JSON.stringify(entries, null, 2)});\n` +
    'export const getCheckReasonCatalogInfo = () => info;\n' +
    'export const getCheckReasonCatalogEntry = code => typeof code === "string" && Object.hasOwn(entries, code) ? entries[code] : undefined;\n' +
    'export function selectCheckReasonPresentation(reason) {\n' +
    '  const entry = getCheckReasonCatalogEntry(reason?.code);\n' +
    '  if (!entry) return undefined;\n' +
    '  return entry.presentation.variants.find(variant => Object.entries(variant.when).every(([key, expected]) =>\n' +
    '    Array.isArray(expected) ? expected.includes(reason?.facts?.[key]) : reason?.facts?.[key] === expected)) ?? entry.presentation.default;\n' +
    '}\n';
  const codes = catalog.entries.map(entry => JSON.stringify(entry.code)).join(' | ');
  const types = '// Generated by scripts/generate-check-reason-catalog.mjs --write.\n' +
    `export type KnownCheckReasonCode = ${codes};\n` +
    `export type CheckReasonCatalogInfo = Readonly<{version: ${JSON.stringify(info.version)}; revision: string; reasonSchemaCid: string}>;\n` +
    'export type CheckReasonCatalogEntry = Readonly<{code: KnownCheckReasonCode; condition: string; facts_schema: "#/reason_schema"; disclosure: string; locations: readonly string[]; default_severity: "error" | "warning" | "info"; family: "input" | "requirement" | "limit" | "coverage"; examples: readonly Readonly<{file: string; scenario: string}>[]; presentation: Readonly<{default?: Readonly<{key: string; english: readonly [string, string]}>; variants: readonly Readonly<{when: Readonly<Record<string, string | readonly string[]>>; key: string; english: readonly [string, string]}>[]}>}>;\n' +
    'export declare function getCheckReasonCatalogInfo(): CheckReasonCatalogInfo;\n' +
    'export declare function getCheckReasonCatalogEntry(code: unknown): CheckReasonCatalogEntry | undefined;\n' +
    'export declare function selectCheckReasonPresentation(reason: unknown): Readonly<{key: string; english: readonly [string, string]}> | undefined;\n';
  const cell = text => text.replaceAll('|', '\\|').replaceAll('\n', ' ');
  const docs = '# Public check Reason catalog\n\n' +
    '<!-- Generated by scripts/generate-check-reason-catalog.mjs --write. -->\n\n' +
    `Catalog: \`${info.version}\`; revision: \`${info.revision}\`.\n` +
    `Public facts schema: \`${cid}\`. Translation revisions remain independent.\n\n` +
    'The existing checker and disclosure projection decide verdicts and public facts. Severity, family, descriptions and hints confer no verification, execution or recovery authority. Locations require original input custody and revisions. Examples refer to independent tests; this catalog does not construct their expectations.\n\n' +
    'These entries belong to public check, not the legacy actql-diagnostics/0.1 compiler catalog or runtime operation outcomes. No legacy catalog-body or 109-entry compatibility claim follows from this inventory.\n\n' +
    '| Code | Condition | Severity / family | Original location roles |\n| --- | --- | --- | --- |\n' +
    catalog.entries.map(entry => `| \`${entry.code}\` | ${cell(entry.condition)} | ${entry.default_severity} / ${entry.family} | ${cell(entry.locations.join('; ') || 'None emitted')} |`).join('\n') + '\n\n' +
    catalog.entries.map(entry => `## ${entry.code}\n\nFacts: [registered public Reason schema](../../spec/contracts/actql-check-reason-catalog.json#/reason_schema), selected by this code; required payload and cross-field constraints remain in that schema.\n\n${entry.disclosure}\n\n` +
      [entry.presentation.default, ...entry.presentation.variants].filter(Boolean).map(item => `${item.when ? 'For `' + JSON.stringify(item.when) + '`' : 'Default'}: ${item.english.join(' ')}\n`).join('\n') +
      '\nIndependent acceptance: ' + entry.examples.map(example => `[${example.scenario}](../../${example.file})`).join(', ') + '.\n').join('\n');
  return new Map([['packages/sdk/check-reason-catalog.generated.js', module],
    ['packages/sdk/check-reason-catalog.generated.d.ts', types], ['docs/reference/check-reasons.md', docs]]);
}
export function generateCheckReasonCatalog(write = false) {
  const registry = JSON.parse(readFileSync(new URL('spec/contracts/actql-protocol-schemas.json', root), 'utf8'));
  const outputs = buildCheckReasonCatalog(readCheckReasonCatalog(), registry);
  for (const [path, content] of outputs) {
    const url = new URL(path, root);
    if (write) writeFileSync(url, content);
    else assert.equal(readFileSync(url, 'utf8'), content, `StaleCheckReasonCatalog:${path}`);
  }
  return outputs;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) generateCheckReasonCatalog(process.argv.includes('--write'));
