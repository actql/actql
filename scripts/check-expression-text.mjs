import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';

export function generate(corpus) {
  assert.equal(corpus.version, 'actql-expression-text-corpus/0.1');
  assert.ok(Array.isArray(corpus.positive) && corpus.positive.length > 0);
  assert.ok(Array.isArray(corpus.negative) && corpus.negative.length > 0);
  const sources = new Set();
  const lines = ['// Generated by scripts/check-expression-text.mjs --write. Do not edit.'];
  for (const [index, entry] of corpus.positive.entries()) {
    assert.equal(typeof entry.source, 'string');
    assert.ok(entry.tree && typeof entry.tree === 'object' && !Array.isArray(entry.tree));
    assert.ok(!sources.has(entry.source), 'duplicate source');
    sources.add(entry.source);
    lines.push('', '///|', `test "expression corpus accepted: ${index + 1}" {`,
      `  assert_tree(${literal(entry.source)}, ${literal(JSON.stringify(entry.tree))})`, '}');
  }
  for (const [index, source] of corpus.negative.entries()) {
    assert.equal(typeof source, 'string');
    assert.ok(!sources.has(source), 'duplicate source');
    sources.add(source);
    lines.push('', '///|', `test "expression corpus rejected: ${index + 1}" {`,
      `  assert_true(parse(${literal(source)}, test_limits()) is Err(_))`, '}');
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const corpus = JSON.parse(readFileSync('portability/corpus/actql-expression-text-v0.1.json', 'utf8'));
  const output = generate(corpus);
  const path = 'src/expression_text/corpus.generated_wbtest.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, output);
  else assert.equal(readFileSync(path, 'utf8'), output, 'expression text tests are stale');
  console.log(`${corpus.positive.length} accepted and ${corpus.negative.length} rejected expression vectors; generated tests match fixed expectations.`);
}
