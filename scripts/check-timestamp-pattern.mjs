import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {canonicalText, verifyIdentity} from './check-canonical-json.mjs';
import {createHash} from 'node:crypto';

const file = 'portability/corpus/timestamp-pattern.json';
const corpus = JSON.parse(readFileSync(file, 'utf8'));
const schema = JSON.parse(readFileSync('spec/grammar/actql-timestamp-pattern-ast-0.1.schema.json', 'utf8'));
const variants = schema.properties.components.items.oneOf;
assert.equal(corpus.version, 'actql-timestamp-pattern-vectors/0.1');
assert.equal(schema.properties.version.const, 'actql-timestamp-pattern-ast/0.1');
assert.equal(schema.properties.full_input_match.const, true);
assert.equal(schema.properties.timezone.const, 'UTC');
assert.deepEqual(schema.required.slice().sort(), ['ast_cid', 'components', 'full_input_match', 'mode', 'timezone', 'version']);
const seen = new Set();
// Fixed component arrays are handwritten semantic expectations, not parser or
// lowerer output. Only canonical serialization and hashing use a Node oracle.
for (const c of corpus.accepted) {
  assert.ok(!seen.has(c.id)); seen.add(c.id);
  assert.ok(schema.properties.mode.enum.includes(c.mode));
  assert.ok(c.components.length > 0);
  assert.equal(c.components.map(x => x.value).join(''), c.pattern);
  for (const x of c.components) {
    assert.deepEqual(Object.keys(x).sort(), ['kind', 'value']);
    const branch = variants.find(v => v.properties.kind.const === x.kind);
    assert.ok(branch?.properties.value.enum.includes(x.value));
  }
  const tokens = c.components.filter(x => x.kind === 'token').map(x => x.value);
  const has = t => tokens.includes(t);
  assert.equal(new Set(tokens).size, tokens.length);
  if (c.mode === 'parse') assert.ok(['yyyy', 'MM', 'dd'].every(has));
  assert.equal(has('HH'), has('mm'));
  assert.ok(!has('ss') || has('HH'));
  assert.ok(!has('SSS') || has('ss'));
  const core = {version: 'actql-timestamp-pattern-ast/0.1', mode: c.mode,
    components: c.components, full_input_match: true, timezone: 'UTC'};
  if (process.argv.includes('--write-identities')) {
    c.expected_preimage = canonicalText(core);
    c.expected_cid = 'sha256:' + createHash('sha256').update(c.expected_preimage).digest('hex');
    c.expected_ast = canonicalText({...core, ast_cid: c.expected_cid});
  }
  verifyIdentity(core, c.expected_cid, c.expected_preimage);
  assert.equal(c.expected_ast, canonicalText({...core, ast_cid: c.expected_cid}));
}
for (const c of corpus.rejected) {
  assert.ok(!seen.has(c.id)); seen.add(c.id);
  assert.ok(schema.properties.mode.enum.includes(c.mode));
  assert.ok(/^(EmptyPattern|MissingDate|InvalidTimeDependencies|InvalidComponent\([0-9]+\)|DuplicateToken\("[a-zA-Z]+"\))$/.test(c.issue));
}
if (process.argv.includes('--write-identities')) writeFileSync(file, JSON.stringify(corpus, null, 2) + '\n');
const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const lines = ['// Generated by scripts/check-timestamp-pattern.mjs --write. Do not edit.'];
for (const c of corpus.accepted) {
  lines.push('', '///|', `test ${literal('timestamp pattern: ' + c.id)} {`,
    `  let value = parse(${literal(c.pattern)}, ${c.mode === 'parse' ? 'Parse' : 'Format'}, limits()).unwrap()`,
    `  assert_eq(cid(value), ${literal(c.expected_cid)})`,
    '  let writer = @encode.writer(10000, 1000, 3)', '  emit(value, writer)',
    `  assert_eq(@encode.finish(writer), ${literal(c.expected_ast)})`,
    '  let preimage = @encode.writer(10000, 1000, 3)', '  emit_preimage(value, preimage)',
    `  assert_eq(@encode.finish(preimage), ${literal(c.expected_preimage)})`,
    `  assert_eq(value_width(value), ${c.pattern.length})`,
    `  assert_eq(component_count(value), ${c.components.length})`,
    ...c.components.map((x, i) => `  assert_eq(component_at(value, ${i}), Some(${x.kind === 'token' ? 'Token' : 'Literal'}(${literal(x.value)})))`), '}');
}
for (const c of corpus.rejected) {
  lines.push('', '///|', `test ${literal('timestamp pattern rejects: ' + c.id)} {`,
    `  assert_true(parse(${literal(c.pattern)}, ${c.mode === 'parse' ? 'Parse' : 'Format'}, limits()) is Err(${c.issue}))`, '}');
}
const path = 'src/timestamp_pattern/vectors.generated_test.mbt', text = lines.join('\n') + '\n';
if (process.argv.includes('--write')) writeFileSync(path, text);
else assert.equal(readFileSync(path, 'utf8'), text, 'stale timestamp-pattern tests');
console.log(`${corpus.accepted.length} accepted and ${corpus.rejected.length} rejected timestamp-pattern vectors; no timestamp evaluation claim.`);
