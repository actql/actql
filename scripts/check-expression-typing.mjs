import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';

export function generate(corpus) {
  assert.equal(corpus.version, 'actql-expression-typing-corpus/0.1');
  assert.ok(corpus.positive.length && corpus.negative.length);
  assert.ok(corpus.fields && corpus.parameters && corpus.types);
  const seen = new Set();
  const lines = ['// Generated by scripts/check-expression-typing.mjs --write. Do not edit.'];
  const fields = literal(JSON.stringify(corpus.fields));
  const params = literal(JSON.stringify(corpus.parameters));
  lines.push('', '///|', `fn corpus_fields() -> String { ${fields} }`, '', '///|', `fn corpus_parameters() -> String { ${params} }`);
  for (const [group, entries] of [['accepted', corpus.positive], ['rejected', corpus.negative]]) {
    for (const [index, entry] of entries.entries()) {
      assert.ok(Object.hasOwn(entry, 'source'));
      const source = JSON.stringify(entry.source);
      assert.ok(!seen.has(source), 'duplicate source');
      seen.add(source);
      const expected = group === 'accepted' ? corpus.types[entry.type] : entry.issue;
      if (group === 'accepted') assert.ok(expected && typeof expected.nullable === 'boolean', 'missing fixed type expectation');
      else assert.ok(['TypeMismatch', 'NullTypeUnresolved', 'UnknownField', 'UnknownParameter', 'MissingJoinScope', 'InvalidStaticOption', 'ForbiddenConstructorValue'].includes(expected), 'unknown issue');
      lines.push('', '///|', `test "expression type corpus ${group}: ${index + 1}" {`,
        `  ${group === 'accepted' ? 'assert_type' : 'assert_rejected'}(${literal(source)}, corpus_fields(), corpus_parameters(), ${literal(group === 'accepted' ? JSON.stringify(expected) : expected)})`, '}');
    }
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const corpus = JSON.parse(readFileSync('portability/corpus/actql-expression-typing-v0.1.json', 'utf8'));
  const output = generate(corpus);
  const path = 'src/expression_typing/corpus.generated_test.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, output);
  else assert.equal(readFileSync(path, 'utf8'), output, 'expression type tests are stale');
  console.log(`${corpus.positive.length} accepted and ${corpus.negative.length} rejected fixed type vectors; runtime evaluation is not tested.`);
}
