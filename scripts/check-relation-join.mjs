import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const quote = s => '"' + [...s].map(c => {
  const n = c.codePointAt(0);
  return n < 32 || n > 126 ? '\\u{' + n.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const issues = new Set(['EmptyBody', 'InvalidBody', 'UnknownField', 'IncomparableKeys', 'InvalidProjection', 'InvalidName', 'InvalidGuard']);
export function generate(c) {
  assert.equal(c.version, 'actql-relation-join-corpus/0.1');
  assert.ok(c.input_fields && typeof c.input_fields === 'object');
  assert.ok(Array.isArray(c.cases) && c.cases.length);
  const seen = new Set();
  const out = ['// Generated by scripts/check-relation-join.mjs --write. Do not edit.'];
  for (const v of c.cases) {
    assert.equal(typeof v.id, 'string'); assert.ok(v.id && !seen.has(v.id)); seen.add(v.id);
    assert.ok(v.body && typeof v.body === 'object' && !Array.isArray(v.body));
    const args = [quote(JSON.stringify(v.body)), quote(JSON.stringify(c.input_fields))];
    if (v.issue !== undefined) {
      assert.ok(issues.has(v.issue)); assert.equal(v.fields, undefined); assert.equal(v.nullable, undefined); assert.equal(v.key_count, undefined);
      args.push(quote(v.issue));
    } else {
      assert.ok(Array.isArray(v.fields) && v.fields.every(x => typeof x === 'string'));
      assert.equal(new Set(v.fields).size, v.fields.length);
      assert.ok(Array.isArray(v.nullable) && v.nullable.length === v.fields.length && v.nullable.every(x => typeof x === 'boolean'));
      assert.ok(Number.isSafeInteger(v.key_count) && v.key_count > 0);
      args.push('[' + v.fields.map(quote).join(',') + ']', JSON.stringify(v.nullable), String(v.key_count));
    }
    out.push('', '///|', `test ${quote('join corpus: ' + v.id)} {`, `  corpus_${v.issue === undefined ? 'accepted' : 'rejected'}(${args.join(', ')})`, '}');
  }
  return out.join('\n') + '\n';
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = JSON.parse(readFileSync('portability/corpus/actql-relation-join-v0.1.json', 'utf8'));
  const path = 'src/relation_join/corpus.generated_test.mbt', text = generate(c);
  if (process.argv.includes('--write')) writeFileSync(path, text);
  else assert.equal(readFileSync(path, 'utf8'), text, 'stale join corpus tests');
  console.log(`${c.cases.length} fixed local join type cases; not execution or proof conformance.`);
}
