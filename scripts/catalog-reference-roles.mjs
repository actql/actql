import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';

// Role meanings are explicit. Shape and optional-parent paths come from the
// pinned schemas; newly added reference slots fail coverage until classified.
const roles = {
  source_view: {
    'acquisition.request_schema':'request_schema',
    'acquisition.batching.request_key_schema':'lookup_request_key',
    'acquisition.batching.batch_request_schema':'lookup_batch_request',
    'acquisition.batching.response_key_schema':'lookup_response_key',
    'acquisition.modes.*.checkpoint.value_schema':'checkpoint',
    'acquisition.modes.*.checkpoint.expiration_schema':'checkpoint',
    'acquisition.modes.*.delivery.lease.expiration_schema':'checkpoint',
    'request_processing.data_handling.contract':'request_data_handling',
    'request_processing.provider_execution_capability':'provider_execution_capability',
    'output.schema':'carrier_schema',
    'output.facts':'carrier_facts',
    'output.data_policy':'data_policy',
    'pushdown.contract':'pushdown',
  },
  command_contract: {
    input_schema:'command_input',output_schema:'command_output',
    'idempotency.key_schema':'idempotency_key',
    reconciliation:'reconciliation',poll:'poll',cancel:'cancel',
  },
};
export function generateRoutes(schemas) {
const lines=['// Generated by scripts/catalog-reference-roles.mjs; do not edit.', '///|', 'fn catalog_reference_routes() -> Array[ReferenceRoute] {', '  ['];
let count=0;
for(const [owner,mapping] of Object.entries(roles)){
  const found=new Map();
  function walk(schema,path,hops,seen=new Set(),conditional=false){
    if(schema.$ref){
      assert.ok(schema.$ref.startsWith('#/'),`external reference needs explicit routing: ${schema.$ref}`);
      if(seen.has(schema.$ref))return;
      const target=schema.$ref.slice(2).split('/').reduce((v,k)=>v[k.replaceAll('~1','/').replaceAll('~0','~')],schemas[owner]);
      assert.ok(target,`unresolved schema reference ${schema.$ref}`);
      walk(target,path,hops,new Set([...seen,schema.$ref]),conditional);
    }
    if(schema.type==='object' && schema.additionalProperties===false
      && Object.keys(schema.properties??{}).sort().join(',')==='cid,id,version'
      && [...(schema.required??[])].sort().join(',')==='cid,id,version'){
      assert.equal(conditional,false,`conditional ContractRef needs explicit routing: ${owner}.${path.join('.')}`);
      assert.ok(!found.has(path.join('.')),`ambiguous reference route ${path.join('.')}`);
      found.set(path.join('.'),hops); return;
    }
    for(const [name,child] of Object.entries(schema.properties??{})){
      walk(child,[...path,name],[...hops,`RefField(${JSON.stringify(name)}, ${Boolean(schema.required?.includes(name))})`],seen,conditional);
    }
    if(schema.items && !Array.isArray(schema.items))walk(schema.items,[...path,'*'],[...hops,'RefEach'],seen,conditional);
    for(const keyword of ['allOf','anyOf','oneOf'])for(const branch of schema[keyword]??[])walk(branch,path,hops,seen,true);
    for(const keyword of ['if','then','else','not'])if(schema[keyword])walk(schema[keyword],path,hops,seen,true);
  }
  walk(schemas[owner],[],[]);
  assert.deepEqual([...found.keys()].sort(),Object.keys(mapping).sort(),`${owner} reference role coverage`);
  for(const [path,kind] of Object.entries(mapping)){
    assert.ok(schemas.contract_envelope.properties.kind.enum.includes(kind),kind);
    lines.push(`    ReferenceRoute(${owner==='source_view'}, [${found.get(path).join(', ')}], ${JSON.stringify(kind)}),`);
    count++;
  }
}
lines.push('  ]','}','');
const output=lines.join('\n');
return {output,count};
}
if(process.argv[1] && import.meta.url===pathToFileURL(process.argv[1]).href){
const schemas=JSON.parse(readFileSync('spec/contracts/actql-protocol-schemas.json','utf8')).schemas;
const {output,count}=generateRoutes(schemas);
const target='src/check_environment/catalog_roles.generated.mbt';
if(process.argv.includes('--write'))writeFileSync(target,output);
assert.equal(readFileSync(target,'utf8'),output,`Regenerate ${target}`);
console.log(`${count} Catalog reference roles cover the pinned SourceView and Command schemas.`);
}
