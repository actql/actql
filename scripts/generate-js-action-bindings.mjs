import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname} from 'node:path';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {actionBoundaries} from './js-action-boundaries.mjs';

function block(source, pattern, label) {
  const match = pattern.exec(source);
  if (!match) throw new Error(`Missing Owner declaration: ${label}`);
  const start = match.index + match[0].length;
  let depth = 1, end = start;
  for (; end < source.length && depth; end++) {
    if (source[end] === '{') depth++;
    if (source[end] === '}') depth--;
  }
  if (depth) throw new Error(`Unclosed Owner declaration: ${label}`);
  return source.slice(start, end - 1);
}

export function readActionBoundary(root, boundary) {
  const source = readFileSync(new URL(boundary.source, root), 'utf8');
  const variants = block(source, new RegExp(`pub\\(all\\) enum ${boundary.enumeration} \\{`, 'u'), boundary.enumeration)
    .trim().split(/\s+/u);
  if (!variants.every(value => /^[A-Z][A-Za-z0-9_]*$/u.test(value)) ||
      new Set(variants).size !== variants.length) throw new Error('Unsupported Owner action enum');
  const body = block(source, new RegExp(`pub fn ${boundary.projection}\\([\\s\\S]*?\\) -> Int \\{`, 'u'), boundary.projection).trim();
  const match = /^match [a-z_]+(?:\([a-z_]+\))? \{([\s\S]*)\}$/u.exec(body);
  if (!match) throw new Error(`Unsupported Owner code projection: ${boundary.projection}`);
  const arms = [...match[1].matchAll(/([A-Z][A-Za-z0-9_]*)\s*=>\s*(\d+)/gu)];
  if (match[1].replace(/([A-Z][A-Za-z0-9_]*)\s*=>\s*(\d+)/gu, '').trim() ||
      arms.length !== variants.length || new Set(arms.map(arm => arm[1])).size !== variants.length ||
      arms.some(arm => !variants.includes(arm[1]))) throw new Error('Incomplete Owner code projection');
  const rows = arms.map(([,variant,code]) => ({variant,code:Number(code)})).sort((a,b) => a.code-b.code);
  if (rows.some((row,index) => row.code !== index)) throw new Error('Noncontiguous Owner action codes');
  const excluded = boundary.excluded ?? [];
  if (excluded.some(variant => !variants.includes(variant))) throw new Error('Unknown excluded Owner action');
  if (boundary.names && (Object.keys(boundary.names).length !== variants.length ||
      variants.some(variant => typeof boundary.names[variant] !== 'string'))) {
    throw new Error('Incomplete JS action-name declaration');
  }
  return rows.filter(row => !excluded.includes(row.variant)).map(row => ({...row,
    name:boundary.names?.[row.variant] ?? row.variant}));
}

const header = '// Generated by scripts/generate-js-action-bindings.mjs from existing MoonBit Owner code.\n' +
  '// Names project decisions; they create no state, transition, permission or release.\n';

export function actionBindingOutputs(root) {
  const resolved = actionBoundaries.map(boundary => ({boundary,rows:readActionBoundary(root,boundary)}));
  const publication = header + 'const actions = Object.freeze({\n' +
    resolved.filter(({boundary}) => boundary.family === 'publication').map(({boundary,rows}) =>
      `  ${boundary.kind}: Object.freeze(${JSON.stringify(rows.map(row => row.name))}),\n`).join('') + '});\n\n' +
    `export function publicationAction(kind, code) {
  const names = actions[kind];
  if (names === undefined || !Number.isInteger(code) || code < 0 || code >= names.length) {
    throw new TypeError('InvalidRunHostPublicationAction');
  }
  return names[code];
}
`;
  const strategy = header + `function actionNames(names, errorCode) {
  return code => {
    if (!Number.isSafeInteger(code) || code < 0 || code >= names.length) {
      throw Object.assign(new Error(errorCode), {code: errorCode});
    }
    return names[code];
  };
}

export const strategyAction = Object.freeze({
` + resolved.filter(({boundary}) => boundary.family === 'strategy').map(({boundary,rows}) =>
    `  ${boundary.kind}: actionNames(Object.freeze(${JSON.stringify(rows.map(row => row.name))}), ${JSON.stringify(boundary.error)}),\n`).join('') + '});\n';
  const aliases = {run_publication:'publication',execution_site:'site',physical_strategy_host:'strategy'};
  const cases = resolved.filter(({boundary}) => boundary.kind !== 'resultAccess').flatMap(({boundary,rows}) => {
    const owner = aliases[boundary.source.split('/')[1]];
    return rows.map(row => `  rows.push([${[boundary.family,boundary.kind,row.variant,row.name].map(JSON.stringify).join(', ')}, @${owner}.${boundary.projection}(@${owner}.${row.variant}).to_string()])\n`);
  }).join('');
  const access = resolved.find(({boundary}) => boundary.kind === 'resultAccess');
  const records = ['record_result_access_request_authorization','record_result_access_resolution',
    'record_result_access_initial_availability','record_result_access_read_admission','record_result_access_grant'];
  const accessRows = access.rows.map((row,index) =>
    (index === access.rows.length-1 ? '  let rejected = @publication.begin_result_access_progress()\n  @publication.record_result_access_request_authorization(rejected, false).unwrap()\n' : '') +
    `  rows.push(["publication", "resultAccess", ${JSON.stringify(row.variant)}, ${JSON.stringify(row.name)}, @publication.result_access_progress_action_code(${index === access.rows.length-1 ? 'rejected' : 'access'}).to_string()])\n` +
    (index < records.length ? `  @publication.${records[index]}(access, true).unwrap()\n` : '')).join('');
  const probeSource = '// Generated by scripts/generate-js-action-bindings.mjs; verification fixture only.\n\n///|\n' +
    '#export_name("bindingActionCodes")\npub fn action_codes() -> Array[Array[String]] {\n  let rows : Array[Array[String]] = []\n' +
    cases + '  let access = @publication.begin_result_access_progress()\n' + accessRows + '  rows\n}\n';
  const probe = execFileSync(process.env.MOON_HOME ? join(process.env.MOON_HOME,'bin/moonfmt') : 'moonfmt',
    ['-'],{input:probeSource,encoding:'utf8',timeout:10000});
  return new Map([
    ['adapters/host-common/publication-action.mjs',publication],
    ['packages/run-host-core/publication-action.mjs',publication],
    ['adapters/host-common/strategy-actions.mjs',strategy],
    ['src/interface_action_probe/codes.generated.mbt',probe],
  ]);
}

export function generateActionBindings(root, write = false) {
  for (const [path,expected] of actionBindingOutputs(root)) {
    const target = new URL(path,root);
    let actual;
    try { actual = readFileSync(target,'utf8'); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (actual === expected) continue;
    if (!write) throw new Error(`Stale Owner action binding: ${path}`);
    mkdirSync(dirname(fileURLToPath(target)),{recursive:true});
    writeFileSync(target,expected);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.length !== 3 || !['--check','--write'].includes(process.argv[2])) {
    throw new Error('Usage: generate-js-action-bindings.mjs --check|--write');
  }
  generateActionBindings(new URL('../',import.meta.url),process.argv[2] === '--write');
}
