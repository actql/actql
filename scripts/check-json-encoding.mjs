import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { machineCid } from './actql-spec-family.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const readJson = path => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const outputPath = resolve(root, 'src/encode_core/scalar_vectors.generated_wbtest.mbt');

export function verifyKernel(manifest, contract) {
  assert.equal(manifest.manifest_version, contract.kernel_law_manifest);
  assert.equal(machineCid(manifest), contract.kernel_law_manifest_cid, 'kernel manifest CID');
}

export function validateVectors(corpus) {
  assert.equal(corpus.version, 'actql-json-encoding-vectors/0.1');
  const seen = new Set();
  for (const kind of ['numbers', 'strings']) {
    assert.ok(Array.isArray(corpus[kind]) && corpus[kind].length > 0, kind);
    for (const item of corpus[kind]) {
      let value;
      let invalid;
      let identity;
      if (kind === 'numbers') {
        assert.match(item.bits, /^[0-9a-f]{16}$/);
        value = Buffer.from(item.bits, 'hex').readDoubleBE();
        invalid = !Number.isFinite(value) || Object.is(value, -0);
        identity = item.bits;
      } else {
        assert.equal(typeof item.id, 'string');
        assert.ok(item.id.length > 0);
        assert.ok(Array.isArray(item.units));
        for (const unit of item.units) {
          assert.ok(Number.isInteger(unit) && unit >= 0 && unit <= 0xffff, 'UTF-16 unit');
        }
        value = item.units.map(unit => String.fromCharCode(unit)).join('');
        invalid = !value.isWellFormed();
        identity = item.id;
      }
      const key = kind + ':' + identity;
      assert.ok(!seen.has(key), 'duplicate vector: ' + key);
      seen.add(key);
      if (invalid) {
        assert.equal(item.error, kind === 'numbers' ? 'InvalidNumber' : 'InvalidUnicode', key);
        assert.ok(!Object.hasOwn(item, 'json'), key);
      } else {
        assert.ok(!Object.hasOwn(item, 'error'), key);
        assert.equal(item.json, JSON.stringify(value), key);
      }
    }
  }
}

// ASCII literals also avoid treating JSON's \uXXXX spelling as MoonBit syntax.
function literal(value) {
  let result = '"';
  for (const char of value) {
    const point = char.codePointAt(0);
    if (point >= 0x20 && point <= 0x7e) {
      result += char === '"' || char === '\\' ? '\\' + char : char;
    } else {
      result += '\\u{' + point.toString(16) + '}';
    }
  }
  return result + '"';
}

export function generateTests(corpus) {
  validateVectors(corpus);
  const lines = [
    '// Generated by scripts/check-json-encoding.mjs --write. Do not edit.',
    '// Expectations come from portability/corpus/json-encoding.json.',
  ];
  for (const kind of ['numbers', 'strings']) {
    lines.push('', '///|', 'test "fixed ' + kind + ' encoding vectors" {');
    for (const item of corpus[kind]) {
      const value = kind === 'numbers'
        ? '(0x' + item.bits + 'UL).reinterpret_as_double()'
        : 'String::from_array([' + item.units.map(unit => '(0x' + unit.toString(16) + ').unsafe_to_char()').join(', ') + '])';
      const fn = kind === 'numbers' ? 'number_value' : 'string_value';
      lines.push('  {', '    let value = ' + value);
      if (item.error) {
        lines.push(
          '    for measure in [false, true] {',
          '      let w = if measure { measuring_writer(4096, 1, 0) } else { writer(4096, 1, 0) }',
          '      let rejected = try { ' + fn + '(w, value); false } catch { ' + item.error + ' => true; _ => false }',
          '      assert_true(rejected)',
          '      assert_encoding_closed(w)',
          '    }',
        );
      } else {
        const bytes = Buffer.byteLength(item.json, 'utf8');
        lines.push(
          '    let exact = writer(' + bytes + ', 1, 0)',
          '    ' + fn + '(exact, value)',
          '    assert_eq(finish(exact), ' + literal(item.json) + ')',
          '    let measured = measuring_writer(' + bytes + ', 1, 0)',
          '    ' + fn + '(measured, value)',
          '    assert_eq(finish_measurement(measured), ' + bytes + ')',
          '    for measure in [false, true] {',
          '      let short = if measure { measuring_writer(' + (bytes - 1) + ', 1, 0) } else { writer(' + (bytes - 1) + ', 1, 0) }',
          '      let rejected = try { ' + fn + '(short, value); false } catch { OutputLimit => true; _ => false }',
          '      assert_true(rejected)',
          '      assert_encoding_closed(short)',
          '    }',
        );
      }
      lines.push('  }');
    }
    lines.push('}');
  }
  return lines.join('\n') + '\n';
}

export function checkGenerated(actual, expected) {
  assert.equal(actual, expected, 'encoding vectors are stale; run npm run generate:encoding');
}

function main() {
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 1 && args[0] === '--write'), 'usage: check-json-encoding.mjs [--write]');
  verifyKernel(readJson('spec/dependencies/aoa-kernel-laws.json'), readJson('spec/contracts/actql-aoa.json'));
  const corpus = readJson('portability/corpus/json-encoding.json');
  const expected = generateTests(corpus);
  if (args[0] === '--write') writeFileSync(outputPath, expected);
  else checkGenerated(readFileSync(outputPath, 'utf8'), expected);
  console.log('Kernel manifest pin and ' + (corpus.numbers.length + corpus.strings.length) + ' encoding vectors verified.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
