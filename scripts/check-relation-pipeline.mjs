import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const quote = s => '"' + [...s].map(c => {
  const n = c.codePointAt(0);
  return n < 32 || n > 126 ? '\\u{' + n.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const array = xs => '[' + xs.map(quote).join(',') + ']';
const issues = new Set(['MissingCurrent','DuplicateName','UnknownName','UnsupportedOperation','Operation','InvalidBody','ReservedMetadataKey']);
export function generate(c) {
  assert.equal(c.version, 'actql-relation-pipeline-corpus/0.1');
  assert.ok(Array.isArray(c.cases) && c.cases.length);
  const seen = new Set();
  const out = ['// Generated by scripts/check-relation-pipeline.mjs --write. Do not edit.'];
  for (const v of c.cases) {
    assert.equal(typeof v.id, 'string'); assert.ok(v.id && !seen.has(v.id)); seen.add(v.id);
    assert.ok(Array.isArray(v.inputs) && v.inputs.every(x => typeof x === 'string'));
    assert.ok(Array.isArray(v.steps));
    assert.ok(v.from === undefined || typeof v.from === 'string');
    const args = [quote(JSON.stringify(v.steps)), array(v.inputs), v.from === undefined ? 'None' : 'Some(' + quote(JSON.stringify(v.from)) + ')'];
    if (v.issue !== undefined) {
      assert.ok(issues.has(v.issue)); assert.equal(v.current, undefined);
      args.push(quote(v.issue));
    } else {
      assert.match(v.current, /^(input|step):[0-9]+$/);
      assert.ok(Array.isArray(v.edges) && v.edges.length === v.steps.length);
      for (const edge of v.edges) assert.match(edge, /^(input|step):[0-9]+$/);
      assert.ok(Array.isArray(v.fields) && v.fields.every(x => typeof x === 'string'));
      args.push(quote(v.current), array(v.edges), array(v.fields));
    }
    out.push('', '///|', `test ${quote('pipeline corpus: ' + v.id)} {`,
      `  corpus_${v.issue === undefined ? 'accepted' : 'rejected'}(${args.join(', ')})`, '}');
  }
  return out.join('\n') + '\n';
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = JSON.parse(readFileSync('portability/corpus/actql-relation-pipeline-v0.1.json', 'utf8'));
  const output = generate(c), path = 'src/relation_pipeline/corpus.generated_test.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, output);
  else assert.equal(readFileSync(path, 'utf8'), output, 'stale pipeline corpus tests');
  console.log(`${c.cases.length} fixed pipeline type/edge cases; not execution conformance.`);
}
