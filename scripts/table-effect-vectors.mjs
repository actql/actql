// Independent authored preimages. No Table provider or product issuer is
// imported; expected identity changes require reviewing these exact bodies.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {canonicalText} from './check-canonical-json.mjs';

const path = 'portability/corpus/table-effect.json';
const pin = digit => `sha256:${digit.repeat(64)}`;
const hash = value => `sha256:${createHash('sha256')
  .update(canonicalText(value)).digest('hex')}`;
const seal = (body, field) => ({...body, [field]: hash(body)});

export function authoredTableVectors() {
  const create = seal({
    version: 'actql-table-operation/0.1',
    logical_request_scope_cid: pin('1'),
    effect_identity_cid: pin('2'),
    action: 'create',
    catalog_identity_cid: pin('3'),
    namespace: ['analytics'],
    table_name: 'tickets',
    expected_table: null,
    input_artifact_cid: pin('4'),
    input_relation_cid: pin('5'),
    schema_cid: pin('6'),
    storage_mapping_cid: pin('7'),
    data_policy_cid: pin('8'),
  }, 'request_cid');
  const {request_cid: _, ...base} = create;
  const replace = seal({...base, action: 'replace',
    expected_table: {table_uuid: '01234567-89ab-cdef-0123-456789abcdef',
      generation_cid: pin('9')}}, 'request_cid');
  const emptyReceipt = seal({version: 'actql-table-receipt/0.1',
    request_cid: create.request_cid, effect_identity_cid: pin('2'),
    catalog_identity_cid: pin('3'),
    table_uuid: '01234567-89ab-cdef-0123-456789abcdef',
    generation_cid: pin('a'),
    metadata_location: 'file:///warehouse/tickets/metadata/00000.json',
    snapshot_id: null, schema_cid: pin('6'), storage_mapping_cid: pin('7'),
    row_count: 0}, 'receipt_cid');
  const {receipt_cid: __, ...receiptBase} = emptyReceipt;
  const replacementReceipt = seal({...receiptBase,
    request_cid: replace.request_cid,
    generation_cid: pin('b'),
    metadata_location: 'file:///warehouse/tickets/metadata/00001.json',
    snapshot_id: '9223372036854775807', row_count: 3}, 'receipt_cid');
  const cases = Object.entries({create, replace, emptyReceipt,
    replacementReceipt}).map(([id, body]) => ({id, body,
    expected_canonical_bytes: canonicalText(body),
    expected_cid: body.request_cid && !id.endsWith('Receipt')
      ? body.request_cid : body.receipt_cid}));
  return {version: 'actql-table-effect-vectors/0.1', cases};
}

export function tableMoonVectors(corpus) {
  const literal = value => JSON.stringify(value);
  const lines = ['// Generated by scripts/table-effect-vectors.mjs --write.',
    '// Independent source bodies, not output from a Table implementation.'];
  for (const entry of corpus.cases) {
    const name = entry.id.replace(/[A-Z]/gu, c => `_${c.toLowerCase()}`);
    lines.push('', '///|',
      `fn table_vector_${name}() -> String {`,
      `  ${literal(entry.expected_canonical_bytes)}`, '}',
      '', '///|', `fn table_vector_${name}_cid() -> String {`,
      `  ${literal(entry.expected_cid)}`, '}');
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const corpus = authoredTableVectors();
  const outputs = new Map([[path, JSON.stringify(corpus, null, 2) + '\n'],
    ['src/effect_application/table_vectors.generated_wbtest.mbt',
      tableMoonVectors(corpus)]]);
  for (const [file, contents] of outputs) {
    if (process.argv.includes('--write')) writeFileSync(file, contents);
    assert.equal(readFileSync(file, 'utf8'), contents, `Stale ${file}`);
  }
  console.log('Table operation vectors: four independently authored preimages.');
}
