// Rebuild-time assembly only. Concrete module references come from manifests
// owned by connector packages; the common Host has no provider imports.
import {readFileSync, readdirSync, existsSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'adapters/connectors-builtin/strategy.generated.mjs');
const entries = [];
for (const name of readdirSync(join(root, 'src/connectors')).sort()) {
  const path = join(root, 'src/connectors', name, 'node-bundle.json');
  if (!existsSync(path)) continue;
  const manifest = JSON.parse(readFileSync(path, 'utf8'));
  if (Object.keys(manifest).join() !== 'strategy' ||
      Object.keys(manifest.strategy).sort().join() !== 'export,module') {
    throw new Error(`Invalid Node bundle manifest: ${path}`);
  }
  const entry = manifest.strategy;
  if (!/^adapters\/[a-z0-9_-]+\/strategy-bundle\.mjs$/.test(entry.module) ||
      !/^[A-Za-z_]\w*$/.test(entry.export) || !existsSync(join(root, entry.module))) {
    throw new Error(`Invalid strategy contribution: ${path}`);
  }
  entries.push({name, module: relative(dirname(output), join(root, entry.module)), symbol: entry.export});
}
const source = `// Generated by scripts/connector-node-bundles.mjs; edit connector manifests.\n` +
  entries.map((entry, index) => `import {${entry.symbol} as contribution${index}} from '${entry.module}';\n`).join('') +
  `\nexport function installStrategyContributions(moon, setup, checked, options) {\n` +
  `  const factories = new Map([\n` +
  entries.map((entry, index) => `    ['${entry.name}', contribution${index}],\n`).join('') +
  `  ]);\n` +
  `  const keys = moon.strategyHostModules(setup);\n` +
  `  if (!Array.isArray(keys) || new Set(keys).size !== keys.length ||\n` +
  `      keys.some(key => !factories.has(key))) {\n` +
  `    throw new Error('Configured module has no unique Node implementation');\n` +
  `  }\n` +
  `  return Object.freeze(keys.map(key => factories.get(key)(moon, setup, checked, options)));\n}\n`;
if (process.argv.includes('--write')) writeFileSync(output, source);
else if (readFileSync(output, 'utf8') !== source) throw new Error('Node connector bundle assembly is stale');
console.log(`${entries.length} rebuild-time Node strategy contributions verified.`);
