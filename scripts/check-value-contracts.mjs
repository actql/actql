import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { canonicalText } from './check-canonical-json.mjs';
import { machineCid } from './actql-spec-family.mjs';

const read = path => JSON.parse(readFileSync(path, 'utf8'));
const corpus = read('portability/corpus/value-contracts.json');
const registry = read('spec/contracts/actql-protocol-schemas.json');
assert.equal(corpus.version, 'actql-value-contract-vectors/0.1');
const pattern = '^(?!__cid$)(?!__actql_)(?![\\s\\S]*\\.)(?=[\\s\\S]*\\S)[\\s\\S]+$';
const stalePattern = '^(?!__cid$)(?!__actql_)(?!.*\\.)(?=.*\\S).+$';
let contracts = 0;
function inspect(value) {
  if (!value || typeof value !== 'object') return;
  assert.notEqual(value.pattern, stalePattern, 'stale field-name pattern');
  if (value.properties?.type?.const === 'object' && value.properties.fields?.propertyNames) {
    const fields = value.properties.fields;
    assert.equal(fields.minProperties ?? 0, 0, 'empty object contracts');
    assert.equal(fields.propertyNames.pattern, pattern, 'field names include line breaks');
    const regex = new RegExp(pattern, 'u');
    for (const name of ['first\nname', '__cid\n', '\u2028x', 'x\u2029', 'meta', 'é', '😀', '\u0085']) assert.ok(regex.test(name));
    for (const name of ['', '\n \t', '\ufeff', '__cid', '__actql_x', 'first\n.name']) assert.ok(!regex.test(name));
    contracts++;
  }
  for (const child of Object.values(value)) inspect(child);
}
for (const file of readdirSync('spec/contracts').filter(n => n.endsWith('.json'))) {
  const value = read('spec/contracts/' + file);
  inspect(value);
  if (value.schema_cids && value.schemas) {
    for (const [name, expected] of Object.entries(value.schema_cids)) assert.equal(expected, machineCid(value.schemas[name]), file + ':' + name);
  }
  const self = file === 'actql-production-profile-schemas.json' ? 'registry_cid' : file === 'actql-read-collection.json' ? 'contract_cid' : null;
  if (self) { const body = { ...value }; delete body[self]; assert.equal(value[self], machineCid(body), file); }
}
assert.ok(contracts > 0);
for (const [bodyKey, pinKey, totalKey] of [['schemas', 'schema_cids', 'registry_cid'], ['artifact_schemas', 'artifact_schema_cids', 'artifact_registry_cid']]) {
  for (const [name, body] of Object.entries(registry[bodyKey])) assert.equal(registry[pinKey][name], machineCid(body), name);
  assert.equal(registry[totalKey], machineCid(registry[bodyKey]));
}
const literal = s => '"' + [...s].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const lines = ['// Generated by scripts/check-value-contracts.mjs --write. Do not edit.'];
const ids = new Set();
for (const c of corpus.cases) {
  assert.ok(typeof c.id === 'string' && c.id.length > 0 && !ids.has(c.id)); ids.add(c.id);
  assert.ok(c.mode === 'author' || c.mode === 'checked');
  assert.ok(c.input && typeof c.input === 'object' && !Array.isArray(c.input));
  assert.equal(Object.hasOwn(c, 'expected_json'), !Object.hasOwn(c, 'expected_error'));
  const call = `@value_contract.read_${c.mode}(cursor(${literal(JSON.stringify(c.input))}), limits())`;
  lines.push('', '///|', `test ${literal('value contract corpus: ' + c.id)} {`);
  if (c.expected_json !== undefined) {
    assert.equal(c.expected_json, canonicalText(JSON.parse(c.expected_json)));
    lines.push(`  let value = ${call}.unwrap()`, `  assert_eq(render(value), ${literal(c.expected_json)})`,
      `  let checked = @value_contract.read_checked(cursor(${literal(c.expected_json)}), limits()).unwrap()`,
      '  assert_true(@value_contract.type_equal(value, checked, 1000))');
  } else {
    assert.ok(['MissingField','UnknownField','InvalidRange','InvalidFieldName'].includes(c.expected_error));
    lines.push(`  assert_eq(error_name(${call}), ${literal(c.expected_error)})`);
  }
  lines.push('}');
}
for (const id of ['empty-object', 'newline-field', 'nel-field', 'feff-only-field']) assert.ok(ids.has(id));
const output = lines.join('\n') + '\n';
const path = 'src/value_contract/corpus.generated_test.mbt';
if (process.argv.includes('--write')) writeFileSync(path, output);
else assert.equal(readFileSync(path, 'utf8'), output, 'value-contract corpus tests are stale');
console.log(`${ids.size} value-contract cases and embedded contract schemas verified.`);
