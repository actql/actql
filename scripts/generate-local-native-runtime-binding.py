"""Generate the existing private Runtime C/ctypes binding; no permission logic.

The closed declaration binds the actual MoonBit callback root. The C shim is
independently checked for parameter names and types, including same-type order.
Actual emitted C and dynamic-library probes remain separate verification.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DECLARATION = ROOT / 'scripts/local-native-runtime-binding.json'
ENTRY = ROOT / 'src/platform_native/installed_arena_entry'
C_TYPES = {'host': 'actql_control_host *', 'read': 'actql_parent_read *',
           'runtime': 'actql_packaged_runtime *', 'reply': 'actql_packaged_runtime_reply *',
           'host_slot': 'actql_control_host **', 'read_slot': 'actql_parent_read **',
           'runtime_slot': 'actql_packaged_runtime **',
           'reply_slot': 'actql_packaged_runtime_reply **',
           'utf16': 'const uint16_t *', 'i32': 'int32_t', 'int': 'int'}
PY_TYPES = {k: 'c_void_p' for k in ('host', 'read', 'runtime', 'reply')}
PY_TYPES.update({k: 'POINTER(c_void_p)' for k in
                ('host_slot', 'read_slot', 'runtime_slot', 'reply_slot')})
PY_TYPES.update({'utf16': 'POINTER(c_uint16)', 'i32': 'c_int32', 'int': 'c_int'})


def norm(text: str) -> str:
    return re.sub(r'\s+', '', text)


def outputs(root: Path = ROOT) -> dict[Path, str]:
    raw = (root / DECLARATION.relative_to(ROOT)).read_bytes()
    body = json.loads(raw)
    if type(body['version']) is not int or body['version'] != 1 or body['calling_convention'] != 'C':
        raise ValueError('Unsupported private Runtime binding')
    moon = (root / body['callback_source']).read_text()
    callback = re.search(r'extern "C" fn register_original_packaged_runtime_roots\(.*?= "actql_native_control_register_packaged_runtime_roots"', moon, re.S)
    if callback is None or norm(callback[0]) != norm(body['callback_declaration']):
        raise ValueError('Original MoonBit Runtime callback binding changed')
    digest = hashlib.sha256(raw).hexdigest()
    header = ['/* Generated by scripts/generate-local-native-runtime-binding.py. */',
              '#ifndef ACTQL_PRIVATE_RUNTIME_ABI_GENERATED_H',
              '#define ACTQL_PRIVATE_RUNTIME_ABI_GENERATED_H',
              '#define ACTQL_PACKAGED_RUNTIME_BINDING_VERSION 1',
              '#define ACTQL_PACKAGED_RUNTIME_BINDING_SHA256 "' + digest + '"',
              'int32_t actql_packaged_runtime_binding_version(void);',
              'int32_t actql_packaged_runtime_binding_byte(int32_t index);']
    python = ['"""Generated private same-library declarations; do not edit."""',
              'from ctypes import POINTER, c_int, c_int32, c_uint16, c_void_p', '',
              'from typing import Any', '',
              'BINDING_VERSION = 1', 'BINDING_SHA256 = ' + repr(digest), '',
              'PARAMETERS = {']
    shim = (root / ENTRY.relative_to(ROOT) / 'packaged_runtime_shim.c').read_text()
    names = []
    for fn in body['functions']:
        name = 'actql_packaged_runtime_' + fn['name']
        names.append(name)
        args = fn['parameters']
        parameters = ', '.join(C_TYPES[p['type']] + ' ' + p['name'] for p in args)
        declaration = C_TYPES[fn['result']] + ' ' + name + '(' + parameters + ')'
        implementation = re.search(r'\b(int32_t|int)\s+' + re.escape(name) + r'\s*\(([^()]*)\)\s*\{', shim)
        if implementation is None or norm(implementation[1] + ' ' + name + '(' + implementation[2] + ')') != norm(declaration):
            raise ValueError('Native Runtime shim parameter binding changed: ' + name)
        header.append(declaration + ';')
        python.append('    ' + repr(fn['name']) + ': ' + repr(tuple((p['name'], p['type'], p['meaning']) for p in args)) + ',')
    actual = set(re.findall(r'\b(?:int32_t|int)\s+(actql_packaged_runtime_\w+)\s*\(', shim))
    if actual != set(names) | {'actql_packaged_runtime_binding_version', 'actql_packaged_runtime_binding_byte'}:
        raise ValueError('Unknown or missing Native Runtime boundary symbol')
    header.extend(['#endif', ''])
    python += ['}', '', 'def bind(library: Any) -> dict[str, Any]:',
               '    """Reject another compiled declaration before any Owner operation."""',
               '    try:',
               '        version = library.actql_packaged_runtime_binding_version',
               '        byte = library.actql_packaged_runtime_binding_byte',
               '    except AttributeError:',
               '        raise ValueError("Unsupported original Native Runtime binding") from None',
               '    version.argtypes, version.restype = [], c_int32',
               '    byte.argtypes, byte.restype = [c_int32], c_int32',
               '    if (version() != BINDING_VERSION or',
               '            bytes(byte(i) for i in range(64)) != BINDING_SHA256.encode("ascii")):',
               '        raise ValueError("Unsupported original Native Runtime binding")',
               '    calls = {}']
    for fn in body['functions']:
        name = fn['name']
        python += ['    call = library.actql_packaged_runtime_' + name,
                   '    call.argtypes = [' + ', '.join(PY_TYPES[p['type']] for p in fn['parameters']) + ']',
                   '    call.restype = ' + PY_TYPES[fn['result']],
                   '    calls[' + repr(name) + '] = call']
    python += ['    return calls', '']
    return {ENTRY / 'packaged_runtime_abi.generated.h': '\n'.join(header),
            ROOT / 'packages/python-sdk/src/actql_sdk/_local_native_runtime_abi.py': '\n'.join(python)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, rendered in outputs().items():
        if args.check:
            if path.read_text() != rendered:
                raise SystemExit('Private Native Runtime binding is stale: ' + str(path))
        else:
            path.write_text(rendered)
    print('Private Native Runtime C/ctypes declaration is current')
