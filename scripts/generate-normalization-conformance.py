#!/usr/bin/env python3
"""Retain independent NFKC expectations from the pinned Unicode 16 corpus."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
UCD = ROOT / 'vendor/unicode/16.0.0'
source = UCD / 'NormalizationTest.txt'
expected = json.loads((UCD / 'manifest.json').read_text())['sha256'][source.name]
if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
    raise ValueError('NormalizationTest pin mismatch')
rows = []
for line in source.read_text().splitlines():
    body = line.split('#')[0].strip()
    if body and not body.startswith('@'):
        rows.append(body.split(';')[:5])

def quote(sequence):
    return '"' + ''.join('\\u{' + cp + '}' for cp in sequence.split()) + '"'

out = [
    '// Generated by scripts/generate-normalization-conformance.py.',
    '// Independent Unicode 16 NormalizationTest c1 -> c4 expectations.',
    '// See vendor/unicode/16.0.0/LICENSE.txt.',
]
for start in range(0, len(rows), 250):
    out.extend(['', '///|',
                f'test "bounded Unicode NFKC corpus {start // 250 + 1}" {{',
                '  for (source, expected) in ['])
    for columns in rows[start:start + 250]:
        out.append(f'    ({quote(columns[0])}, {quote(columns[3])}),')
    out.extend(['  ] {',
                '    assert_eq(normalization_fixture(source, false), expected)',
                '  }', '}'])
path = ROOT / 'src/canonical_value/normalization_conformance_wbtest.mbt'
content = '\n'.join(out) + '\n'
if '--check' in sys.argv:
    if not path.exists() or path.read_text() != content:
        raise SystemExit('normalization conformance fixture stale')
else:
    path.write_text(content)
print(f'{len(rows)} independent Unicode normalization cases')
