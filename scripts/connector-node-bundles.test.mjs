test('RelA bridge uses the exact shared body with package-local provider selection', t => {
  const sharedPath = fileURLToPath(
    new URL('../src/connectors_builtin_node/client_program_bridge.mbt', import.meta.url));
  if (!existsSync(sharedPath)) {
    t.skip('the JS-only Host subset intentionally omits MoonBit bridge sources');
    return;
  }
  const shared = readFileSync(sharedPath, 'utf8');
  const rela = readFileSync(fileURLToPath(
    new URL('../src/connectors_builtin_node_rela/client_program_bridge.mbt', import.meta.url)), 'utf8');
  assert.equal(rela,
    '// Generated by scripts/connector-node-bundles.mjs; edit the common bridge.\n\n' + shared);
  assert.ok(shared.includes('selected_client_sga_providers('));
  assert.equal((shared.match(/provider_factory=installed_client_family_providers/g) ?? [])
    .length, 4, 'all standard memory/retained factories share family installation');
  assert.ok(!shared.includes('SELECTED_SGA_PROVIDER_BEGIN'));
  for (const selected of ['connectors_builtin_node', 'connectors_builtin_node_rela']) {
    const source = readFileSync(fileURLToPath(
      new URL(`../src/${selected}/client_program_selection.mbt`, import.meta.url)), 'utf8');
    assert.ok(source.includes('fn selected_client_sga_providers('));
    assert.ok(source.includes('fn installed_client_family_providers('));
  }
});

test('Node installation touches only the configured module subset', async () => {
  const setup = {};
  const registration = {};
  const task = {};
  let executions = 0;
  const moon = new Proxy({
    strategyHostBeginManagedFailureProgress: () => ({}),
    strategyHostRecordManagedFailureAdditionalClosed: () => true,
    strategyHostRecordManagedFailureOperationsCloseAttempted: () => true,
    strategyHostRecordManagedFailureOperationsClosed: () => true,
    strategyHostRecordManagedFailureCleanupStopped: () => true,
    strategyHostRecordManagedFailureExecutionSettled: () => true,
    strategyHostRecordManagedFailureCleanupRefreshed: () => true,
    strategyHostManagedFailureAction: () => 5,
    strategyHostModules: value => { assert.equal(value, setup); return ['local']; },
    strategyModule_local_Registration: value => { assert.equal(value, setup); return registration; },
    strategyHostRegistrationSelectionKey: value => {
      assert.equal(value, registration);
      return 'local-test';
    },
    strategyModule_local_Dispatch: (owner, value) => {
      assert.equal(owner, setup); assert.equal(value, task); executions++;
      return {inputs: [],
        advance: () => ({complete: true, progress: 0n, work: 0n}),
        settle() {}, complete() {},
        guard_usage: () => [0, 0, 0], close() {}};
    },
  }, {
    get(target, key) {
      assert.ok(Object.hasOwn(target, key), `Absent module accessed ${String(key)}`);
      return target[key];
    },
  });
  const options = new Proxy({}, {get() { throw new Error('Absent module read settings'); }});
  const entries = await installStrategyContributions(moon, setup, value => value, {duckdb: options});
  assert.equal(entries.length, 1);
  assert.equal(entries[0].registration, registration);
  await entries[0].run(task);
  assert.equal(executions, 1);
  assert.equal(entries[0].finish, undefined);
  assert.ok(Object.isFrozen(entries));
});

test('empty installation invokes no factory and malformed subsets fail before any factory', async () => {
  for (const keys of [[], ['local', 'local'], ['local', 'not-installed'], undefined]) {
    let configured = 0;
    const moon = {
      strategyHostModules: () => keys,
      strategyModule_local_Registration: () => { configured++; return {}; },
    };
    if (Array.isArray(keys) && keys.length === 0) {
      assert.deepEqual(await installStrategyContributions(moon, {}, x => x), []);
    } else {
      await assert.rejects(installStrategyContributions(moon, {}, x => x), /unique Node implementation/);
    }
    assert.equal(configured, 0);
  }
});

test('connector host manifests generate the installed connector table and refuse malformed declarations', async t => {
  const {mkdtempSync, mkdirSync, writeFileSync, rmSync} = await import('node:fs');
  const {join} = await import('node:path');
  const {tmpdir} = await import('node:os');
  const {checkHostBundle, generateInstallations} = await import('./connector-node-bundles.mjs');
  const root = fileURLToPath(new URL('../', import.meta.url));
  if (!existsSync(join(root, 'src/connectors/salesforce/host-bundle.json'))) {
    t.skip('the JS-only Host subset intentionally omits connector manifests');
    return;
  }
  const salesforce = checkHostBundle(root, 'salesforce',
    join(root, 'src/connectors/salesforce/host-bundle.json'));
  assert.equal(salesforce.source.profileVersion, 'actql-installed-salesforce-source/0.1');
  const generated = readFileSync(join(root, 'adapters/connectors-builtin/installations.generated.mjs'), 'utf8');
  assert.equal(generated, generateInstallations([salesforce],
    join(root, 'adapters/connectors-builtin/installations.generated.mjs'), root));
  assert.match(generated, /^\/\/ Generated by scripts\/connector-node-bundles.mjs/);
  assert.doesNotMatch(readFileSync(join(root, 'adapters/host-node/installed-source.mjs'), 'utf8')
    .replace(/\/\/[^\n]*/g, ''), /salesforce/i, 'the common Host names no provider');

  const scratch = mkdtempSync(join(tmpdir(), 'actql-host-bundle-'));
  try {
    const write = (manifest, name = 'example') => {
      const directory = join(scratch, 'src/connectors', name);
      mkdirSync(directory, {recursive: true});
      const path = join(directory, 'host-bundle.json');
      writeFileSync(path, JSON.stringify(manifest));
      return path;
    };
    mkdirSync(join(scratch, 'src/connectors/example/host_node'), {recursive: true});
    writeFileSync(join(scratch, 'src/connectors/example/host_node/moon.pkg'),
      'supported_targets = "js"\n\npkgtype(kind: "foreign_library")\n');
    mkdirSync(join(scratch, 'adapters/connectors/example/host'), {recursive: true});
    writeFileSync(join(scratch, 'adapters/connectors/example/host/installed-example-source.mjs'),
      'export function checkExample() {}\nexport async function partsExample() {}\n' +
      'export async function loadExample() {}\n');
    const valid = () => ({installation: {
      registration: 'example', revision: 'example/0.1',
      providerBundle: 'connectors/example/host_node', responseHeaders: ['link'],
      source: {profileVersion: 'actql-installed-example-source/0.1',
        module: 'adapters/connectors/example/host/installed-example-source.mjs',
        exports: {check: 'checkExample', identityParts: 'partsExample', load: 'loadExample'}}}});
    const checked = checkHostBundle(scratch, 'example', write(valid()));
    assert.equal(checked.registration, 'example');
    assert.match(generateInstallations([checked, salesforce],
      join(scratch, 'adapters/connectors-builtin/installations.generated.mjs'), scratch),
    /import\("\.\.\/connectors\/example\/host\/installed-example-source\.mjs"\)/);
    assert.throws(() => generateInstallations([checked, {...checked, name: 'twin'}],
      join(scratch, 'adapters/connectors-builtin/installations.generated.mjs'), scratch),
    /Duplicate installed source profile version/);
    const mutate = (change, reason) => {
      const manifest = valid();
      change(manifest.installation);
      assert.throws(() => checkHostBundle(scratch, 'example', write(manifest)),
        new RegExp(`Invalid Host bundle manifest \\(${reason}\\)`), reason);
    };
    mutate(installation => { installation.extra = 1; }, 'keys');
    mutate(installation => { installation.registration = 'other'; }, 'registration');
    mutate(installation => { installation.revision = 'example-0.1'; }, 'revision');
    mutate(installation => { installation.providerBundle = 'connectors/other/host_node'; }, 'providerBundle');
    mutate(installation => { installation.providerBundle = 'connectors/example/missing'; }, 'providerBundle package');
    mutate(installation => { installation.responseHeaders = ['Link']; }, 'responseHeaders');
    mutate(installation => { installation.responseHeaders = ['link', 'link']; }, 'responseHeaders');
    mutate(installation => { installation.responseHeaders = ['set-cookie']; }, 'responseHeaders');
    mutate(installation => { installation.source.profileVersion = 'actql-installed-example-source'; }, 'profileVersion');
    mutate(installation => { installation.source.module = 'adapters/host-node/installed-source.mjs'; }, 'module');
    mutate(installation => { delete installation.source.exports.load; }, 'exports keys');
    mutate(installation => { installation.source.exports.extra = 'x'; }, 'exports keys');
    mutate(installation => { installation.source.exports.load = 'missingExport'; }, 'export load');
    writeFileSync(join(scratch, 'src/connectors/example/host_node/moon.pkg'),
      'supported_targets = "+js+wasm+native"\n');
    mutate(() => {}, 'providerBundle kind');
  } finally {
    rmSync(scratch, {recursive: true, force: true});
  }
});
