import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { machineCid } from './actql-spec-family.mjs';

const root = new URL('../', import.meta.url);
export function validateRegistry(body, policy) {
  assert.deepEqual(Object.keys(body).sort(), ['author_guard_laws', 'law_ids', 'version']);
  assert.equal(body.version, 'actql-bound-law-registry/0.1');
  assert.ok(Array.isArray(body.law_ids) && body.law_ids.length > 0);
  assert.ok(body.law_ids.every(id => typeof id === 'string' && /^actql\.[a-z]+\.[a-z][a-z0-9.-]*$/.test(id)));
  assert.deepEqual(body.law_ids, [...new Set(body.law_ids)].sort());
  assert.deepEqual(body.law_ids.filter(id => id.startsWith('actql.host.')),
    Object.values(policy.host_witness_laws).map(law => law.law_id).sort());
  assert.deepEqual(Object.keys(body.author_guard_laws).sort(), Object.keys(guardScopes).sort());
  for (const rule of Object.values(body.author_guard_laws)) {
    assert.deepEqual(Object.keys(rule).sort(), ['field', 'law_id', 'unit']);
    assert.ok(body.law_ids.includes(rule.law_id) && rule.law_id.startsWith('actql.guard.'));
    assert.ok(Object.hasOwn(guardUnits, rule.unit));
    assert.ok(['max_output_rows', 'max_items', 'max_bytes', 'max_matches_per_key'].includes(rule.field));
    assert.equal(rule.unit, {max_output_rows:'rows', max_items:'array_items',
      max_bytes:'bytes', max_matches_per_key:'matches_per_key'}[rule.field]);
  }
  return machineCid(body);
}

const guardScopes = {join:'JoinOutputRows', cross_join:'CrossJoinOutputRows',
  interval_join:'IntervalJoinOutputRows', nest:'NestedArrayItems',
  array_agg:'AggregateArrayItems(_)', string_agg:'AggregateStringBytes(_)',
  sequence_matches:'SequenceMatchesPerKey', sequence_output:'SequenceOutputRows',
  components:'ComponentOutputRows', traverse:'TraverseOutputRows', shortest_path:'ShortestOutputRows'};
const guardUnits = {rows:'Rows', bytes:'Bytes', array_items:'ArrayItems', matches_per_key:'MatchesPerKey'};

export function renderGuardLaws(body) {
  const arms = Object.entries(guardScopes).map(([key, scope]) => {
    const rule = body.author_guard_laws[key];
    return `    ${scope} => (${JSON.stringify(rule.law_id)}, @derivation.${guardUnits[rule.unit]}, ${JSON.stringify(rule.field)})`;
  }).join('\n');
  return `// Generated by scripts/capacity-law-registry.mjs. Do not edit.\n\n///|\nfn guard_law(scope : GuardScope) -> (String, @derivation.BoundUnit, String) {\n  match scope {\n${arms}\n  }\n}\n\n///|\n/// Governing source law only; source identity and enforcement remain required.\npub fn author_guard_law(v : AuthorGuard) -> @law.RegisteredLaw {\n  @law.admit(guard_law(v.scope).0).unwrap()\n}\n\n///|\npub fn author_guard_unit(v : AuthorGuard) -> @derivation.BoundUnit {\n  guard_law(v.scope).1\n}\n\n///|\npub fn author_guard_field(v : AuthorGuard) -> String {\n  guard_law(v.scope).2\n}\n`;
}

export function renderRegistry(body) {
  const arms = body.law_ids.map(id => `    ${JSON.stringify(id)} => Some(RegisteredLaw(law))`).join('\n');
  return `// Generated by scripts/capacity-law-registry.mjs. Do not edit.\n\n///|\nstruct RegisteredLaw(String)\n\n///|\n/// Registry membership only, not source integrity or valid law application.\npub fn admit(law : String) -> RegisteredLaw? {\n  match law {\n${arms}\n    _ => None\n  }\n}\n\n///|\npub fn name(law : RegisteredLaw) -> String { law.0 }\n`;
}

export function loadRegistry() {
  return {
    body: JSON.parse(readFileSync(new URL('spec/contracts/actql-bound-law-registry.json', root), 'utf8')),
    policy: JSON.parse(readFileSync(new URL('spec/contracts/actql-capacity-host-policy.json', root), 'utf8')),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { body, policy } = loadRegistry();
  const cid = validateRegistry(body, policy);
  const path = new URL('src/capacity_law/registry.generated.mbt', root);
  const expected = renderRegistry(body);
  if (process.argv.includes('--write')) writeFileSync(path, expected);
  else assert.equal(readFileSync(path, 'utf8'), expected, 'Stale capacity law registry');
  const guardPath = new URL('src/pipeline_typing/guard_laws.generated.mbt', root);
  if (process.argv.includes('--write')) writeFileSync(guardPath, renderGuardLaws(body));
  else assert.equal(readFileSync(guardPath, 'utf8'), renderGuardLaws(body), 'Stale author guard laws');
  console.log(JSON.stringify({ laws: body.law_ids.length, cid, law_application_validated: false }));
}
