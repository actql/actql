import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {machineCid} from './actql-spec-family.mjs';

const protocolPath = 'spec/contracts/actql-protocol-schemas.json';
const manifestPath = 'spec/spec-family.json';
const read = path => JSON.parse(readFileSync(path, 'utf8'));
const text = {type: 'string', minLength: 1};
const cid = {type: 'string', pattern: '^sha256:[0-9a-f]{64}$'};
const object = properties => ({type: 'object', additionalProperties: false,
  required: Object.keys(properties), properties});
const array = (items, minItems = 1) => ({type: 'array', minItems, items});
const probability = {type: 'number', minimum: 0, maximum: 1};

export const initialJevProfile = Object.freeze({
  format: 'actql.decision_probability_profile/0.1',
  profile: 'typesafe_jev_2dp', decimal_precision: 2,
  half_unit: 0.005, arithmetic_margin: 0.000001,
  grid_margin_scaled: 1e-10,
});

export function decisionSchemas(oldTask) {
  // The old registered schema and its pin remain untouched.
  const task = structuredClone(oldTask);
  task.required = task.required.filter(name => name !== 'generation_config');
  task.properties.schema = {const: 'actql.model_task/0.2'};
  task.properties.task_kind = {enum: ['structured_generate', 'decision']};
  task.properties.decision_config = object({
    answer_profile: {const: 'actql.decision_answers/0.1'},
    probability_source: {const: 'native'},
    distribution_policy: {const: 'required_for_choice_and_score'},
  });
  task.oneOf = [
    {properties: {task_kind: {const: 'structured_generate'}, decision_config: false},
      required: ['generation_config']},
    {properties: {task_kind: {const: 'decision'}, generation_config: false},
      required: ['decision_config']},
  ];
  const description = {type: 'string'};
  const common = {id: text, instructions: description};
  const prompt = object({format: {const: 'actql.decision_prompt/0.1'},
    state_input: text, questions: array({oneOf: [
      object({...common, type: {const: 'choice'}, options: array(object({id: text, description}))}),
      object({...common, type: {const: 'score'}, levels: array(description, 2)}),
      object({...common, type: {const: 'boolean'}}),
    ]})});
  const nullableArray = items => ({type: ['array', 'null'], items});
  const answers = {type: 'object', minProperties: 1, additionalProperties: {oneOf: [
    object({choice: text, probabilities: nullableArray(object({option: text, probability}))}),
    object({score: {type: 'number', minimum: 0}, probabilities: nullableArray(object({
      level: {type: 'integer', minimum: 0}, probability}))}),
    object({probability}),
  ]}};
  const profile = object(Object.fromEntries(Object.entries(initialJevProfile)
    .map(([name, value]) => [name, {const: value}])));
  return {task, prompt, answers, profile};
}

export function generateDecisionProfile() {
  return `// Generated by scripts/decision-contract.mjs; do not edit.

///|
/// Physical profile selection alone proves no native provider capability.
pub fn initial_jev_decision_profile() -> DecisionProbabilityProfile {
  {
    cid: ${JSON.stringify(machineCid(initialJevProfile))},
    scale: 100.0,
    half_unit: 0.005,
    arithmetic_margin: 0.000001,
    grid_margin_scaled: 0.0000000001,
  }
}

///|
pub fn decision_probability_profile_cid(value : DecisionProbabilityProfile) -> String {
  value.cid
}
`;
}

export function checkDecisionSchemas(registry) {
  const {task, prompt, answers, profile} = decisionSchemas(registry.schemas.model_task);
  assert.deepEqual(registry.schemas.model_task_v02, task);
  assert.equal(registry.schema_cids.model_task_v02, machineCid(task));
  for (const [name, value] of Object.entries({decision_prompt: prompt,
    decision_answers: answers, decision_probability_profile: profile})) {
    assert.deepEqual(registry.artifact_schemas[name], value);
    assert.equal(registry.artifact_schema_cids[name], machineCid(value));
  }
  assert.equal(registry.registry_cid, machineCid(registry.schemas));
  assert.equal(registry.artifact_registry_cid, machineCid(registry.artifact_schemas));
  assert.equal(readFileSync('src/check_environment/decision_profile.generated.mbt', 'utf8'),
    generateDecisionProfile());
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const registry = read(protocolPath);
  if (process.argv.includes('--write')) {
    const manifest = read(manifestPath);
    const owner = manifest.documents.find(item => item.document_id === 'contracts');
    assert.ok(owner);
    let source = readFileSync(owner.path, 'utf8');
    const anchor = source.split('\n').find(line => line.startsWith(
      '../../../spec/contracts/actql-protocol-schemas.json#/schemas/model_task '));
    assert.ok(anchor);
    const {task, prompt, answers, profile} = decisionSchemas(registry.schemas.model_task);
    const additions = [];
    for (const [collection, pins, name, value] of [
      ['schemas', 'schema_cids', 'model_task_v02', task],
      ['artifact_schemas', 'artifact_schema_cids', 'decision_prompt', prompt],
      ['artifact_schemas', 'artifact_schema_cids', 'decision_answers', answers],
      ['artifact_schemas', 'artifact_schema_cids', 'decision_probability_profile', profile],
    ]) {
      const pointer = `/${collection}/${name}`;
      const pin = machineCid(value);
      registry[collection][name] = value;
      registry[pins][name] = pin;
      const reference = owner.machine_contracts.find(item => item.path === protocolPath && item.pointer === pointer);
      if (reference) {
        source = source.replace(`../../../${protocolPath}#${pointer} ${reference.cid}`,
          `../../../${protocolPath}#${pointer} ${pin}`);
        reference.cid = pin;
      } else {
        owner.machine_contracts.push({path: protocolPath, pointer, cid: pin, version: registry.version});
        additions.push(`../../../${protocolPath}#${pointer} ${pin}`);
      }
    }
    registry.registry_cid = machineCid(registry.schemas);
    registry.artifact_registry_cid = machineCid(registry.artifact_schemas);
    if (additions.length) source = source.replace(anchor, anchor + '\n' + additions.join('\n'));
    writeFileSync(protocolPath, JSON.stringify(registry, null, 2) + '\n');
    writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    writeFileSync(owner.path, source);
    writeFileSync('src/check_environment/decision_profile.generated.mbt', generateDecisionProfile());
  }
  checkDecisionSchemas(registry);
}
