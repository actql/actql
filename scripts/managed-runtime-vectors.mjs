import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {machineCid} from './actql-spec-family.mjs';

const contract = JSON.parse(readFileSync('spec/contracts/actql-managed-retained-execution.json', 'utf8'));
const dependency = contract.dependencies.fixed_compute_capacity;
assert.equal(dependency.path, 'spec/contracts/actql-fixed-compute-capacity.json');
assert.equal(dependency.pointer, '');
assert.equal(dependency.cid,
  machineCid(JSON.parse(readFileSync(dependency.path, 'utf8'))),
  'managed profile fixed-compute capacity dependency is stale');
const pin = machineCid(contract);
const heading = '// Generated by scripts/managed-runtime-vectors.mjs --write. Do not edit.\n';
const outputs = [
  ['src/execution_relation/managed_profile_pin.generated.mbt', `${heading}\n///|\nlet selected_managed_profile_cid : String = ${JSON.stringify(pin)}\n`],
  ['src/execution_relation/managed_profile_body.generated_wbtest.mbt', `${heading}
///|
fn managed_profile_body() -> @identity.CanonicalValue raise {
  @identity.from_json(
    @json.parse(
      ${JSON.stringify(JSON.stringify(contract))},
    ),
    10000,
    100,
    100000,
  )
}
`],
];
for (const [path, body] of outputs) {
  if (process.argv.includes('--write')) writeFileSync(path, body);
  else assert.equal(readFileSync(path, 'utf8'), body, `stale ${path}`);
}
