import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {canonicalText,verifyIdentity} from './check-canonical-json.mjs';
const corpus=JSON.parse(readFileSync('portability/corpus/pushdown-contract.json','utf8'));
assert.equal(corpus.version,'actql-pushdown-contract-vectors/0.1');
const lines=['// Generated by scripts/check-pushdown-contracts.mjs; do not edit.'];
for(const c of corpus.cases){
  if(c.accepted) verifyIdentity(c.body,c.expected_body_cid);
  lines.push('', '///|', `test ${JSON.stringify('pushdown contract corpus: '+c.id)} {`,
    `  assert_pushdown_case(@json.parse(${JSON.stringify(canonicalText(c.body))}), ${JSON.stringify(c.carrier)}, @json.parse(${JSON.stringify(canonicalText(c.operations))}), ${c.accepted})`, '}');
}
const path='src/check_environment/pushdown_vectors.generated_test.mbt',text=lines.join('\n')+'\n';
if(process.argv.includes('--write'))writeFileSync(path,text);
assert.equal(readFileSync(path,'utf8'),text);
console.log(`${corpus.cases.length} fixed pushdown admission cases verified.`);
