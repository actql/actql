const cid = text => 'sha256:' + createHash('sha256').update(text, 'utf8').digest('hex');

function normalize(text) {
  assert.ok(text.isWellFormed(), 'unpaired surrogate');
  return text.normalize('NFC').replace(/\r\n?/g, '\n');
}

// Independent scalar spelling, normalization, ordering and hashing oracle.
// Product output is never used to update expectations.
export function canonicalText(value) {
  if (value === null || typeof value === 'boolean') return JSON.stringify(value);
  if (typeof value === 'number') {
    assert.ok(Number.isFinite(value) && !Object.is(value, -0), 'invalid number');
    return JSON.stringify(value);
  }
  if (typeof value === 'string') {
    assert.ok(value.isWellFormed(), 'unpaired surrogate');
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) return '[' + value.map(canonicalText).join(',') + ']';
  assert.ok(value && typeof value === 'object', 'JSON value');
  const pairs = Object.entries(value).map(([key, item]) => [normalize(key), item]);
  assert.equal(new Set(pairs.map(([key]) => key)).size, pairs.length, 'normalized key collision');
  pairs.sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  return '{' + pairs.map(([key, item]) => JSON.stringify(key) + ':' + canonicalText(item)).join(',') + '}';
}

export function verifyIdentity(value, expectedCid, expectedText) {
  assert.match(expectedCid, /^sha256:[0-9a-f]{64}$/);
  const text = canonicalText(value);
  if (expectedText !== undefined) assert.equal(text, expectedText, 'canonical bytes');
  assert.equal(cid(text), expectedCid, 'canonical CID');
  return text;
}

export function resolvePointer(value, pointer) {
  assert.ok(pointer === '' || pointer.startsWith('/'), 'JSON Pointer');
  for (const part of pointer.split('/').slice(1)) {
    assert.ok(!/~(?:[^01]|$)/.test(part), 'JSON Pointer escape');
    const key = part.replace(/~1/g, '/').replace(/~0/g, '~');
    assert.ok(value !== null && typeof value === 'object' && Object.hasOwn(value, key), 'missing pointer');
    value = value[key];
  }
  return value;
}

function literal(value) {
  return '"' + [...value].map(char => {
    const cp = char.codePointAt(0);
    if (cp < 32 || cp > 126) return '\\u{' + cp.toString(16) + '}';
    return char === '"' || char === '\\' ? '\\' + char : char;
  }).join('') + '"';
}

function budget(value, depth = 0) {
  if (value === null || typeof value !== 'object') return { nodes: 1, depth };
  let nodes = 1;
  let peak = depth + 1;
  for (const child of Object.values(value)) {
    const b = budget(child, depth + 1);
    nodes += b.nodes;
    peak = Math.max(peak, b.depth);
  }
  return { nodes, depth: peak };
}

export function generateTests(fixtures) {
  assert.ok(Array.isArray(fixtures) && fixtures.length > 0);
  const seen = new Set();
  const lines = [
    '// Generated by scripts/check-canonical-json.mjs --write. Do not edit.',
    '// Fixed corpus and existing specification pins are the expected identities.',
  ];
  for (const f of fixtures) {
    assert.ok(typeof f.id === 'string' && f.id.length > 0 && !seen.has(f.id), 'fixture identity');
    seen.add(f.id);
    const expected = verifyIdentity(f.value, f.cid, f.text);
    const source = JSON.stringify(f.value);
    const points = [...source];
    const chunks = [];
    // Keep owned identifiers contiguous in generated source so source scanners
    // see the same version as the JSON value, rather than a truncated prefix.
    const identifiers = [...source.matchAll(/\b(?:(?:actql|aoa)[A-Za-z0-9_.-]*\/v?[0-9]+(?:\.[0-9]+)*(?:[-+][A-Za-z0-9.-]+)?|(?:actql|aoa)\.[A-Za-z0-9_.-]+\.v[0-9]+(?:\.[0-9]+)*(?:[-+][A-Za-z0-9.-]+)?|urn:(?:actql|aoa):[A-Za-z0-9_.:-]+:[0-9]+(?:\.[0-9]+)*(?:[-+][A-Za-z0-9.-]+)?)/gu)]
      .map(match => ({start: [...source.slice(0, match.index)].length,
        end: [...source.slice(0, match.index + match[0].length)].length}));
    for (let i = 0, boundary = 1024; i < points.length; boundary += 1024) {
      let end = Math.min(boundary, points.length);
      const split = identifiers.find(token => token.start > i && token.start < end && end < token.end);
      if (split) end = split.start;
      chunks.push(literal(points.slice(i, end).join('')));
      i = end;
    }
    const limits = budget(f.value);
    const bytes = Buffer.byteLength(expected);
    lines.push(
      '', '///|', 'test ' + literal(f.id) + ' {',
      '  let input = @json.parse([\n    ' + chunks.join(',\n    ') + ',\n  ].join(""))',
      '  let value = @canonical_json.from_json(input, ' + limits.nodes + ', ' + limits.depth + ', ' + source.length + ')',
      '  assert_eq(@canonical_json.cid_value(value, ' + bytes + ', ' + limits.nodes + ', ' + limits.depth + '), ' + literal(f.cid) + ')',
      '  assert_eq(@canonical_json.measure_value(value, ' + bytes + ', ' + limits.nodes + ', ' + limits.depth + '), ' + bytes + ')',
    );
    if (f.text !== undefined) {
      lines.push('  assert_eq(@canonical_json.stringify_value(value, ' + bytes + ', ' + limits.nodes + ', ' + limits.depth + '), ' + literal(f.text) + ')');
    }
    lines.push('}');
  }
  return lines.join('\n') + '\n';
}

