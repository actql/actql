// Project existing admission vectors and registry data, never expected output.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {canonicalText} from './check-canonical-json.mjs';

const read = path => readFileSync(path, 'utf8');
const task = JSON.parse(read('src/stage_results/infer_program_test.mbt')
  .match(/let body =\n\s+#\|(.+)/u)[1]);
const source = read('src/run_publication_host/client_infer_prefix_wbtest.mbt')
  .match(/let source =\n\s+#\|(.+)/u)[1];
const {evidence_bundle_cid: ignored, ...base} =
  JSON.parse(read('spec/local-check-environment.json'));
void ignored;
const body = {...base, model_task_contracts: [task]};
const evidenceCid = `sha256:${createHash('sha256')
  .update(canonicalText(body)).digest('hex')}`;
const aoa = JSON.parse(read('spec/contracts/actql-aoa.json'));
const values = [
  ['infer_fixture_environment', canonicalText({...body,
    evidence_bundle_cid: evidenceCid})],
  ['infer_fixture_environment_cid', evidenceCid],
  ['infer_fixture_program', source],
  ['infer_fixture_registry', canonicalText(JSON.parse(read(
    aoa.pipeline_registry_file)))],
  ['infer_fixture_values', canonicalText(aoa.execution_contracts['REL.values'])],
];
let generated = '// Generated by scripts/infer-host-fixtures.mjs; admission data only.\n';
for (const [name, value] of values) {
  generated += `\n///|\nlet ${name} : String =\n  #|${value}\n`;
}
assert.ok(process.env.MOON_HOME, 'The pinned MOON_HOME is required');
generated = execFileSync(join(process.env.MOON_HOME, 'bin/moonfmt'), ['-'],
  {input: generated, encoding: 'utf8'});
const target = 'src/client_infer_host/fixture.generated_wbtest.mbt';
if (process.argv.includes('--write')) writeFileSync(target, generated);
assert.equal(read(target), generated, 'Stale bounded Infer admission fixture');
console.log('Bounded Infer admission fixture matches its existing owners.');
