import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';

export function generate(corpus) {
  assert.equal(corpus.version, 'actql-value-admission-vectors/0.1');
  assert.ok(Array.isArray(corpus.cases) && corpus.cases.length > 0);
  const outcomes = new Set(['accepted', 'UnexpectedNull', 'WrongType', 'InvalidDecimal', 'InvalidDate', 'InvalidTimestamp', 'UnknownField', 'MissingField', 'ArrayConstraint', 'VectorDimension', 'UnsupportedReference']);
  const ids = new Set();
  const lines = ['// Generated by scripts/check-value-admission.mjs --write. Do not edit.'];
  for (const c of corpus.cases) {
    assert.ok(typeof c.id === 'string' && c.id.length > 0 && !ids.has(c.id));
    ids.add(c.id);
    assert.ok(c.contract && typeof c.contract === 'object' && !Array.isArray(c.contract));
    assert.ok(Object.hasOwn(c, 'value'));
    assert.ok(outcomes.has(c.expected));
    if (Object.hasOwn(c, 'coefficient')) {
      assert.equal(c.expected, 'accepted');
      assert.equal(c.contract.type, 'decimal');
      assert.ok(typeof c.coefficient === 'string' && /^(?:0|-?[1-9][0-9]*)$/.test(c.coefficient));
    }
    lines.push('', '///|', `test ${literal('value admission corpus: ' + c.id)} {`,
      `  let c = contract(${literal(JSON.stringify(c.contract))})`,
      `  let result = @value_admission.admit(c, owned(parsed(${literal(JSON.stringify(c.value))})), limits())`,
      `  assert_eq(outcome(result), ${literal(c.expected)})`);
    if (Object.hasOwn(c, 'coefficient')) {
      lines.push('  match result.unwrap().value {',
        `    @value_admission.Decimal(value) => assert_eq(value.coefficient, ${literal(c.coefficient)})`,
        '    _ => assert_true(false)', '  }');
    }
    lines.push('}');
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const corpus = JSON.parse(readFileSync('portability/corpus/value-admission.json', 'utf8'));
  const output = generate(corpus);
  const path = 'src/value_admission/corpus.generated_test.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, output);
  else assert.equal(readFileSync(path, 'utf8'), output, 'value-admission tests are stale');
  console.log(`${corpus.cases.length} value-admission vectors verified; generated tests match fixed expectations.`);
}
