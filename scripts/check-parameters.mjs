import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkParameterSchemas } from './parameter-schema.mjs';

const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';

export function generate(corpus) {
  assert.equal(corpus.version, 'actql-parameter-binding-vectors/0.1');
  assert.ok(Array.isArray(corpus.cases) && corpus.cases.length > 0);
  const outcomes = new Set(['Ready', 'NeedsBindings', 'UnexpectedNull', 'NumericConstraint', 'MissingField', 'UnknownField', 'WrongType', 'DurationConstraint', 'LengthConstraint', 'ArrayConstraint', 'ReservedMetadataKey', 'UnknownType']);
  const ids = new Set();
  const lines = ['// Generated by scripts/check-parameters.mjs --write. Do not edit.'];
  for (const c of corpus.cases) {
    assert.ok(typeof c.id === 'string' && c.id.length > 0 && !ids.has(c.id)); ids.add(c.id);
    for (const field of ['declarations', 'supplied']) assert.ok(c[field] && typeof c[field] === 'object' && !Array.isArray(c[field]));
    assert.ok(outcomes.has(c.expected));
    assert.equal(Object.hasOwn(c, 'missing'), c.expected === 'NeedsBindings');
    if (c.missing) {
      assert.ok(c.missing.length > 0 && c.missing.every(n => typeof n === 'string' && Object.hasOwn(c.declarations, n)));
      assert.deepEqual(c.missing, [...new Set(c.missing)].sort());
    }
    lines.push('', '///|', `test ${literal('parameter corpus: ' + c.id)} {`,
      `  let d = @parameter_binding.read_declarations(Some(cursor(${literal(JSON.stringify(c.declarations))})), limits())`,
      `  let result = match d { Ok(d) => @parameter_binding.bind(d, Some(cursor(${literal(JSON.stringify(c.supplied))})), values_limit()); Err(e) => Err(e) }`,
      `  assert_eq(outcome(result), ${literal(c.expected)})`);
    if (c.missing) lines.push('  match result.unwrap() {', `    @parameter_binding.NeedsBindings(m) => assert_eq(@parameter_binding.missing_names(m), [${c.missing.map(literal).join(', ')}])`, '    _ => assert_true(false)', '  }');
    lines.push('}');
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const read = path => JSON.parse(readFileSync(path, 'utf8'));
  checkParameterSchemas(read('spec/contracts/actql-protocol-schemas.json'), read('spec/contracts/actql-stage-contracts.json'));
  const corpus = read('portability/corpus/parameters.json');
  const output = generate(corpus);
  const path = 'src/parameter_binding/corpus.generated_test.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, output);
  else assert.equal(readFileSync(path, 'utf8'), output, 'Parameter corpus tests are stale');
  console.log(`${corpus.cases.length} Parameter cases and recursive schemas verified.`);
}
