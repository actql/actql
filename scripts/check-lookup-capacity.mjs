import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export function checkLookupCapacity(write=false){
  const c=JSON.parse(readFileSync('portability/corpus/lookup-capacity.json','utf8'));
  const cases=c.cases.map(v=>({...v,body:{lookup_capacity:{...c.base,...v.patch}}}));
  for(const k of Object.keys(c.base)){
    const v={...c.base};delete v[k];
    cases.push({id:'missing-'+k,body:{lookup_capacity:v},accepted:false});
  }
  for(const [id,body,accepted] of [
    ['absent',{},true],['generic-root',{completeness:'complete'},true],
    ['null-component',{lookup_capacity:null},false],['null-body',null,false],
    ['array-body',[],false],['opaque',{literal:{$param:'business'}},true],
  ])cases.push({id,body,accepted});
  const lines=['// Generated by scripts/check-lookup-capacity.mjs --write. Do not edit.'];
  for(const v of cases)lines.push('','///|',`test ${JSON.stringify('lookup capacity '+v.id)} {`,
    `  assert_lookup_capacity_fixture(${JSON.stringify(JSON.stringify(v.body))}, ${v.accepted}, ${v.supports_completeness===true})`,'}');
  const path='src/check_environment/lookup_capacity.generated_test.mbt';
  const text=lines.join('\n')+'\n';
  if(write)writeFileSync(path,text);else assert.equal(readFileSync(path,'utf8'),text);
  return cases.length;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  console.log(`${checkLookupCapacity(process.argv.includes('--write'))} lookup capacity fixtures checked; not acquisition conformance.`);
}
