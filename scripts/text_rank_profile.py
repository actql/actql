def byte_cid(raw):
    return "sha256:" + hashlib.sha256(raw).hexdigest()


def generate(ucd=UCD, corpus_dir=ROOT / "portability/corpus"):
    spec = importlib.util.spec_from_file_location("unicode_inputs", ROOT / "scripts/generate-unicode-tables.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    manifest = json.loads((ucd / "manifest.json").read_text(encoding="utf-8"))
    pins = module.validate_manifest(manifest)
    for name, digest in pins.items():
        if hashlib.sha256((ucd / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f"Unicode hash mismatch: {name}")
    profile = {
        "version": "actql-text-rank-profile/0.1",
        "unicode_version": "16.0.0",
        "unicode_source_sha256": pins,
        "tokenizer_law": TOKENIZER_LAW,
        "numeric_law": NUMERIC_LAW,
    }
    for field, (name, version) in VECTORS.items():
        raw = (corpus_dir / name).read_bytes()
        body = json.loads(raw)
        if body["version"] != version or not body["cases"]:
            raise ValueError(f"Invalid vectors: {name}")
        if "tokenizer" in field and body["unicode_version"] != profile["unicode_version"]:
            raise ValueError("Tokenizer Unicode version mismatch")
        profile[field] = byte_cid(raw)
    # All law strings and keys are ASCII, no numbers require cross-language
    # spelling, and pins refer to exact source/vector bytes, not parsed models.
    return json.dumps(profile, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def check(path=OUT):
    expected = generate()
    if not path.exists() or path.read_bytes() != expected:
        raise ValueError(f"Stale or noncanonical text-rank profile: {path}")
    print("Text-rank profile:", byte_cid(expected))


def moonbit_files():
    def canonical(value):
        return json.dumps(value, sort_keys=True, separators=(",", ":"))

    laws = "// Generated by scripts/text_rank_profile.py.\n"
    for name, law in [("tokenizer", TOKENIZER_LAW), ("numeric", NUMERIC_LAW)]:
        laws += f'///|\nfn {name}_law_cid() -> String {{\n  "{byte_cid(canonical(law).encode())}"\n}}\n'
    # Synthetic blobs test admission integrity, not Unicode provenance or
    # tokenizer/scorer conformance. Expected identities come from hashlib.
    body = json.loads(generate())
    fixtures = ["UnicodeData", "CompositionExclusions", "CaseFolding", "DerivedNormalizationProps", "NormalizationTest", "License", "TokenizerVectors", "NumericVectors"]
    names = ["UnicodeData.txt", "CompositionExclusions.txt", "CaseFolding.txt", "DerivedNormalizationProps.txt", "NormalizationTest.txt", "LICENSE.txt"]
    for kind, name in zip(fixtures, names):
        body["unicode_source_sha256"][name] = hashlib.sha256(kind.encode()).hexdigest()
    body["tokenizer_vectors_bytes_cid"] = byte_cid(b"TokenizerVectors")
    body["numeric_vectors_bytes_cid"] = byte_cid(b"NumericVectors")
    raw = canonical(body)
    test = '// Generated synthetic integrity fixture; not an execution conformance claim.\n'
    test += '///|\nfn fixture() -> String {\n  ' + json.dumps(raw) + '\n}\n'
    test += f'///|\nfn fixture_cid() -> String {{ "{byte_cid(raw.encode())}" }}\n'
    test += '///|\nfn blobs() -> Array[(@text_rank_profile.Dependency, Bytes)] {\n  [\n'
    for kind in fixtures:
        test += f'    (@text_rank_profile.{kind}, @utf8.encode("{kind}")),\n'
    test += '  ]\n}\n'
    base = ROOT / "src/text_rank_profile"
    pipeline_test = test.replace("fn fixture()", "fn text_profile_fixture()").replace(
        "fn fixture_cid()", "fn text_profile_fixture_cid()"
    ).replace("fn blobs()", "fn text_profile_blobs()")
    return {
        base / "laws.generated.mbt": laws,
        base / "fixture.generated_test.mbt": test,
        ROOT / "src/pipeline_typing/text_profile.generated_test.mbt": pipeline_test,
        ROOT / "src/check_environment/text_profile.generated_test.mbt": pipeline_test.replace("@text_rank_profile", "@lexical"),
        ROOT / "src/pipeline_check_context/text_profile.generated_test.mbt": pipeline_test.replace("@text_rank_profile", "@lexical"),
        ROOT / "src/program_check/text_profile.generated_wbtest.mbt": pipeline_test.replace("@text_rank_profile", "@lexical"),
        ROOT / "src/program_check/text_profile.generated_test.mbt": pipeline_test.replace("@text_rank_profile", "@lexical"),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.write:
        expected = generate()
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_bytes(expected)
    for path, text in moonbit_files().items():
        if args.write:
            path.write_text(text, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            raise ValueError(f"Stale generated profile file: {path}")
    check()
