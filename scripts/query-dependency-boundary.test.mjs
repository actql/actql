const dependencies = name => {
  const seen = new Set();
  const pending = imports(name);
  while (pending.length) {
    const dependency = pending.pop();
    if (seen.has(dependency)) continue;
    seen.add(dependency);
    pending.push(...imports(dependency));
  }
  return [...seen];
};

