import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
const corpus = JSON.parse(readFileSync('portability/corpus/local-source-refs.json', 'utf8'));
assert.equal(corpus.version, 'actql-local-source-reference-vectors/0.1');
const contract = JSON.parse(readFileSync('spec/contracts/actql-local-source-reference.json', 'utf8'));
assert.equal(contract.version, 'actql-local-source-reference/0.1');
const syntax = new RegExp(contract.schema.pattern, 'u');
const escape = s => s.replaceAll('~', '~0').replaceAll('/', '~1');
const canonical = s => s.length > 0 && s.isWellFormed() && s === s.normalize('NFC').replace(/\r\n?/g, '\n');
const valid = s => {
  const parts = s.split('/');
  if (parts.length !== 3 || parts[0] !== 'source:local') return false;
  return parts.slice(1).every(p => !/~(?:[^01]|$)/u.test(p) && canonical(p.replaceAll('~1','/').replaceAll('~0','~')));
};
const literal = s => '"' + [...s].map(c => c.codePointAt(0) < 32 || c.codePointAt(0) > 126 ? '\\u{' + c.codePointAt(0).toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c).join('') + '"';
const lines = ['// Generated by scripts/check-local-source-refs.mjs --write. Do not edit.'];
for (const [i,c] of corpus.accepted.entries()) {
  assert.ok(canonical(c.stage) && canonical(c.input));
  assert.equal('source:local/' + escape(c.stage) + '/' + escape(c.input), c.reference);
  assert.ok(valid(c.reference));
  assert.ok(syntax.test(c.reference));
  const bytes = Buffer.byteLength(c.reference);
  lines.push('', '///|', `test "local source reference ${i}" {`,
    `  let v = @local_source_ref.create(${literal(c.stage)}, ${literal(c.input)}, max_bytes=${bytes}).unwrap()`,
    `  assert_eq(@local_source_ref.stringify(v), ${literal(c.reference)})`,
    `  let parsed = @local_source_ref.read(${literal(c.reference)}, max_bytes=${bytes}).unwrap()`,
    `  assert_eq(@local_source_ref.stage_name(parsed), ${literal(c.stage)})`,
    `  assert_eq(@local_source_ref.input_name(parsed), ${literal(c.input)})`,
    `  assert_true(@local_source_ref.create(${literal(c.stage)}, ${literal(c.input)}, max_bytes=${bytes-1}) is Err(@local_source_ref.LimitExceeded))`,
    `  assert_true(@local_source_ref.read(${literal(c.reference)}, max_bytes=${bytes-1}) is Err(@local_source_ref.LimitExceeded))`, '}');
}
for (const [i,s] of corpus.rejected.entries()) {
  assert.equal(valid(s),false,s);
  lines.push('', '///|', `test "reject local source reference ${i}" {`, `  assert_true(@local_source_ref.read(${literal(s)}, max_bytes=1000) is Err(_))`, '}');
}
const path = 'src/local_source_ref/vectors.generated_test.mbt', output = lines.join('\n') + '\n';
if (process.argv.includes('--write')) writeFileSync(path, output);
else assert.equal(readFileSync(path,'utf8'), output, 'stale local source-reference tests');
console.log('16 independent local source-reference vectors verified.');
