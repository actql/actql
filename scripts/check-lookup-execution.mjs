import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {canonicalText} from './check-canonical-json.mjs';
export function checkLookupExecution(write=false){
  const c=JSON.parse(readFileSync('portability/corpus/lookup-execution-policy.json','utf8'));
  const cases=c.cases.map(v=>({...v,body:{...c.base,...v.patch}}));
  for(const k of Object.keys(c.base)){
    const body={...c.base};delete body[k];cases.push({id:'missing-'+k,body,accepted:false});
  }
  for(const [id,body] of [['null',null],['array',[]],['empty',{}],['scalar',1]])cases.push({id,body,accepted:false});
  const lines=['// Generated by scripts/check-lookup-execution.mjs --write. Do not edit.'];
  for(const v of cases){
    const body=canonicalText(v.body);
    const cid='sha256:'+createHash('sha256').update(body).digest('hex');
    if(v.id==='separate-wire-and-decoded'){assert.equal(body,c.expected_canonical);assert.equal(cid,c.expected_cid);}
    lines.push('','///|',`test ${JSON.stringify('lookup execution '+v.id)} {`,
      `  assert_lookup_execution_fixture(${JSON.stringify(body)}, ${JSON.stringify(cid)}, ${v.accepted})`,'}');
  }
  const path='src/check_environment/lookup_execution.generated_test.mbt',text=lines.join('\n')+'\n';
  if(write)writeFileSync(path,text);else assert.equal(readFileSync(path,'utf8'),text);
  return cases.length;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(`${checkLookupExecution(process.argv.includes('--write'))} lookup policy fixtures verified; not execution evidence.`);
