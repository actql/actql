import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';

// Compile only the keywords actually used by the normative SourceView schema.
// Unknown keywords fail generation instead of becoming silently weaker checks.
export function compileSourceView(schema) {
  // Count the constructors emitted by THIS same grammar walk. Literal Strings
  // stay module-owned; only fresh rule, tuple and Array controls are counted.
  const units={records:0,record_references:0,record_words:0,reference_arrays:0,reference_items:0,scalar_arrays:0,scalar_items:0,maps:0,map_entries:0};
  const record=(references=0,words=0)=>{units.records++;units.record_references+=references;units.record_words+=words;};
  const array=n=>{units.reference_arrays++;units.reference_items+=n;};
  function emit(s) {
    const allowed=['type','const','enum','minLength','pattern','minimum','properties','required','additionalProperties','items','minItems','uniqueItems'];
    for(const key of Object.keys(s))assert.ok(allowed.includes(key),`Unsupported keyword ${key}`);
    if(Object.hasOwn(s,'const')) {
      assert.deepEqual(Object.keys(s),['const']);
      if(typeof s.const==='boolean'){record(1);record(0,1);return `SVBoolean(Some(${s.const}))`;}
      assert.equal(typeof s.const,'string');record(1,2);array(1);return `SVText(0, [${JSON.stringify(s.const)}], false)`;
    }
    if(s.enum){assert.deepEqual(Object.keys(s),['enum']);assert.ok(s.enum.length&&s.enum.every(v=>typeof v==='string'));record(1,2);array(s.enum.length);return `SVText(0, ${JSON.stringify(s.enum)}, false)`;}
    if(s.type==='string'){
      assert.ok(Object.keys(s).every(k=>['type','minLength','pattern'].includes(k)));
      assert.ok(s.minLength===undefined||s.minLength===1);
      assert.ok(s.pattern===undefined||s.pattern==='^sha256:[0-9a-f]{64}$');
      record(1,2);array(0);
      return `SVText(${s.minLength??0}, [], ${Boolean(s.pattern)})`;
    }
    if(s.type==='boolean'){assert.deepEqual(s,{type:'boolean'});record(1);record(0,1);return 'SVBoolean(None)';}
    if(s.type==='integer'){assert.deepEqual(s,{type:'integer',minimum:1});record();return 'SVPositiveInteger';}
    if(s.type==='object'){
      assert.ok(Object.keys(s).every(k=>['type','properties','required','additionalProperties'].includes(k)));
      assert.equal(s.additionalProperties,false);assert.ok(s.properties);
      assert.ok((s.required??[]).every(k=>Object.hasOwn(s.properties,k)));
      record(1);array(Object.keys(s.properties).length);
      for(const ignored of Object.keys(s.properties))record(2,1);
      return 'SVObject(['+Object.entries(s.properties).map(([k,v])=>`(${JSON.stringify(k)}, ${Boolean(s.required?.includes(k))}, ${emit(v)})`).join(', ')+'])';
    }
    if(s.type==='array'){
      assert.ok(Object.keys(s).every(k=>['type','items','minItems','uniqueItems'].includes(k)));
      assert.ok(s.minItems===undefined||s.minItems===1);
      assert.ok(s.uniqueItems===undefined||s.uniqueItems===true);
      if(s.uniqueItems)assert.ok(s.items.type==='string'||s.items.enum?.every(v=>typeof v==='string'),'Uniqueness currently supports only string items');
      record(1,2);
      return `SVArray(${s.minItems??0}, ${Boolean(s.uniqueItems)}, ${emit(s.items)})`;
    }
    throw Error(`Unsupported schema ${JSON.stringify(s)}`);
  }
  const rule=emit(schema);
  return '// Generated by scripts/source-view-shape.mjs; do not edit.\n\n///|\nfn source_view_shape_rule() -> SourceViewRule {\n  '+rule+'\n}\n\n///|\n// Same emitted constructors; shared collection owner prices fresh backing.\nfn source_view_rule_construction() -> @shape.CollectionConstructionExtent {\n  @shape.collection_construction_extent({\n'+Object.entries(units).map(([key,value])=>`    ${key}: ${value}L,`).join('\n')+'\n  }).unwrap()\n}\n';
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  const schema=JSON.parse(readFileSync('spec/contracts/actql-protocol-schemas.json','utf8')).schemas.source_view;
  const text=compileSourceView(schema),path='src/check_environment/source_view_shape.generated.mbt';
  if(process.argv.includes('--write'))writeFileSync(path,text);
  assert.equal(readFileSync(path,'utf8'),text);
  console.log('SourceView shape rules match the complete pinned schema.');
}
