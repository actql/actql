import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalText,verifyIdentity} from './check-canonical-json.mjs';
const path='portability/corpus/local-relation-snapshots.json';
const corpus=JSON.parse(readFileSync(path,'utf8'));
assert.equal(corpus.version,'actql-local-relation-snapshot-vectors/0.1');
const literal=s=>'"'+[...s].map(c=>c.codePointAt(0)<32||c.codePointAt(0)>126?'\\u{'+c.codePointAt(0).toString(16)+'}':c==='"'||c==='\\'?'\\'+c:c).join('')+'"';
const lines=['// Generated by scripts/check-local-snapshots.mjs --write. Do not edit.'];
for(const c of corpus.cases){
  // Explicit maintenance only: independent Node canonicalization and hashing.
  if(process.argv.includes('--write-identities')){
    c.canonical_json=canonicalText(c.body);
    c.cid='sha256:'+createHash('sha256').update(c.canonical_json).digest('hex');
  }
  verifyIdentity(c.body,c.cid,c.canonical_json);
  assert.equal(typeof c.accepted,'boolean');
  lines.push('','///|',`test ${literal('snapshot '+c.id)} {`,
    `  let bytes = @utf8.encode(${literal(c.canonical_json)})`,
    `  assert_true(@local_relation_snapshot.read(bytes, ${literal(c.cid)}, { max_bytes: 10000, max_nodes: 1000, max_depth: 100 }) is ${c.accepted?'Ok':'Err'}(_))`, '}');
}
if(process.argv.includes('--write-identities'))writeFileSync(path,JSON.stringify(corpus,null,2)+'\n');
const output='src/local_relation_snapshot/vectors.generated_test.mbt', text=lines.join('\n')+'\n';
if(process.argv.includes('--write'))writeFileSync(output,text);else assert.equal(readFileSync(output,'utf8'),text);
console.log(`${corpus.cases.length} local Relation snapshot integrity/admission fixtures verified; not Host authorization.`);
