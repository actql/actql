import {readFileSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {controlRegistryPath} from './interactive-run-control-contract.mjs';
import {resolveControlSchema} from './interactive-run-control-schema.mjs';
import {structuralValidatorSource} from './generate-client-publication-wire.mjs';

const typeName = name => 'Wire' + name.split('_')
  .map(part => part[0].toUpperCase() + part.slice(1)).join('');

function wireType(schema) {
  if (schema.oneOf) return schema.oneOf.map(wireType).join(' | ');
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(JSON.stringify).join(' | ');
  if (schema.type === 'null') return 'null';
  if (schema.type === 'string') return 'string';
  if (schema.type === 'boolean') return 'boolean';
  if (['integer', 'number'].includes(schema.type)) return 'number';
  if (schema.type === 'array') return `readonly (${wireType(schema.items ?? {})})[]`;
  if (schema.allOf && !schema.properties) return schema.allOf.map(wireType)
    .map(type => `(${type})`).join(' & ');
  if (schema.type === 'object') {
    const required = new Set(schema.required ?? []);
    const members = Object.entries(schema.properties ?? {}).map(([name, field]) =>
      `${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${wireType(field)}`);
    if (schema.additionalProperties && typeof schema.additionalProperties === 'object')
      return `Readonly<Record<string, ${wireType(schema.additionalProperties)}>>`;
    return `Readonly<{${members.join('; ')} }>`;
  }
  if (schema.allOf) return schema.allOf.map(wireType).map(type => `(${type})`)
    .join(' & ');
  return 'ControlJsonValue';
}

export function generateControlWire(registry) {
  const schemas = Object.fromEntries(Object.entries(registry.schemas)
    .map(([name, schema]) => [name, resolveControlSchema(schema, registry)]));
  const header = '// Generated by scripts/generate-interactive-run-control-wire.mjs.\n' +
    '// Structural admission only; no installed control or sampling capability.\n';
  return {
    module: header + `const schemas = ${JSON.stringify(schemas, null, 2)};\n` +
      structuralValidatorSource({extended: true}) +
      `export const interactiveControlRegistryCid = ${JSON.stringify(registry.registry_cid)};\n` +
      `export const interactiveControlErrors = Object.freeze(${JSON.stringify(registry.errors)});\n` +
      Object.keys(schemas).map(name =>
        `export const valid${typeName(name)}Shape = value => valid(value, schemas.${name});\n`)
        .join(''),
    types: header +
      'export type ControlJsonValue = null | boolean | number | string | readonly ControlJsonValue[] | {readonly [key:string]: ControlJsonValue};\n' +
      'export declare const interactiveControlRegistryCid: string;\n' +
      `export declare const interactiveControlErrors: readonly (${registry.errors.map(JSON.stringify).join(' | ')})[];\n` +
      Object.entries(schemas).map(([name, schema]) =>
        `export type ${typeName(name)} = ${wireType(schema)};\n` +
        `export declare function valid${typeName(name)}Shape(value: unknown): value is ${typeName(name)};\n`)
        .join(''),
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const registry = JSON.parse(readFileSync(controlRegistryPath, 'utf8'));
  const {module, types} = generateControlWire(registry);
  for (const [path, content] of [
    ['packages/client-wire/interactive-control.generated.js', module],
    ['packages/client-wire/interactive-control.generated.d.ts', types],
  ]) {
    if (process.argv.includes('--write')) writeFileSync(path, content);
    else if (readFileSync(path, 'utf8') !== content)
      throw new Error(`StaleInteractiveControlWire:${path}`);
  }
}
