import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

// Copy existing hand-authored expectations into compiler tests. This never
// evaluates Calendar code, invokes the Python oracle or changes the corpus.
const root = new URL('../', import.meta.url);
const corpus = JSON.parse(readFileSync(new URL('portability/corpus/calendar-boundaries.json', root)));
const artifact = readFileSync(new URL('portability/corpus/calendar-tzdb-2025b.json', root));
assert.equal(corpus.transition_artifact_cid, `sha256:${createHash('sha256').update(artifact).digest('hex')}`);
assert.equal(corpus.version, 'actql-calendar-boundary-corpus/0.1');
const units = {day: 'Day', week: 'Week', month: 'Month', quarter: 'Quarter', year: 'Year'};
const quote = JSON.stringify;
const pair = row => `(${quote(row[0])}, ${quote(row[1])})`;
let source = '// Generated by scripts/generate-calendar-runtime-laws.mjs from the fixed independent corpus.\n';
const seen = new Set();
for (const item of corpus.cases) {
  assert(!seen.has(item.id)); seen.add(item.id);
  const unit = units[item.unit];
  const week = item.week_start ? `Some(${item.week_start === 'monday' ? 'Monday' : 'Sunday'})` : 'None';
  source += `\n///|\ntest ${quote(`original Calendar law: ${item.id}`)} {\n  let profile = runtime_law_profile()\n`;
  if (item.error === 'UnknownZone') {
    source += `  assert_true(@calendar_profile.zone(profile, ${quote(item.timezone)}) is None)\n}\n`;
    continue;
  }
  source += `  let table = @calendar_profile.zone(profile, ${quote(item.timezone)}).unwrap()\n`;
  if (item.operation === 'resolve') {
    assert.equal(typeof item.expected, 'string');
    source += `  assert_eq(runtime_law_resolution(table, ${quote(item.local)}), ${quote(item.expected)})\n`;
  } else if (item.operation === 'bucket') {
    assert(unit);
    source += `  let actual = runtime_law_bucket(table, ${quote(item.time)}, ${unit}, ${week}, 1)\n`;
    if (item.error) {
      assert.equal(item.error, 'BoundaryOutOfRange');
      source += '  assert_eq(actual.0, Err(@transition.CalendarBoundaryDomain))\n';
    } else source += `  assert_eq(actual.0, Ok(${pair(item.expected)}))\n`;
    source += `  assert_eq(runtime_law_bucket(table, ${quote(item.time)}, ${unit}, ${week}, 127), actual)\n`;
  } else {
    assert.equal(item.operation, 'series'); assert(unit);
    if (item.error) {
      assert.equal(item.error, 'ReversedRange');
      source += `  assert_true(@transition.start_series(table, @value.timestamp_epoch_milliseconds(${quote(item.start)}).unwrap(), @value.timestamp_epoch_milliseconds(${quote(item.end)}).unwrap(), ${unit}, week_start=${week}, max_rows=10, max_work=100) is Err(@transition.InvalidSeriesRange))\n`;
    } else {
      source += `  let actual = runtime_law_series(table, ${quote(item.start)}, ${quote(item.end)}, ${unit}, ${week}, 1)\n  assert_eq(actual.0, [${item.expected.map(pair).join(', ')}])\n  assert_eq(runtime_law_series(table, ${quote(item.start)}, ${quote(item.end)}, ${unit}, ${week}, 127), actual)\n`;
    }
  }
  source += '}\n';
}
assert.equal(seen.size, 28);
const target = new URL('src/calendar_profile/runtime_laws.generated_test.mbt', root);
if (process.argv.slice(2).includes('--write')) writeFileSync(target, source);
else assert.equal(readFileSync(target, 'utf8'), source, 'stale Calendar runtime law fixture');
console.log(`Calendar runtime law fixture: ${seen.size} independent cases; ${fileURLToPath(target)}`);
