import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
const read = path => JSON.parse(readFileSync(path, 'utf8'));
const contract = read('spec/contracts/actql-aoa.json');
const registry = read(contract.pipeline_registry_file);
const values = contract.execution_contracts['REL.values'];
const ordered = contract.execution_contracts['REL.derive.ordered'];
const fragment = contract.execution_contracts['ACTQL.expression_fragment/0.1'];
const property = contract.execution_contracts['BRIDGE.rows.to_graph'];
const adopted = {
  source_revision: '9edb5a65db8b822b8629cfa4913fb1097fb99945',
  registry_cid: contract.pipeline_registry_cid,
  values_cid:
    contract.target_registry_requirements['REL.values'].execution_contract.cid,
  fragment_cid:
    registry['ACTQL.expression_fragment/0.1'].execution_contract.cid,
  graph_cid: registry['BRIDGE.rows.to_graph'].execution_contract.cid,
  registry,
  values,
  fragment,
  graph: property,
};
const pins = `// Generated by scripts/lowering-registry-vectors.mjs --write. Do not edit.

///|
let selected_registry_cid : String = ${JSON.stringify(contract.pipeline_registry_cid)}

///|
let selected_values_contract_cid : String = ${JSON.stringify(contract.target_registry_requirements['REL.values'].execution_contract.cid)}

///|
let selected_ordered_contract_cid : String = ${JSON.stringify(registry['REL.derive'].execution_extensions.ordered_bindings.cid)}

///|
let selected_fragment_contract_cid : String = ${JSON.stringify(registry['ACTQL.expression_fragment/0.1'].execution_contract.cid)}

///|
let selected_expression_contract_cid : String = ${JSON.stringify(contract.expression_contract_cid)}
`;
const lines = ['// Generated by scripts/lowering-registry-vectors.mjs --write. Do not edit.'];
const consumerLines = [...lines];
const nativeValuesLines = [...lines];
const lifetimeLines = [...lines];
const graphOrderLines = [...lines];
const calendarLines = [...lines];
const contentRecoveryLines = [...lines];
const compilerBodies = [
  '// Generated by scripts/lowering-registry-vectors.mjs --write. Do not edit.',
];
for (const [name, value] of [['registered_body', registry], ['registered_values', values], ['registered_ordered', ordered], ['registered_fragment', fragment], ['registered_graph', property],
  ['historical_body', read('portability/fixtures/pipeline-registry-base.json')]]) {
  const start = lines.length;
  lines.push('', '///|', `fn ${name}() -> @identity.CanonicalValue raise {`,
    '  @identity.from_json(', '    @json.parse(', `      ${JSON.stringify(JSON.stringify(value))},`, '    ),',
    '    10000,', '    100,', '    100000,', '  )', '}');
  if (['registered_body', 'registered_values'].includes(name)) {
    calendarLines.push(...lines.slice(start).map(line =>
      line.replace(`fn ${name}()`, `fn calendar_runtime_${name}()`)));
    graphOrderLines.push(...lines.slice(start).map(line =>
      line.replace(`fn ${name}()`, `fn graph_order_${name}()`)));
    contentRecoveryLines.push(...lines.slice(start).map(line =>
      line.replace(`fn ${name}()`, `fn content_recovery_${name}()`)));
  }
  if (['registered_body', 'registered_values', 'registered_fragment'].includes(name)) {
    lifetimeLines.push(...lines.slice(start).map(line =>
      line.replace(`fn ${name}()`, `fn chain_lifetime_${name}()`)));
  }
  if (name !== 'historical_body' && name !== 'registered_graph') consumerLines.push(...lines.slice(start));
  if (['registered_body', 'registered_values', 'registered_fragment'].includes(name)) {
    nativeValuesLines.push(...lines.slice(start));
  }
  if (['registered_body', 'registered_values', 'registered_ordered'].includes(name)) {
    compilerBodies.push('', '///|', `fn compiler_${name}_wire() -> String {`,
      `  ${JSON.stringify(JSON.stringify(value))}`, '}');
  }
}
// Refresh only execution-contract inputs; authored Programs, Source identities,
// requests, rows and failure expectations remain independent fixture evidence.
function nativeSourceContracts(path, prefix) {
  let body = readFileSync(path, 'utf8');
  for (const [name, value] of [['registry', registry], ['values', values], ['fragment', fragment]]) {
    const pattern = new RegExp(`(let ${prefix}_${name} : String =\\s*\\n\\s*#\\|)[^\\n]+`, 'g');
    assert.equal([...body.matchAll(pattern)].length, 1, `${path}: ${name}`);
    body = body.replace(pattern, (_, declaration) => declaration + JSON.stringify(value));
  }
  return body;
}
