import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
const read = path => JSON.parse(readFileSync(path, 'utf8'));
const contract = read('spec/contracts/actql-aoa.json');
const registry = read(contract.pipeline_registry_file);
const values = contract.execution_contracts['REL.values'];
const ordered = contract.execution_contracts['REL.derive.ordered'];
const fragment = contract.execution_contracts['ACTQL.expression_fragment/0.1'];
const property = contract.execution_contracts['BRIDGE.rows.to_property_graph'];
const adopted = {
  source_revision: '9edb5a65db8b822b8629cfa4913fb1097fb99945',
  registry_cid: contract.pipeline_registry_cid,
  values_cid:
    contract.target_registry_requirements['REL.values'].execution_contract.cid,
  fragment_cid:
    registry['ACTQL.expression_fragment/0.1'].execution_contract.cid,
  property_graph_cid: registry['BRIDGE.rows.to_property_graph'].execution_contract.cid,
  registry,
  values,
  fragment,
  property_graph: property,
};
const pins = `// Generated by scripts/lowering-registry-vectors.mjs --write. Do not edit.

///|
let selected_registry_cid : String = ${JSON.stringify(contract.pipeline_registry_cid)}

///|
let selected_values_contract_cid : String = ${JSON.stringify(contract.target_registry_requirements['REL.values'].execution_contract.cid)}

///|
let selected_ordered_contract_cid : String = ${JSON.stringify(registry['REL.derive'].execution_extensions.ordered_bindings.cid)}

///|
let selected_fragment_contract_cid : String = ${JSON.stringify(registry['ACTQL.expression_fragment/0.1'].execution_contract.cid)}

///|
let selected_expression_contract_cid : String = ${JSON.stringify(contract.expression_contract_cid)}
`;
const lines = ['// Generated by scripts/lowering-registry-vectors.mjs --write. Do not edit.'];
const consumerLines = [...lines];
const lifetimeLines = [...lines];
for (const [name, value] of [['registered_body', registry], ['registered_values', values], ['registered_ordered', ordered], ['registered_fragment', fragment], ['registered_property_graph', property],
  ['historical_body', read('portability/fixtures/pipeline-registry-base.json')]]) {
  const start = lines.length;
  lines.push('', '///|', `fn ${name}() -> @identity.CanonicalValue raise {`,
    '  @identity.from_json(', '    @json.parse(', `      ${JSON.stringify(JSON.stringify(value))},`, '    ),',
    '    10000,', '    100,', '    100000,', '  )', '}');
  if (['registered_body', 'registered_values', 'registered_fragment'].includes(name)) {
    lifetimeLines.push(...lines.slice(start).map(line =>
      line.replace(`fn ${name}()`, `fn chain_lifetime_${name}()`)));
  }
  if (name !== 'historical_body' && name !== 'registered_property_graph') consumerLines.push(...lines.slice(start));
}
for (const [path, body] of [
  ['src/connectors/local/relation_chain_lifetime_contracts_wbtest.mbt',
    lifetimeLines.join('\n') + '\n'],
  ['src/execution_relation/registry_pins.generated.mbt', pins],
  ['src/execution_relation/registry_vectors.generated_wbtest.mbt', lines.join('\n') + '\n'],
  ['src/execution_relation/registry_vectors.generated_test.mbt', consumerLines.join('\n') + '\n'],
  ['src/query_integration/pinned_engine_contracts_wbtest.mbt',
    consumerLines.join('\n') + '\n'],
  ['adapters/connectors/duckdb/node/contracts/adopted-relation.json',
    JSON.stringify(adopted, null, 2) + '\n'],
]) {
  if (process.argv.includes('--write')) writeFileSync(path, body);
  else assert.equal(readFileSync(path, 'utf8'), body, `stale ${path}`);
}
