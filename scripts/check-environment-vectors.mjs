import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalText,verifyIdentity,generateTests} from './check-canonical-json.mjs';
const path='portability/corpus/check-environment.json';
const corpus=JSON.parse(readFileSync(path,'utf8'));
assert.equal(corpus.version,'actql-check-environment-vectors/0.1');
const fixtures=[];
const literal=s=>'"'+[...s].map(c=>c.codePointAt(0)<32||c.codePointAt(0)>126?'\\u{'+c.codePointAt(0).toString(16)+'}':c==='"'||c==='\\'?'\\'+c:c).join('')+'"';
const tests=['// Generated by scripts/check-environment-vectors.mjs --write. Do not edit.'];
for(const c of [...corpus.cases,...corpus.invalid_cases]){
  const preimage={...corpus.base,...c.replace};
  for(const key of c.omit??[])delete preimage[key];
  assert.ok(!Object.hasOwn(preimage,'evidence_bundle_cid'));
  if(process.argv.includes('--write-identities')){
    c.expected_preimage=canonicalText(preimage);
    c.expected_cid='sha256:'+createHash('sha256').update(c.expected_preimage).digest('hex');
    c.expected_wire=canonicalText({...preimage,evidence_bundle_cid:c.expected_cid});
  }
  verifyIdentity(preimage,c.expected_cid,c.expected_preimage);
  assert.equal(canonicalText({...preimage,evidence_bundle_cid:c.expected_cid}),c.expected_wire);
  if(!c.issue)fixtures.push({id:'Check Environment preimage '+c.id,value:preimage,cid:c.expected_cid,text:c.expected_preimage});
  tests.push('','///|',`test ${literal('environment wire '+c.id)} {`,
    `  let value = @check_environment.read(@utf8.encode(${literal(c.expected_wire)}), ${literal(c.expected_cid)}, { max_bytes: 10000, max_nodes: 1000, max_depth: 100, max_members: 100 })`,
    c.issue ? `  assert_true(value is Err(@check_environment.${c.issue}))` : '  assert_true(value is Ok(_))');
  if(!c.issue){
    tests.push('  let environment = value.unwrap()',
      `  assert_eq(@check_environment.cid(environment), ${literal(c.expected_cid)})`,
      '  let writer = @encode.writer(10000, 1000, 100)',
      '  @check_environment.emit(environment, writer)',
      `  assert_eq(@encode.finish(writer), ${literal(c.expected_wire)})`,
      '  let (bytes, nodes, members) = @check_environment.usage(environment)',
      `  assert_true(@check_environment.read(@utf8.encode(${literal(c.expected_wire)}), ${literal(c.expected_cid)}, { max_bytes: bytes, max_nodes: nodes, max_depth: 100, max_members: members }) is Ok(_))`,
      `  assert_true(@check_environment.read(@utf8.encode(${literal(c.expected_wire)}), ${literal(c.expected_cid)}, { max_bytes: bytes - 1, max_nodes: nodes, max_depth: 100, max_members: members }) is Err(@check_environment.BudgetExceeded))`,
      `  assert_true(@check_environment.read(@utf8.encode(${literal(c.expected_wire)}), ${literal(c.expected_cid)}, { max_bytes: bytes, max_nodes: nodes - 1, max_depth: 100, max_members: members }) is Err(@check_environment.BudgetExceeded))`);
  }
  tests.push('}');
}
assert.equal(new Set(corpus.cases.map(c=>c.expected_cid)).size,corpus.cases.length);
if(process.argv.includes('--write-identities'))writeFileSync(path,JSON.stringify(corpus,null,2)+'\n');
const output='src/canonical_json/check_environment.generated_test.mbt';
const text=generateTests(fixtures).replace('scripts/check-canonical-json.mjs','scripts/check-environment-vectors.mjs');
if(process.argv.includes('--write'))writeFileSync(output,text);else assert.equal(readFileSync(output,'utf8'),text);
const wireOutput='src/check_environment/vectors.generated_test.mbt', wireText=tests.join('\n')+'\n';
if(process.argv.includes('--write'))writeFileSync(wireOutput,wireText);else assert.equal(readFileSync(wireOutput,'utf8'),wireText);
console.log(`${fixtures.length} independent Check Environment preimages and ${corpus.cases.length+corpus.invalid_cases.length} wire cases verified; not environment admission.`);
