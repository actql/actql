// Source-only mirrors owned by the existing connector Node assembly.
import {readFileSync, existsSync, writeFileSync, mkdirSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {generateUpdateTargetDataCodec} from './generate-update-target-data-codec.mjs';

export function checkRelaClientBridges(root, write = false) {
  generateUpdateTargetDataCodec(root, write);
  const sourcePreparation = readFileSync(join(root,
    'src/connectors_builtin_node/client_source_preparation.mbt'), 'utf8');
  const sourcePreparationPath = join(root,
    'src/connectors_builtin_node_rela/client_source_preparation.mbt');
  const generatedPreparation = '// Generated by scripts/connector-node-bundles.mjs; edit the selected bridge.\n\n' + sourcePreparation;
  if (write) writeFileSync(sourcePreparationPath, generatedPreparation);
  else if (!existsSync(sourcePreparationPath) ||
      readFileSync(sourcePreparationPath, 'utf8') !== generatedPreparation) {
    throw new Error(`RelA source preparation is stale: ${sourcePreparationPath}`);
  }
  const sourcePath = join(root, 'src/connectors_builtin_node/client_program_bridge.mbt');
  const outputPath = join(root,
    'src/connectors_builtin_node_rela/client_program_bridge.mbt');
  const source = readFileSync(sourcePath, 'utf8');
  // Provider selection lives in a small package-local module. The shared
  // bridge body is copied byte-for-byte into the RelA package, with no regex
  // rewrite of executable code.
  const lean = '// Generated by scripts/connector-node-bundles.mjs; edit the common bridge.\n\n' +
    source;
  if (write) {
    mkdirSync(dirname(outputPath), {recursive:true});
    writeFileSync(outputPath, lean);
  } else if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== lean) {
    throw new Error(`RelA Node bridge is stale: ${outputPath}`);
  }
  for (const file of ['client_preparation_root_bridge.mbt',
    'client_native_snapshot_reader.mbt',
    'client_installed_sequence_contracts_bridge.mbt', 'client_row_response_bridge.mbt', 'client_row_json_page_bridge.mbt', 'client_salesforce_row_source_bridge.mbt', 'client_salesforce_initialization_bridge.mbt', 'client_snowflake_read_bridge.mbt', 'client_bigquery_read_bridge.mbt', 'client_gcs_source_construction_bridge.mbt', 'client_hubspot_initialization_bridge.mbt', 'client_kintone_read_bridge.mbt', 'client_kintone_mutation_bridge.mbt', 'client_kintone_lookup_bridge.mbt', 'client_update_target_bridge.mbt', 'client_table_write_publication.mbt', 'client_multi_source_bridge.mbt',
    'client_kintone_create_execution_bridge.mbt',
    'client_kintone_delete_outcome_bridge.mbt',
    'client_project_configuration_bridge.mbt',
    'client_project_admission_construction_bridge.mbt',
    'client_check_environment_construction_bridge.mbt',
    'client_mock_churn_risk_bridge.mbt',
    'client_relation_document_bridge.mbt',
    'client_relation_restore_construction_bridge.mbt',
    'client_host_signers_bridge.mbt',
    'client_local_signing_bridge.mbt',
    'client_installation_preparation_bridge.mbt',
    'client_installation_preparation_fields.generated.mbt',
    'client_model_defaults_bridge.mbt',
    'client_infer_run_materials_bridge.mbt',
    'client_public_model_task_bridge.mbt',
    'client_row_listing_capacity.mbt',
    'client_request_value_policy.mbt',
    'client_prepared_public_environment.mbt',
    'client_multi_source_host_bridge.mbt',
    'client_single_source_host_bridge.mbt',
    'client_source_capture_bridge.mbt',
    'client_whole_source_capture_bridge.mbt',
    'client_pending_capture_capacity_bridge.mbt',
    'client_published_store_target_bridge.mbt',
    'client_effect_phase_bridge.mbt',
    'client_effect_content_bridge.mbt',
    'client_recovered_content_bridge.mbt',
    'calendar_events_bridge.mbt',
    'client_effect_checked_row_bridge.mbt']) {
    const input = join(root, 'src/connectors_builtin_node', file);
    const output = join(root, 'src/connectors_builtin_node_rela', file);
    const mirrored = '// Generated by scripts/connector-node-bundles.mjs; edit the common bridge.\n\n' +
      readFileSync(input, 'utf8');
    if (write) writeFileSync(output, mirrored);
    else if (!existsSync(output) || readFileSync(output, 'utf8') !== mirrored) {
      throw new Error(`RelA Node bridge is stale: ${output}`);
    }
  }
}
