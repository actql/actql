import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {join} from 'node:path';

// This generator only copies fixed reference payloads into target tests. It
// never invokes ActQL or calculates rounding results from the implementation.
export function generateRoundPrecisionReference(corpus) {
  assert.equal(corpus.format, 'actql-round-trunc-reference-vectors/0.1');
  assert.equal(corpus.reference_commit, '81c15b796138185c046aefe852321011fdf96615');
  assert.equal(corpus.reference_sha256, 'cea59c46644f894fc204d434b7f56f65501b103fdd1f3a81c99304343bdee78d');
  assert.equal(corpus.rows.length, 1000);
  assert.equal(corpus.vector_count, corpus.rows.length);
  assert.equal(corpus.operation_count, 2 * corpus.rows.length);
  assert.equal(corpus.power_pairs.length, 647);
  const hex = value => {
    assert.match(value, /^[0-9a-f]{16}$/u);
    assert.notEqual((BigInt('0x' + value) >> 52n) & 0x7ffn, 0x7ffn, 'finite expected payload');
    return '0x' + value + 'UL';
  };
  const seen = new Set();
  const rows = corpus.rows.map(([input, spelling, digits, rounded, truncated, category]) => {
    assert.equal(typeof spelling, 'string'); assert.equal(typeof category, 'string');
    assert.ok(Number.isSafeInteger(digits));
    const key = input + ':' + digits;
    assert.ok(!seen.has(key), 'duplicate reference input'); seen.add(key);
    const overflow = rounded === 'ArithmeticFailure';
    return `    (${hex(input)}, ${digits}.0, ${hex(overflow ? '0000000000000000' : rounded)}, ${hex(truncated)}, ${overflow}),`;
  });
  assert.equal(corpus.round_overflow_count, corpus.rows.filter(row => row[3] === 'ArithmeticFailure').length);
  const header = '// Generated by scripts/round-precision-reference.mjs --write. Do not edit.\n' +
    '// Fixed payloads from GoogleSQL 81c15b796138185c046aefe852321011fdf96615.\n' +
    '// Source: portability/corpus/round-precision-reference.json; never product output.\n';
  let vectors = header;
  for (let i = 0; i < rows.length; i += 200) {
    vectors += `\n///|\ntest "pinned Google decimal reference corpus batch ${i / 200 + 1}" {\n` +
      '  for (input, digits, rounded, truncated, overflow) in [\n' + rows.slice(i, i + 200).join('\n') + '\n  ] {\n' +
      '    let value = Number(input.reinterpret_as_double())\n' +
      '    if overflow {\n' +
      '      assert_true(binary(@lower.RoundAt, value, Number(digits)) is Err(ArithmeticFailure))\n' +
      '    } else {\n' +
      '      guard binary(@lower.RoundAt, value, Number(digits)) is Ok(Number(actual)) else { fail("reference ROUND") }\n' +
      '      assert_eq(actual.reinterpret_as_uint64(), rounded)\n' +
      '    }\n' +
      '    guard binary(@lower.TruncAt, value, Number(digits)) is Ok(Number(actual)) else { fail("reference TRUNC") }\n' +
      '    assert_eq(actual.reinterpret_as_uint64(), truncated)\n' +
      '  }\n}\n';
  }
  for (const [i, row] of corpus.power_pairs.entries()) {
    assert.equal(row.length, 3); assert.equal(row[0], i - 323); hex(row[1]); hex(row[2]);
  }
  let powers = header + '\n///|\ntest "all 647 pinned decimal power pairs match the exact constructor" {\n' +
    '  let mut power = @bigint.BigInt::from_int(1)\n  let mut exponent = -1\n' +
    '  for (positive_hi, positive_lo, negative_hi, negative_lo) in [\n';
  for (let n = 0; n <= 323; n++) {
    powers += `    (${hex(corpus.power_pairs[323 + n][1])}, ${hex(corpus.power_pairs[323 + n][2])}, ${hex(corpus.power_pairs[323 - n][1])}, ${hex(corpus.power_pairs[323 - n][2])}),\n`;
  }
  powers += '  ] {\n    exponent += 1\n    if exponent > 0 { power *= @bigint.BigInt::from_int(5) }\n' +
    '    for (inverse, hi, lo) in [(false, positive_hi, positive_lo), (true, negative_hi, negative_lo)] {\n' +
    '      if !inverse || exponent > 0 {\n        let actual = decimal_power_pair(power, inverse).unwrap()\n' +
    '        assert_eq(actual.hi.reinterpret_as_uint64(), hi)\n        assert_eq(actual.lo.reinterpret_as_uint64(), lo)\n' +
    '      }\n    }\n  }\n}\n';
  return {vectors, powers};
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const corpus = JSON.parse(readFileSync('portability/corpus/round-precision-reference.json', 'utf8'));
  const outputs = generateRoundPrecisionReference(corpus);
  const formatter = process.env.MOON_HOME
    ? join(process.env.MOON_HOME, 'bin', 'moonfmt') : 'moonfmt';
  for (const [key, name] of [['vectors', 'round_precision_reference'], ['powers', 'round_precision_powers']]) {
    const path = `src/execution_relation/${name}.generated_wbtest.mbt`;
    const source = execFileSync(formatter, ['-'], {input: outputs[key], encoding: 'utf8'});
    if (process.argv.includes('--write')) writeFileSync(path, source);
    else assert.equal(readFileSync(path, 'utf8'), source, `stale ${name}`);
  }
  console.log('1,000 fixed reference input pairs, 2,000 operations and 647 power-pair vectors are fresh.');
}
