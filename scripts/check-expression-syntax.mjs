import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const literal = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}' : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';

export function generate(corpus, textCorpus) {
  assert.equal(corpus.version, 'actql-expression-syntax-corpus/0.1');
  assert.equal(textCorpus.version, 'actql-expression-text-corpus/0.1');
  assert.ok(corpus.positive.length > 0 && corpus.negative.length > 0);
  const lines = ['// Generated by scripts/check-expression-syntax.mjs --write. Do not edit.'];
  const seen = new Set();
  for (const [i, entry] of corpus.positive.entries()) {
    assert.ok(entry.tree && typeof entry.tree === 'object' && !Array.isArray(entry.tree));
    assert.ok(Object.hasOwn(entry, 'source'));
    assert.ok(Array.isArray(entry.parameters) && entry.parameters.every(name => typeof name === 'string'));
    const source = JSON.stringify(entry.source);
    assert.ok(!seen.has(source), 'duplicate source');
    seen.add(source);
    lines.push('', '///|', `test "structured expression corpus accepted: ${i + 1}" {`,
      `  assert_tree(${literal(source)}, ${literal(JSON.stringify(entry.tree))})`,
      `  let expression = admit(source_cursor(${literal(source)}), test_limits()).unwrap()`,
      '  assert_cursor(tree(admit(tree(expression), test_limits()).unwrap()), tree(expression))',
      `  assert_eq(parameter_references(expression).map(r => r.name), [${entry.parameters.map(literal).join(', ')}])`, '}');
  }
  for (const [i, source] of corpus.negative.entries()) {
    const encoded = JSON.stringify(source);
    assert.ok(!seen.has(encoded), 'duplicate source');
    seen.add(encoded);
    lines.push('', '///|', `test "structured expression corpus rejected: ${i + 1}" {`,
      `  assert_true(admit(source_cursor(${literal(encoded)}), test_limits()) is Err(_))`, '}');
  }
  for (const [i, entry] of textCorpus.positive.entries()) {
    lines.push('', '///|', `test "common admission of text corpus: ${i + 1}" {`,
      `  assert_tree(${literal(JSON.stringify(entry.source))}, ${literal(JSON.stringify(entry.tree))})`, '}');
  }
  for (const [i, source] of textCorpus.negative.entries()) {
    lines.push('', '///|', `test "common rejection of text corpus: ${i + 1}" {`,
      `  assert_true(admit(text_cursor(${literal(source)}), test_limits()) is Err(_))`, '}');
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const corpus = JSON.parse(readFileSync('portability/corpus/actql-expression-syntax-v0.1.json', 'utf8'));
  const textCorpus = JSON.parse(readFileSync('portability/corpus/actql-expression-text-v0.1.json', 'utf8'));
  const output = generate(corpus, textCorpus);
  const path = 'src/expression_syntax/corpus.generated_wbtest.mbt';
  if (process.argv.includes('--write')) writeFileSync(path, output);
  else assert.equal(readFileSync(path, 'utf8'), output, 'expression syntax tests are stale');
  console.log(`${corpus.positive.length} accepted and ${corpus.negative.length} rejected structured vectors, plus the expression text corpus; generated tests match.`);
}
