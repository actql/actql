import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalText, verifyIdentity} from './check-canonical-json.mjs';

const file = 'portability/corpus/regex-replacement.json';
const corpus = JSON.parse(readFileSync(file, 'utf8'));
const owner = JSON.parse(readFileSync('spec/contracts/actql-production-profile-schemas.json', 'utf8'));
const schema = owner.schemas.regex_replacement_ast;
assert.equal(corpus.version, 'actql-regex-replacement-vectors/0.1');
assert.equal(schema.properties.version.const, 'actql-regex-replacement-ast/0.1');
assert.deepEqual(schema.required.slice().sort(), ['ast_cid','capture_reference_count','literal_utf8_bytes','max_capture_index','parts','version']);
const variants = schema.properties.parts.items.oneOf;
const seen = new Set();
for (const c of corpus.accepted) {
  assert.ok(!seen.has(c.id)); seen.add(c.id);
  assert.equal(c.text.normalize('NFC').replace(/\r\n?/g,'\n'), c.text);
  let literals = 0, count = 0, maximum = 0, previousLiteral = false;
  // Handwritten parts are the expected syntax tree, not product parser output.
  for (const part of c.parts) {
    const branch = variants.find(v => v.properties.kind.const === part.kind);
    assert.ok(branch);
    assert.deepEqual(Object.keys(part).sort(), branch.required.slice().sort());
    if (part.kind === 'literal') {
      assert.ok(part.value.length > 0 && !previousLiteral);
      assert.equal(part.value.normalize('NFC').replace(/\r\n?/g,'\n'), part.value);
      literals += Buffer.byteLength(part.value);
      previousLiteral = true;
    } else {
      assert.ok(Number.isInteger(part.capture) && part.capture >= branch.properties.capture.minimum && part.capture <= branch.properties.capture.maximum);
      count++; maximum = Math.max(maximum, part.capture); previousLiteral = false;
    }
  }
  const core = {version:'actql-regex-replacement-ast/0.1',parts:c.parts,literal_utf8_bytes:literals,capture_reference_count:count,max_capture_index:maximum};
  if (process.argv.includes('--write-identities')) {
    c.expected_preimage = canonicalText(core);
    c.expected_cid = 'sha256:' + createHash('sha256').update(c.expected_preimage).digest('hex');
    c.expected_ast = canonicalText({...core,ast_cid:c.expected_cid});
  }
  verifyIdentity(core,c.expected_cid,c.expected_preimage);
  assert.equal(c.expected_ast,canonicalText({...core,ast_cid:c.expected_cid}));
}
for (const c of corpus.rejected) {
  assert.ok(!seen.has(c.id)); seen.add(c.id);
  assert.ok(/^(NonCanonicalText|InvalidReplacement\([0-9]+\))$/.test(c.issue));
}
if (process.argv.includes('--write-identities')) writeFileSync(file,JSON.stringify(corpus,null,2)+'\n');
const literal = text => '"' + [...text].map(c => {
  const cp=c.codePointAt(0);
  return cp<32 || cp>126 ? '\\u{'+cp.toString(16)+'}' : c==='"'||c==='\\' ? '\\'+c : c;
}).join('') + '"';
const lines=['// Generated by scripts/check-regex-replacement.mjs --write. Do not edit.'];
for (const c of corpus.accepted) {
  const core=JSON.parse(c.expected_preimage);
  lines.push('', '///|', `test ${literal('regex replacement: '+c.id)} {`,
    `  let value = parse(${literal(c.text)}, limits()).unwrap()`,
    `  assert_eq(cid(value), ${literal(c.expected_cid)})`,
    '  let wire = @encode.writer(10000,1000,3)', '  emit(value,wire)',
    `  assert_eq(@encode.finish(wire), ${literal(c.expected_ast)})`,
    '  let preimage = @encode.writer(10000,1000,3)', '  emit_preimage(value,preimage)',
    `  assert_eq(@encode.finish(preimage), ${literal(c.expected_preimage)})`,
    `  assert_eq(stats(value).literal_utf8_bytes, ${core.literal_utf8_bytes})`,
    `  assert_eq(stats(value).capture_reference_count, ${core.capture_reference_count})`,
    `  assert_eq(stats(value).max_capture_index, ${core.max_capture_index})`,
    `  assert_eq(part_count(value), ${c.parts.length})`,
    ...c.parts.map((p,i)=>`  assert_eq(part_at(value, ${i}), Some(${p.kind==='literal'?'Literal('+literal(p.value)+')':'Capture('+p.capture+')'}))`), '}');
}
for (const c of corpus.rejected) lines.push('', '///|', `test ${literal('regex replacement rejects: '+c.id)} {`,
  `  assert_true(parse(${literal(c.text)}, limits()) is Err(${c.issue}))`, '}');
const path='src/regex_replacement/vectors.generated_test.mbt', text=lines.join('\n')+'\n';
if (process.argv.includes('--write')) writeFileSync(path,text);
else assert.equal(readFileSync(path,'utf8'),text,'stale regex replacement tests');
console.log(`${corpus.accepted.length} accepted and ${corpus.rejected.length} rejected replacement vectors; capture existence and matching are separate.`);
