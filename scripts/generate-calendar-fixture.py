"""Reproduce a selected-zone Calendar fixture from pinned IANA source archives.

No installed zoneinfo, Python timezone database, network, or system zic is used.
The C compiler and make build the pinned zic source in an isolated directory.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor/tzdb/2025b"
PINS = {
    "tzdata2025b.tar.gz": "11810413345fc7805017e27ea9fa4885fd74cd61b2911711ad038f5d28d71474",
    "tzcode2025b.tar.gz": "05f8fedb3525ee70d49c87d3fae78a8a0dbae4fe87aa565c65cda9948ae135ec",
}
START, END = -62135596800, 253402300800
ZONES = ("America/New_York", "Pacific/Apia", "UTC")


def block(data: bytes, position: int, width: int):
    if data[position:position + 4] != b"TZif":
        raise ValueError("invalid TZif header")
    counts = struct.unpack_from(">6I", data, position + 20)
    ut, standard, leaps, count, types, chars = counts
    if not types or types > 256 or leaps:
        raise ValueError("invalid types or unexpected leap-second data")
    p = position + 44
    times = list(struct.unpack_from(f">{count}{'q' if width == 8 else 'i'}", data, p))
    p += count * width
    indices = list(data[p:p + count])
    p += count
    offsets = [struct.unpack_from(">i", data, p + i * 6)[0] for i in range(types)]
    p += types * 6 + chars + leaps * (width + 4) + standard + ut
    if p > len(data) or len(indices) != count or any(i >= types for i in indices):
        raise ValueError("truncated or invalid TZif block")
    if any(a >= b for a, b in zip(times, times[1:])):
        raise ValueError("unordered TZif transitions")
    return p, times, indices, offsets


def table(data: bytes):
    if data[4:5] not in (b"2", b"3", b"4"):
        raise ValueError("64-bit TZif required")
    p, *_ = block(data, 0, 4)
    _, times, indices, offsets = block(data, p, 8)
    # zic -r inserts coverage sentinels. Do not silently accept a short table
    # whose POSIX footer would be needed to extrapolate through year 9999.
    if START not in times or END not in times:
        raise ValueError("missing explicit coverage sentinels")
    initial = offsets[indices[times.index(START)]]
    previous = initial
    transitions = []
    for at, index in zip(times, indices):
        offset = offsets[index]
        if START < at < END and offset != previous:
            transitions.append({"at_ms": at * 1000, "offset_seconds": offset})
            previous = offset
    return {"initial_offset_seconds": initial, "transitions": transitions}


def generate():
    for name, expected in PINS.items():
        if hashlib.sha256((VENDOR / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"archive hash mismatch: {name}")
    with tempfile.TemporaryDirectory(prefix="actql-calendar-") as temp:
        work = Path(temp)
        for name in PINS:
            with tarfile.open(VENDOR / name) as archive:
                for item in archive.getmembers():
                    if not item.isfile() or Path(item.name).name != item.name:
                        raise ValueError("unexpected archive member")
                    with archive.extractfile(item) as source:
                        (work / item.name).write_bytes(source.read())
        if (work / "version").read_text().strip() != "2025b":
            raise ValueError("unexpected release")
        subprocess.run(["make", "zic"], cwd=work, check=True, capture_output=True)
        subprocess.run([
            str(work / "zic"), "-b", "slim", "-r", f"@{START}/@{END}",
            "-R", f"@{END}", "-d", str(work / "zones"),
            "northamerica", "australasia", "etcetera",
        ], cwd=work, check=True, capture_output=True)
        artifact = {
            "version": "actql-tzdb-table/0.1", "tzdb_version": "2025b",
            "conversion_law": "actql-calendar-boundaries/0.1",
            "coverage_start_ms": START * 1000, "coverage_end_ms": END * 1000,
            "zones": {z: table((work / "zones" / ("Etc/UTC" if z == "UTC" else z)).read_bytes()) for z in ZONES},
        }
    raw = json.dumps(artifact, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()
    cid = "sha256:" + hashlib.sha256(raw).hexdigest()
    # Byte chunks avoid a single oversized literal in any target backend.
    chunks = [raw[i:i + 8000].decode() for i in range(0, len(raw), 8000)]
    literals = ",\n".join("    " + json.dumps(s) for s in chunks)
    mbt = '''// Generated by scripts/generate-calendar-fixture.py; do not edit.
///|
fn real_fixture() -> Bytes {
  @utf8.encode([\n''' + literals + '''\n  ].join(""))
}

///|
fn real_fixture_cid() -> String {
  "''' + cid + '''"
}
'''
    return {
        ROOT / "portability/corpus/calendar-tzdb-2025b.json": raw,
        ROOT / "src/calendar_profile/tzdb_fixture.generated_test.mbt": mbt.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    for path, expected in generate().items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
        elif not path.exists() or path.read_bytes() != expected:
            raise SystemExit(f"stale generated fixture: {path.relative_to(ROOT)}")
        print(path.relative_to(ROOT), len(expected), hashlib.sha256(expected).hexdigest())


if __name__ == "__main__":
    main()
