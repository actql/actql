import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {machineCid} from './actql-spec-family.mjs';
import {canonicalText} from './check-canonical-json.mjs';
const corpus = JSON.parse(readFileSync(
  'portability/corpus/source-evidence-members.json', 'utf8'));
const first = corpus.cases[0].environment;
assert.equal(machineCid(first.schema_snapshots[0]), corpus.schema_evidence_cid);
assert.equal(machineCid(first.connector_capabilities[0]),
  corpus.capability_evidence_cid);
const lines = ['// Generated by scripts/source-evidence-member-vectors.mjs.'];
for (const vector of corpus.cases) {
  const {evidence_bundle_cid: cid, ...body} = vector.environment;
  assert.equal(machineCid(body), cid);
  lines.push('///|', `test ${JSON.stringify(vector.name)} {`,
    `  let environment = @check_environment.read(@utf8.encode(${JSON.stringify(canonicalText(vector.environment))}),`,
    `    ${JSON.stringify(cid)}, { max_bytes: 10000, max_nodes: 1000, max_depth: 20, max_members: 20 }).unwrap()`,
    '  let selection = @check_environment.select_connector_source_evidence_members(environment, {',
    ...Object.entries(vector.selector).map(([k, v]) =>
      `    ${k}: ${JSON.stringify(v)},`), '  })');
  if (vector.expected === 'ok') {
    lines.push('  let members = selection.unwrap()',
      `  assert_eq(@check_environment.connector_source_evidence_member_cids(members), (${JSON.stringify(corpus.schema_evidence_cid)}, ${JSON.stringify(corpus.capability_evidence_cid)}))`,
      `  assert_true(@check_environment.connector_source_evidence_supports(members, [${JSON.stringify(corpus.used_contract_cid)}]))`,
      `  assert_false(@check_environment.connector_source_evidence_supports(members, [${JSON.stringify(corpus.missing_contract_cid)}]))`,
      '  assert_false(@check_environment.connector_source_evidence_supports(members, []))');
  } else {
    lines.push(`  assert_true(selection is Err(@check_environment.${vector.expected}${vector.expected === 'ContractMismatch' ? '(_)' : ''}))`);
  }
  lines.push('}', '');
}
const path = 'src/check_environment/source_evidence_members.generated_test.mbt';
const output = `${lines.join('\n')}\n`;
if (process.argv.includes('--write')) writeFileSync(path, output);
assert.equal(readFileSync(path, 'utf8'), output);
console.log(`Source Evidence member vectors: ${corpus.cases.length}`);
