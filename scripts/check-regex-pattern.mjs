import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {canonicalText,verifyIdentity} from './check-canonical-json.mjs';

const file='portability/corpus/regex-pattern.json';
const corpus=JSON.parse(readFileSync(file,'utf8'));
assert.equal(corpus.version,'actql-regex-pattern-vectors/0.1');
const ids=new Set();
const scalar=n=>assert.ok(Number.isInteger(n)&&n>=0&&n<=0x10ffff&&!(n>=0xd800&&n<=0xdfff));
const keys=(o,expected)=>assert.deepEqual(Object.keys(o).sort(),expected.split(' ').sort());
// Handwritten AST oracle, not a regex parser and not product output. Derive
// nullability, capture numbering and shape directly from each expected tree.
function inspect(root) {
  let captures=0,nodes=0;
  function visit(n, item=false) {
    nodes++;
    switch(n.kind) {
      case 'literal':keys(n,'kind codepoint');scalar(n.codepoint);return false;
      case 'range':keys(n,'kind start end');assert.ok(item);scalar(n.start);scalar(n.end);assert.ok(n.start<=n.end);return false;
      case 'class_escape':keys(n,'kind value');assert.match(n.value,/^[dDsSwW]$/);return false;
      case 'dot':keys(n,'kind');assert.ok(!item);return false;
      case 'anchor':keys(n,'kind value');assert.ok(!item);assert.ok(['^','$'].includes(n.value));return true;
      case 'class':keys(n,'kind negated items');assert.ok(!item);assert.equal(typeof n.negated,'boolean');assert.ok(n.items.length);n.items.forEach(x=>visit(x,true));return false;
      case 'capture':keys(n,'kind capture expression');assert.ok(!item);assert.equal(n.capture,++captures);return visit(n.expression);
      case 'sequence':case 'alternation': {
        const field=n.kind==='sequence'?'items':'branches';keys(n,'kind '+field);assert.ok(!item);assert.ok(n[field].length>=2);
        const children=n[field].map(x=>visit(x));return n.kind==='sequence'?children.every(Boolean):children.some(Boolean);
      }
      case 'repeat':keys(n,'kind min max expression');assert.ok(!item);assert.ok(Number.isInteger(n.min)&&n.min>=0);assert.ok(n.max===null||(Number.isInteger(n.max)&&n.max>=n.min));assert.equal(visit(n.expression),false);return n.min===0;
      default:assert.fail('unknown fixture node');
    }
  }
  const nullable=visit(root);return {captures,nodes,nullable};
}
function jsonNodes(v) {return 1+(Array.isArray(v)?v.reduce((n,x)=>n+jsonNodes(x),0):v&&typeof v==='object'?Object.values(v).reduce((n,x)=>n+jsonNodes(x),0):0);}
const literal=s=>'"'+[...s].map(c=>{const n=c.codePointAt(0);return n<32||n>126?'\\u{'+n.toString(16)+'}':c==='"'||c==='\\'?'\\'+c:c;}).join('')+'"';
const lines=['// Generated by scripts/check-regex-pattern.mjs --write. Do not edit.'];
for(const c of corpus.accepted) {
  assert.ok(!ids.has(c.id));ids.add(c.id);
  assert.equal(c.text.normalize('NFC').replace(/\r\n?/g,'\n'),c.text);
  const facts=inspect(c.ast.root);assert.equal(facts.captures,c.ast.capture_count);
  if(process.argv.includes('--write-identities')) {
    c.expected_preimage=canonicalText(c.ast);
    c.expected_cid='sha256:'+createHash('sha256').update(c.expected_preimage).digest('hex');
    c.expected_ast=canonicalText({...c.ast,ast_cid:c.expected_cid});
  }
  verifyIdentity(c.ast,c.expected_cid,c.expected_preimage);
  assert.equal(c.expected_ast,canonicalText({...c.ast,ast_cid:c.expected_cid}));
  lines.push('','///|',`test ${literal('regex pattern: '+c.id)} {`,
    `  let p = parse(${literal(c.text)}, limits()).unwrap()`,
    `  assert_eq(cid(p), ${literal(c.expected_cid)})`,
    `  assert_eq(capture_count(p), ${facts.captures})`,
    `  assert_eq(nullable(p), ${facts.nullable})`,
    `  assert_eq(usage(p), (${Buffer.byteLength(c.text)}, ${Buffer.byteLength(c.expected_ast)}, ${jsonNodes(c.ast)+1}))`,
    '  let w = @encode.writer(10000,10000,100)', '  emit(p,w)',
    `  assert_eq(@encode.finish(w), ${literal(c.expected_ast)})`,
    '  let w = @encode.writer(10000,10000,100)', '  emit_preimage(p,w)',
    `  assert_eq(@encode.finish(w), ${literal(c.expected_preimage)})`, '}');
}
for(const c of corpus.rejected) {
  assert.ok(!ids.has(c.id));ids.add(c.id);assert.match(c.issue,/^(NonCanonicalText|(InvalidSyntax|InvalidRange|InvalidQuantifier|QuantifierOutOfRange|NullableRepeat)\([0-9]+\))$/);
  lines.push('','///|',`test ${literal('regex pattern rejects: '+c.id)} {`,
    `  assert_true(parse(${literal(c.text)}, limits()) is Err(${c.issue}))`, '}');
}
if(process.argv.includes('--write-identities'))writeFileSync(file,JSON.stringify(corpus,null,2)+'\n');
const output='src/regex_pattern/vectors.generated_test.mbt', text=lines.join('\n')+'\n';
if(process.argv.includes('--write'))writeFileSync(output,text);else assert.equal(readFileSync(output,'utf8'),text,'stale regex pattern tests');
console.log(`${corpus.accepted.length} accepted and ${corpus.rejected.length} rejected regex pattern vectors; no matching conformance claim.`);
