import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';

// Expected bytes come from main's independent corpus, never the lowerer.
// These vectors exercise wire-value conversion through quoted source literals.
// Real Parameter ownership/binding is tested separately, not inferred here.
const corpus = JSON.parse(readFileSync('portability/corpus/rel-values-execution.json', 'utf8'));
const quote = text => '"' + [...text].map(c => {
  const cp = c.codePointAt(0);
  return cp < 32 || cp > 126 ? '\\u{' + cp.toString(16) + '}'
    : c === '"' || c === '\\' ? '\\' + c : c;
}).join('') + '"';
const lines = ['// Generated by scripts/lowering-values-vectors.mjs --write. Do not edit.'];
const execution = [...lines];
const number = n => Number.isInteger(n) ? n + '.0' : String(n);
// Generate structural assertions from fixed wire values and their contracts,
// not by decoding expected values with the implementation under test.
let variable = 0;
function assertValue(value, contract, expression, nested = false) {
  const primitive = value === null ? 'Null' : contract.type === 'number' ? `Number(${number(value)})`
    : contract.type === 'boolean' ? `Boolean(${value})` : contract.type === 'string' ? `Text(${quote(value)})` : null;
  if (primitive) { execution.push(`  assert_true(${expression} is ${nested ? '@admitted.' : ''}${primitive})`); return; }
  if (!nested) {
    const name = 'v' + variable++;
    execution.push(`  guard ${expression} is Captured(${name}) else { fail("structured cell") }`);
    expression = name;
  }
  if (contract.type === 'date' || contract.type === 'timestamp') {
    execution.push(`  assert_true(${expression} is @admitted.${contract.type === 'date' ? 'Date' : 'Timestamp'}(${quote(value)}))`);
  } else if (contract.type === 'decimal') {
    const name = 'd' + variable++;
    execution.push(`  guard ${expression} is @admitted.Decimal(${name}) else { fail("decimal") }`,
      `  assert_eq(${name}.coefficient, ${quote(value.replace('.', ''))})`,
      `  assert_eq(${name}.precision, ${contract.precision})`, `  assert_eq(${name}.scale, ${contract.scale})`);
  } else {
    const name = 'items' + variable++;
    const tag = {array:'Array', object:'Object', vector:'Vector'}[contract.type];
    assert.ok(tag, `unsupported fixture type ${contract.type}`);
    execution.push(`  guard ${expression} is @admitted.${tag}(${name}) else { fail("${tag}") }`);
    const entries = contract.type === 'object' ? Object.keys(value).sort() : value;
    execution.push(`  assert_eq(@admitted.element_count(${name}), ${entries.length})`);
    entries.forEach((entry, i) => {
      const item = 'item' + variable++;
      execution.push(`  let ${item} = @admitted.element_at(${name}, ${i}).unwrap()`);
      if (contract.type === 'vector') execution.push(`  assert_eq(${item}, ${number(entry)})`);
      else if (contract.type === 'object') {
        execution.push(`  assert_eq(${item}.0, ${quote(entry)})`);
        assertValue(value[entry], contract.fields[entry], item + '.1', true);
      } else assertValue(entry, contract.items, item, true);
    });
  }
}
// Checked-only fields are not accepted by the author contract grammar. This
// conversion builds test source; the lowerer consumes checked contracts only.
const author = c => {
  const out = {...c};
  delete out.additional_properties;
  delete out.element_type;
  if (out.fields) out.fields = Object.fromEntries(Object.entries(out.fields).map(([k,v]) => [k,author(v)]));
  if (out.items) out.items = author(out.items);
  return out;
};
let count = 0;
for (const c of corpus.cases) {
  if (!c.schema_valid || !c.rows_valid.every(Boolean)) continue;
  const source = {schema:Object.fromEntries(Object.entries(c.params.schema).map(([k,v]) => [k,author(v)])), rows:c.params.rows.map(row =>
    Object.fromEntries(Object.entries(row).map(([k,v]) => [k, {literal:v}])))};
  lines.push('', '///|', `test ${quote('values wire from fixed params: '+c.id)} {`,
    '  let owner = values_owner(', `    ${quote(JSON.stringify(source))},`, '  )',
    '  assert_eq(', '    values_params_wire(owner),',
    `    ${quote(c.expected_canonical_json)},`, '  )', '}');
  const columns = Object.keys(c.params.schema).sort().reverse();
  const program = [{values:source, as:'seed'}, {derive:{}}, {filter:'true'}, {select:columns}];
  execution.push('', '///|', `test ${quote('values four-operation execution: '+c.id)} {`,
    '  let owner = bound_pipeline(', `    ${quote(JSON.stringify(program))},`, '  )',
    '  let result = evaluate_sequence_components(', '    registered_relation_contracts(),', '    prepared_sequence(owner),',
    '    [],', '    ["select_3"],', '    run_limits(),',
    '    { remaining: 100000, max_frames: 100, },', '  ).unwrap()',
    '  assert_eq(result.store.next, 4)',
    '  let table = result.store.tables[3].unwrap().table',
    `  assert_eq(table.names, [${columns.map(quote).join(', ')}])`,
    `  assert_eq(table.rows.length(), ${c.params.rows.length})`);
  c.params.rows.forEach((row, i) => {
    execution.push(`  assert_eq(table.rows[${i}].length(), ${columns.length})`);
    columns.forEach((field, j) => assertValue(row[field], c.params.schema[field], `table.rows[${i}][${j}]`));
  });
  execution.push('}');
  count++;
}
const path = 'src/lowering_relation/values_vectors.generated_test.mbt';
const body = lines.join('\n')+'\n';
if (process.argv.includes('--write')) writeFileSync(path, body);
else assert.equal(readFileSync(path,'utf8'), body, 'stale fixed values lowering vectors');
console.log(`${count} independent accepted params vectors; not invalid-wire admission tests.`);
const executionPath = 'src/execution_relation/values_vectors.generated_wbtest.mbt';
const executionBody = execution.join('\n') + '\n';
if (process.argv.includes('--write')) writeFileSync(executionPath, executionBody);
else assert.equal(readFileSync(executionPath, 'utf8'), executionBody, 'stale fixed values execution vectors');
