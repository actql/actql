import assert from 'node:assert/strict';
import {readFileSync, writeFileSync} from 'node:fs';
import {canonicalText, verifyIdentity} from './check-canonical-json.mjs';
import {machineCid} from './actql-spec-family.mjs';

const read = path => JSON.parse(readFileSync(new URL('../' + path, import.meta.url), 'utf8'));
const args = process.argv.slice(2);
assert.ok(args.length === 0 || (args.length === 1 && args[0] === '--write'));
const cid = machineCid(read('spec/contracts/actql-expressions.json'));
assert.equal(read('spec/contracts/actql-aoa.json').expression_contract_cid, cid);
const vectors = read('portability/corpus/stage-semantics.json');
assert.equal(vectors.version, 'actql-stage-semantics-vectors/0.1');
const header = '// Generated by scripts/check-stage-semantics.mjs --write. Do not edit.\n';
const pin = `${header}\n///|\nlet stage_expression_contract_cid : String = ${JSON.stringify(cid)}\n`;
let tests = header;
let programTests = header;
// These are composed from independently authored stage envelopes, never from
// MoonBit output. They exercise source projection, not executable admission.
const programs = read('portability/corpus/program-semantics.json');
assert.equal(programs.version, 'actql-program-semantics-vectors/0.1');
for (const {import_mode: mode, accepted, expected_cid} of programs.cases) {
  assert.ok([0, 1, 2].includes(mode));
  assert.equal(typeof accepted, 'boolean');
  const [a, b] = vectors.cases.slice(0, 2).map(c => structuredClone(c.envelope));
  const port = mode === 1 ? {result: {stage: 'a', result: 'r'}}
    : mode === 2 ? {receipt: {stage: 'a', effect: 'd'}} : null;
  if (port) b.local_body.inputs.rows = port;
  const envelope = {
    version: 'actql-program-semantics/0.1', actql_version: 'actql/0.1',
    expression_contract_cid: cid,
    parameters: a.parameters, bindings: a.bindings,
    parameter_references: [a, b].flatMap((s, i) => s.parameter_references.map(r => ({...r, path: `/stages/${i}${r.path}`}))),
    binding_references: a.binding_references.map(r => ({...r, path: `/stages/0${r.path}`})),
    program_template: {
      stages: [
        {id: 'a', after: 'initial', imports: {}, stage_semantics_cid: machineCid(a)},
        {id: 'b', after: accepted ? 'accepted' : 'completed', imports: port ? {rows: port} : {}, stage_semantics_cid: machineCid(b)},
      ],
      exports: {out: {from: {stage: 'b', result: 'r'}}},
    },
  };
  verifyIdentity(envelope, expected_cid);
  programTests += `\n///|\ntest "program semantics: ${mode} ${accepted}" {\n  assert_program_semantics(${mode}, ${accepted}, ${JSON.stringify(canonicalText(envelope))}, ${JSON.stringify(expected_cid)})\n}\n`;
}
for (const c of vectors.cases) {
  assert.equal(c.envelope.expression_contract_cid, cid, 'stale vector expression pin');
  assert.equal(c.envelope.version, 'actql-stage-semantics/0.1');
  verifyIdentity(c.envelope, c.expected_cid);
  assert.deepEqual(Object.keys(c.envelope).sort(), ['binding_references', 'bindings', 'expression_contract_cid', 'local_body', 'parameter_references', 'parameters', 'version']);
  tests += `\n///|\ntest ${JSON.stringify('stage semantics: ' + c.name)} {\n  assert_stage_semantics(${c.empty}, ${c.stage}, ${JSON.stringify(canonicalText(c.envelope))}, ${JSON.stringify(c.expected_cid)})\n}\n`;
}
for (const [path, content] of [
  ['src/program_references/stage_expression_contract.generated.mbt', pin],
  ['src/program_references/stage_semantics.generated_test.mbt', tests],
  ['src/program_references/program_semantics.generated_test.mbt', programTests],
]) {
  const url = new URL('../' + path, import.meta.url);
  if (args[0] === '--write') writeFileSync(url, content);
  else assert.equal(readFileSync(url, 'utf8'), content, `stale generated file: ${path}`);
}
console.log(`${vectors.cases.length} stage and ${programs.cases.length} Program semantics identities verified; no executable conformance claim.`);
