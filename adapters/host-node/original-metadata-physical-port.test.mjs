// Actual compiled Scope/park/installation selector and real physical metadata
// Port. Explicit synthetic layout amounts are NOT a normal physical profile,
// complete Store funding, StoreACK/journal proof or public INFER acceptance.
import assert from 'node:assert/strict';
import {mkdtemp, mkdir, open, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import * as moon from '../../_build/js/release/build/connectors_builtin_node/connectors_builtin_node.js';
import {runtimeCore} from '../host-common/runtime-core.mjs';
import {currentResourceFixture} from './model-current-resource.fixture.mjs';
import {openContinuationEvidence} from './local-continuation-evidence.mjs';

const unavailable = {code: 'InferOriginalMetadataAcquisitionUnavailable'};
const keyId = 'sha256:' + '2'.repeat(64);
async function fixture(t, metadata = {maxWireBytes: 271, maxLedgerEntries: 0}) {
  const state = await mkdtemp(join(tmpdir(), 'actql-c-original-metadata-port-'));
  await mkdir(join(state, 'attempts'));
  const control = runtimeCore(moon).publicationControl;
  const f = await currentResourceFixture(moon, control, 'meta', {metadataAcquisition: {
    metadata, directory: {maxWireBytes: 512, maxDirectoryEntries: 4},
    retainedBytes: 7000n, workspaceBytes: 3000n,
  }});
  const park = f.operation.parkOriginalResources();
  const acquisition = f.operation.originalMetadataAcquisition(park);
  const path = join(state, 'attempts', 'model-meta.json');
  // Independent metadata layout. The request binding is supplied by the actual
  // original Owner, not expected CID bytes regenerated by the product writer.
  const ledger = {version: 'actql-local-continuation-retention/0.1',
    prepare_attempt_id: 'model-meta', request_cid: f.runDefinition.identity, key_id: keyId, holdings: []};
  const wire = JSON.stringify(ledger);
  assert.equal(Buffer.byteLength(wire), 271);
  await writeFile(path, wire);
  const evidence = openContinuationEvidence({stateDirectory: state,
    key: Buffer.alloc(32, 7), keyId, contractControl: control,
    preparation: () => ({status: 'run_created', runStatus: 'needs_reconciliation'}),
    isTerminalRunOutcome: () => false});
  t.after(async () => {
    await evidence.close();
    // No actual invalidation receipt exists. Keep the Core parked/pending
    // distinction; only disposable, unencrypted authored metadata is removed.
    if (!f.operation.cleanupPending()) await f.operation.close().catch(() => {});
    await rm(state, {recursive: true, force: true});
  });
  return {...f, state, path, ledger, evidence, acquisition, park};
}

test('original metadata Port connects actual nominal Scope to bounded read/list with no fallback', async t => {
  const f = await fixture(t);
  const value = await f.evidence.openOriginalModelState('model-meta', f.acquisition);
  assert.equal(value.requestCid, f.runDefinition.identity);
  assert.deepEqual(value.held('original_model_state'), []);
  assert.deepEqual(await f.evidence.listOriginalModelMetadata(f.acquisition), ['model-meta']);
  for (const foreign of [undefined, true, {...f.acquisition}, {current: () => true}]) {
    await assert.rejects(f.evidence.openOriginalModelState('model-meta', foreign), unavailable);
    await assert.rejects(f.evidence.listOriginalModelMetadata(foreign), unavailable);
  }
  // No foreign file is available: the actual original selector still rejects
  // this owner before filesystem lookup, not merely on a missing pathname.
  await assert.rejects(f.evidence.openOriginalModelState('model-foreign', f.acquisition), unavailable);
  assert.equal(f.sends(), 0);
});

test('original metadata Port exact bytes one-short and all retired entries are physical limits', async t => {
  const f = await fixture(t, {maxWireBytes: 270, maxLedgerEntries: 0});
  await assert.rejects(f.evidence.openOriginalModelState('model-meta', f.acquisition),
    {code: 'InvalidPublicationStoreObject'});
  // Ordinary existing reads are explicitly not this selected/funded path;
  // refusing the selected path never retries through this other entry.
  assert.equal((await f.evidence.open('model-meta')).requestCid, f.runDefinition.identity);
  assert.equal(f.sends(), 0);
  const g = await fixture(t, {maxWireBytes: 1024, maxLedgerEntries: 0});
  await writeFile(g.path, JSON.stringify({...g.ledger, holdings: [{name: 'original_model_state',
    semantic_cid: 'sha256:' + '3'.repeat(64), holding_cid: 'sha256:' + '4'.repeat(64),
    key_id: keyId, state: 'retired'}]}));
  await assert.rejects(g.evidence.openOriginalModelState('model-meta', g.acquisition),
    {code: 'ContinuationLedgerEntriesLimit'});
  assert.equal(g.sends(), 0);
});

test('original metadata Port keeps actual request/key binding separate from data shape', async t => {
  const f = await fixture(t);
  await writeFile(f.path, JSON.stringify({...f.ledger, request_cid: 'sha256:' + '5'.repeat(64)}));
  await assert.rejects(f.evidence.openOriginalModelState('model-meta', f.acquisition), unavailable);
  await writeFile(f.path, JSON.stringify({...f.ledger, key_id: 'sha256:' + '6'.repeat(64)}));
  await assert.rejects(f.evidence.openOriginalModelState('model-meta', f.acquisition),
    {code: 'PrivateEvidenceKeyMismatch'});
  assert.equal(f.sends(), 0);
});

test('original metadata Port rechecks actual Scope after a physical await', async t => {
  const f = await fixture(t);
  const probe = await open(f.path, 'r');
  const prototype = Object.getPrototypeOf(probe), stat = prototype.stat;
  await probe.close();
  let original, closing;
  t.after(() => { prototype.stat = stat; });
  prototype.stat = function(...args) {
    if (new Error().stack.includes('at readBounded ') && original === undefined) {
      original = this;
      closing = f.operation.close().catch(error => error);
    }
    return Reflect.apply(stat, this, args);
  };
  await assert.rejects(f.evidence.openOriginalModelState('model-meta', f.acquisition), unavailable);
  prototype.stat = stat;
  await closing;
  assert.equal(original.fd, -1);
  assert.equal(f.operation.cleanupPending(), true);
  assert.strictEqual(f.operation.originalResourceParkCurrent(f.park), f.park);
  assert.equal(f.sends(), 0);
});

test('original metadata Port retains same failed FD in existing queue and retries after acquisition closes', async t => {
  const f = await fixture(t);
  const probe = await open(f.path, 'r');
  const prototype = Object.getPrototypeOf(probe), stat = prototype.stat;
  await probe.close();
  let original, close, attempts = 0, rejectClose = true;
  const primary = new Error('OriginalMetadataFdClosePending');
  t.after(async () => {
    prototype.stat = stat;
    rejectClose = false;
    if (primary.cleanupHandle?.status().pending) await primary.cleanupHandle.retry();
    else if (original?.fd >= 0) await Reflect.apply(close, original, []);
  });
  prototype.stat = function(...args) {
    if (new Error().stack.includes('at readBounded ') && original === undefined) {
      original = this;
      close = this.close;
      this.close = async function() {
        attempts++;
        if (rejectClose) throw primary;
        await Reflect.apply(close, this, []);
      };
    }
    return Reflect.apply(stat, this, args);
  };
  await assert.rejects(f.evidence.openOriginalModelState('model-meta', f.acquisition), error => error === primary);
  prototype.stat = stat;
  await assert.rejects(f.evidence.listOriginalModelMetadata(f.acquisition), error => error === primary);
  await assert.rejects(f.evidence.close(), error => error === primary);
  assert.equal(attempts, 2);
  assert(original.fd >= 0);
  await assert.rejects(f.operation.close(), {code: 'MoonBitHostFailure'});
  await assert.rejects(f.evidence.openOriginalModelState('model-meta', f.acquisition), unavailable);
  rejectClose = false;
  // Cleanup requires the same retained FD, not a new acquisition or InferAllow.
  await f.evidence.close();
  assert.equal(original.fd, -1);
  assert.equal(attempts, 3);
  await f.evidence.close();
  assert.equal(attempts, 3);
  assert.strictEqual(f.operation.originalResourceParkCurrent(f.park), f.park);
  assert.equal(f.sends(), 0);
});
