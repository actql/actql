import assert from 'node:assert/strict';
import test from 'node:test';
import {pathToFileURL} from 'node:url';
import {checked} from '../host-common/runtime-result.mjs';
import {mockChurnRiskCatalogue} from './mock-churn-risk-catalogue.mjs';

assert.ok(process.env.ACTQL_TEST_MOCK_CATALOGUE_COMMON_RUNTIME,
  'Select the actual matching Common runtime');
const moon = await import(pathToFileURL(process.env.ACTQL_TEST_MOCK_CATALOGUE_COMMON_RUNTIME));

test('actual Common owns both mock Relation declarations and exact original key facts', () => {
  for (const entry of mockChurnRiskCatalogue) {
    const declaration = checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
      entry.connectorId, entry.registration, entry.revision,
      JSON.stringify({views: entry.views}), undefined));
    const projected = JSON.parse(moon.clientProgramRowSourceDeclarationJson(declaration));
    assert.equal(projected.connector_id, entry.connectorId);
    assert.equal(projected.views.length, 1);
    const view = projected.views[0];
    assert.equal(view.resource, entry.views[0].resource);
    assert.equal(view.source_ref, 'connector://' + entry.connectorId + '/' + view.resource + '#records');
    // Complete Catalog/contract material is generated by Common. The static
    // asset does not supply a Catalog CID, Host identity or authority.
    assert.match(projected.catalog_cid, /^sha256:[0-9a-f]{64}$/u);
    assert.ok(JSON.stringify(projected).includes(entry.views[0].schema_cid));
    assert.ok(JSON.stringify(projected).includes('candidate_keys'));
  }
});

test('actual Common refuses a changed mock schema under the retained original pin', () => {
  for (const entry of mockChurnRiskCatalogue) {
    const altered = {...entry.views[0], schema_wire: '{}'};
    assert.throws(() => checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
      entry.connectorId, entry.registration, entry.revision,
      JSON.stringify({views: [altered]}), undefined)), {code: 'MoonBitHostFailure'});
  }
});
