import assert from 'node:assert/strict';
import test from 'node:test';
import {pathToFileURL} from 'node:url';
import {checked} from '../host-common/runtime-result.mjs';
import {mockChurnRiskCatalogue} from './mock-churn-risk-catalogue.mjs';

assert.ok(process.env.ACTQL_TEST_MOCK_CATALOGUE_COMMON_RUNTIME,
  'Select the actual matching Common runtime');
const moon = await import(pathToFileURL(process.env.ACTQL_TEST_MOCK_CATALOGUE_COMMON_RUNTIME));

test('actual Common owns both mock Relation declarations and exact original key facts', () => {
  for (const entry of mockChurnRiskCatalogue) {
    const declaration = checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
      entry.connectorId, entry.registration, entry.revision,
      JSON.stringify({views: entry.views}), undefined));
    const projected = JSON.parse(moon.clientProgramRowSourceDeclarationJson(declaration));
    assert.equal(projected.connector_id, entry.connectorId);
    assert.equal(projected.views.length, 1);
    const view = projected.views[0];
    assert.equal(view.resource, entry.views[0].resource);
    assert.equal(view.source_ref, 'connector://' + entry.connectorId + '/' + view.resource + '#records');
    // Complete Catalog/contract material is generated by Common. The static
    // asset does not supply a Catalog CID, Host identity or authority.
    assert.match(projected.catalog_cid, /^sha256:[0-9a-f]{64}$/u);
    const contracts = projected.contracts.map(wire => JSON.parse(wire));
    const carrier = contracts.find(contract => contract.kind === 'carrier_schema');
    assert.equal(carrier.cid, view.carrier_schema_cid);
    assert.deepEqual(carrier.body.fields, JSON.parse(entry.views[0].schema_wire));
    const facts = contracts.find(contract => contract.kind === 'carrier_facts');
    assert.deepEqual(facts.body, JSON.parse(entry.views[0].facts_wire));
  }
});

test('actual Common refuses a changed mock schema under the retained original pin', () => {
  for (const entry of mockChurnRiskCatalogue) {
    const altered = {...entry.views[0], schema_wire: '{}'};
    assert.throws(() => checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
      entry.connectorId, entry.registration, entry.revision,
      JSON.stringify({views: [altered]}), undefined)), {code: 'MoonBitHostFailure'});
  }
});

test('actual Common retains its registration identifier and revision-prefix rules', () => {
  for (const entry of mockChurnRiskCatalogue) {
    for (const [registration, revision] of [
      ['mock.' + entry.connection, 'mock'], [entry.registration, 'foreign/0.1'],
    ]) {
      assert.throws(() => checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
        entry.connectorId, registration, revision,
        JSON.stringify({views: entry.views}), undefined)), {code: 'MoonBitHostFailure'});
    }
  }
});

test('actual Common derives the required UPDATE from the same original Account declaration', () => {
  const entry = mockChurnRiskCatalogue[0];
  const declaration = checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
    entry.connectorId, entry.registration, entry.revision,
    JSON.stringify({views: entry.views}), undefined));
  const declared = JSON.parse(moon.clientProgramRowSourceDeclarationJson(declaration));
  const mapping = JSON.parse(checked(moon.clientProgramMockChurnRiskUpdateMapping(declaration)));
  assert.equal(mapping.target_ref, 'connector://salesforce/Account');
  assert.equal(mapping.connector_manifest_cid, declared.manifest_entry_cid);
  assert.equal(mapping.primary_identity, 'id');
  assert.equal(mapping.minimum_approval, 'required');
  assert.deepEqual(mapping.writable_fields, ['Churn_Risk__c', 'Risk_Reason__c']);
  assert.deepEqual(mapping.permission_rules, [{effect_kind: 'update', selector_class: 'id',
    write_fields: ['Churn_Risk__c', 'Risk_Reason__c'], permissions: ['salesforce:record:update']}]);
  assert.deepEqual(mapping.row_mapping, {
    Churn_Risk__c: {field: 'Churn_Risk__c', null_behavior: 'reject'},
    Risk_Reason__c: {field: 'Risk_Reason__c', null_behavior: 'reject'},
  });
});

test('actual mock UPDATE refuses another generation or the warehouse original', () => {
  const [entry, warehouse] = mockChurnRiskCatalogue;
  for (const selected of [
    {...entry, registration: 'foreign', revision: 'foreign/0.1'}, warehouse,
  ]) {
    const declaration = checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
      selected.connectorId, selected.registration, selected.revision,
      JSON.stringify({views: selected.views}), undefined));
    assert.throws(() => checked(moon.clientProgramMockChurnRiskUpdateMapping(declaration)),
      {code: 'MoonBitHostFailure'});
  }
});

test('actual mock UPDATE refuses a different original candidate key', () => {
  const entry = mockChurnRiskCatalogue[0];
  const declaration = checked(moon.clientProgramRowSourceRestoreRelationDeclaration(
    entry.connectorId, entry.registration, entry.revision,
    JSON.stringify({views: [{...entry.views[0],
      facts_wire: '{"relation_keys":{"candidate_keys":[["name"]]}}'}]}), undefined));
  assert.throws(() => checked(moon.clientProgramMockChurnRiskUpdateMapping(declaration)),
    {code: 'MoonBitHostFailure'});
});
