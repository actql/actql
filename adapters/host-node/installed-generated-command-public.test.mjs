// Required public integration: the submitted Program generates the exact
// approved Content. The Source fixture's preissued Ref is not a substitute.
import assert from 'node:assert/strict';
import {generateKeyPairSync, sign} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {inspect} from 'node:util';
import {setTimeout as delay} from 'node:timers/promises';
import test from 'node:test';
import {createOwnedScratch} from '../../scripts/owned-scratch.mjs';
import {createGeneratedContentFixture} from './fixtures/generated-content.fixture.mjs';
import {generatedContentCommandProgram, generatedContentCommandSource} from './fixtures/content-command.fixture.mjs';
import {openContentCommandHost} from './fixtures/content-command-host.fixture.mjs';

for (const entrance of ['Local', 'HTTPS']) {
for (const format of ['program', 'sql', 'text']) {
for (const preserveOrder of [false, true]) {
test(`public ${entrance} ${format} generated SERIALIZE ${preserveOrder ? 'PRESERVE ORDER' : 'ORDER BY'} COMMAND approves and physically stores original generated bytes`, async t => {
  const scratch = await createOwnedScratch({parent: new URL('../../_build/', import.meta.url).pathname,
    prefix: 'generated-command-', label: 'Generated Content Command integration'});
  const sourceContent = await createGeneratedContentFixture(t);
  await sourceContent.store.commitPhysicalHolding(sourceContent.holding, [sourceContent.physical.prepared]);
  await sourceContent.issue();
  const keys = generateKeyPairSync('ed25519');
  const events = [];
  const host = await openContentCommandHost({scratch, generated: sourceContent, keys, entrance,
    generatedCommand: true,
    faultInjection: (event, facts) => events.push({event, facts})}).catch(error => {
      t.diagnostic(inspect(error.primaryFailure ?? error.cause ?? error, {depth: 8}));
      throw error;
    });
  t.after(host.close);
  const program = format !== 'program' ? generatedContentCommandSource({preserveOrder, format})
    : generatedContentCommandProgram({preserveOrder});
  const sourceFormat = format === 'text' ? 'aql-text' : format;
  if (preserveOrder) {
    const unordered = generatedContentCommandProgram({preserveOrder: true});
    // The original Stage Result has a checked publication order. To test an
    // unproved order, serialize the Source directly, without that producer
    // boundary or an authored sort. Actual sample cardinality is not evidence.
    unordered.stages[1].inputs = unordered.stages[0].inputs;
    unordered.stages[1].steps.splice(2, 1);
    unordered.stages.splice(0, 1);
    const refused = await host.client.check(unordered, {kind: 'program', scope: 'bound_input'});
    assert.notEqual(refused.report.verdict, 'verified',
      'one actual Source row is not a static order witness');
    assert.equal(host.reads(), 0);
    assert.equal(host.sends(), 0);
  }
  const report = await host.client.check(program, format !== 'program'
    ? {kind: 'text', format: sourceFormat, scope: 'bound_input'} : {kind: 'program', scope: 'bound_input'});
  assert.equal(report.report.verdict, 'verified', inspect(report, {depth: 12}));
  assert.equal(host.reads(), 0);
  assert.equal(host.sends(), 0);
  const run = await (format !== 'program' ? host.client.startSource(program, {format: sourceFormat})
    : host.client.start(program)).catch(error => {
      t.diagnostic(inspect({error, events, observations: host.events,
        reads: host.reads(), sends: host.sends()}, {depth: 16}));
      throw error;
    });
  const status = await run.wait({signal: AbortSignal.timeout(15000)});
  assert.equal(status.status, 'waiting_checkpoint', inspect({status, events,
    reads: host.reads(), sends: host.sends(), observations: host.events}, {depth: 16}));
  assert.equal(host.reads(), 1, 'the original admitted Source is acquired once');
  assert.equal(host.sends(), 0);
  await assert.rejects(readFile(host.targetPath), {code: 'ENOENT'});
  const checkpoints = await host.client.checkpoints();
  assert.equal(checkpoints.items.filter(item => item.kind === 'effect_set').length, 1);
  const checkpoint = checkpoints.items.find(item => item.kind === 'effect_set');
  const resolution = await host.client.resolveCheckpoints([{checkpoint, decision: 'approved'}],
    {signer: {keyId: 'reviewer', reviewerId: 'reviewer', authorityScopeCid: run.ref.authorityScopeCid,
      sign: bytes => sign(null, bytes, keys.privateKey)}});
  assert.equal(resolution.results[0].status, 'committed');
  const signal = AbortSignal.timeout(15000);
  let final;
  do {
    final = await run.status({signal});
    if (!['resuming', 'running', 'waiting_checkpoint'].includes(final.status)) break;
    await delay(20, undefined, {signal});
  } while (true);
  assert.equal(final.status, 'succeeded', inspect({final, events, observations: host.events}, {depth: 16}));
  assert.deepEqual(await readFile(host.targetPath), Buffer.from('name\n"approved.csv"\n'));
  const rows = await run.result('r').all();
  assert.equal(rows.length, 1);
  assert.equal(rows[0].name, 'approved.csv');
  assert.equal(rows[0].content.metadata.content_cid,
    'sha256:11af3859185fd4b8e2cef2ba824fdddf63b8a6fbfa26aea783660fefda5459de');
  assert.notEqual(rows[0].content.content_ref_cid,
    JSON.parse(sourceContent.description.wire).content_ref_cid,
    'the submitted Program generated Content rather than reusing the Source Ref');
  const receipt = JSON.parse(await readFile(join(scratch.path, 'receiver-receipt.json'), 'utf8'));
  assert.equal(receipt.content_cid, rows[0].content.metadata.content_cid);
  assert.equal(host.sends(), 1);
  assert.equal(host.reads(), 1);
  await host.close();
  await sourceContent.store.retirePhysicalHolding(sourceContent.holding.holding_cid);
  scratch.passed();
});
}
}
}
