import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import test from 'node:test';
import {admitDispatchJson, pollCancelJson} from './index.mjs';

// Fixed contract preimages, not expectations generated from this issuer.
const vectors = JSON.parse(readFileSync(new URL('../../spec/fixtures/remote-site-wire-vectors.json', import.meta.url))).vectors;
const dispatch = vectors.find(value => value.name === 'dispatch');
const cancel = vectors.find(value => value.name === 'poll_cancel');

test('public Cancel issuer preserves the exact dispatch and fixed wire', () => {
  const request = admitDispatchJson(dispatch.canonical, dispatch.cid);
  const body = pollCancelJson(request);
  assert.equal(body, cancel.canonical);
  assert.equal('sha256:' + createHash('sha256').update(body).digest('hex'), cancel.cid);
  const wire = JSON.parse(body);
  assert.equal(wire.request_json, dispatch.canonical);
  assert.equal(wire.dispatch_request_cid, dispatch.cid);
  assert.deepEqual(Object.keys(wire), ['dispatch_request_cid', 'request_json', 'version']);
});

// Independent states, not outputs generated by the projection under test.
for (const [name, state, expected] of [
  ['unknown execution', [6, 0, 2, 0, 0], false],
  ['pending cleanup', [5, 0, 1, 0, 0], false],
  ['retained holding', [3, 1, 0, 1, 0], false],
  ['quarantine', [6, 0, 4, 0, 1], false],
  ['recovered after loss', [3, 0, 5, 0, 0], false],
  ['success wins cancellation', [3, 0, 2, 0, 0], true],
  ['failure released', [4, 0, 2, 0, 0], true],
  ['cancellation released', [5, 0, 2, 0, 0], true],
]) {
  test(`public Cancel retirement projection: ${name}`, async () => {
    const core = await import('./index.mjs');
    const request = core.admitDispatchJson(dispatch.canonical, dispatch.cid);
    const journal = core.createJournal('coordinator-a');
    const admission = core.prepareIntent(journal, request);
    const durable = core.admitDurableJson(core.admissionDurableJson(admission));
    const record = core.commitIntent(admission);
    assert.equal(core.canRetireCancellationDelivery(record), false);
    const response = core.admitResponseJson(JSON.stringify({
      version: 'actql-remote-dispatch-response/0.1',
      dispatch_request_cid: dispatch.cid, revision: 1, state,
    }), request, false);
    const transition = core.prepareResponseObservation(record, response);
    const persisted = core.responseDurableJson(durable, transition, response);
    assert.equal(core.canRetireCancellationDelivery(record), false,
      'prepared observation is not a committed retirement decision');
    core.commitTransition(transition);
    assert.equal(core.canRetireCancellationDelivery(record), expected);
    const restored = core.restoreDurable(core.createJournal('coordinator-a'),
      core.admitDurableJson(persisted));
    assert.equal(core.canRetireCancellationDelivery(restored), expected);
    const replay = core.prepareResponseObservation(restored, response);
    assert.equal(core.transitionIsReplay(replay), true);
    core.commitTransition(replay);
    assert.equal(core.canRetireCancellationDelivery(restored), expected);
  });
}
